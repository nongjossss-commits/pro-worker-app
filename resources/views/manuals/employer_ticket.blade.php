{{-- User Manual: Employer Ticket (ฝั่งนายจ้าง) --}}

<h4><i class="bi bi-envelope-paper-fill me-2"></i>เมนูนี้คืออะไร?</h4>
<p>
    เมนู <strong>"แจ้งปัญหา / ส่งคำขอ (Employer Ticket)"</strong> สำหรับ<strong>นายจ้าง</strong>
    (role <span class="manual-role">Employer</span>) ใช้แจ้งปัญหา/ส่งคำขอไปยังสำนักงาน
    เช่น ขอใบรับรองการจ้างงาน, แจ้งลูกจ้างขาดงาน, ขอเปลี่ยนข้อมูล
</p>

<h4><i class="bi bi-person-check me-2"></i>ใครเข้าได้?</h4>
<ul>
    <li><span class="manual-role">Employer</span> — สร้าง + ดู ticket ของตัวเองได้</li>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — ดูได้ + ตอบได้ (ผ่าน Ticket Inbox)</li>
</ul>

<h4><i class="bi bi-list-check me-2"></i>ขั้นตอนใช้งาน (ฝั่งนายจ้าง)</h4>

<h5>สร้าง Ticket ใหม่</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>กด "+ ส่งคำขอใหม่"</li>
        <li>เลือกประเภท (ขอใบรับรอง, แจ้งปัญหา, ฯลฯ)</li>
        <li>พิมพ์รายละเอียด</li>
        <li>แนบไฟล์/รูปถ่ายได้</li>
        <li>กด "ส่ง" — สำนักงานจะได้รับและตอบกลับใน Ticket Inbox</li>
    </ol>
</div>

<h5>ติดตามสถานะ</h5>
<div class="manual-step">
    รายการ ticket แสดงสถานะ "รอตอบ", "กำลังดำเนินการ", "ปิดแล้ว"
    คลิกที่ ticket เพื่อดูข้อความตอบจากสำนักงาน
</div>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>

<div class="manual-tip">
    <strong>แนบรูป/เอกสาร:</strong> ทำให้ปัญหาเข้าใจง่ายขึ้น — เจ้าหน้าที่จะตอบได้แม่นยำ
</div>
