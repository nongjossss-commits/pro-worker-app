{{-- User Manual: Incomplete Data --}}

<h4><i class="bi bi-exclamation-diamond-fill me-2"></i>เมนูนี้คืออะไร?</h4>
<p>
    เมนู <strong>"ข้อมูลไม่ครบ (Incomplete Data)"</strong> รวบรวม<strong>นายจ้าง/ลูกจ้าง</strong>
    ที่ข้อมูลในระบบ<strong>ยังไม่ครบ</strong> เช่น ไม่มีเลขผู้เสียภาษี, ไม่มีรูปถ่าย, ไม่มีพาสปอร์ต
    เพื่อให้สำนักงานเห็นและไปกรอกให้ครบ
</p>

<h4><i class="bi bi-person-check me-2"></i>ใครเข้าได้?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — เข้าได้ (ต้องมีสิทธิ์ <code>manage-tickets</code>)</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>หน้าตาของหน้านี้</h4>
<ol>
    <li><strong>แถบประเภท</strong> — Employers / Employees</li>
    <li><strong>ตาราง</strong> — แสดง record ที่ขาดข้อมูล + ระบุว่าขาดอะไรบ้าง</li>
    <li><strong>ปุ่มแก้ไข</strong> — คลิกไปกรอกข้อมูลให้ครบ</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>ขั้นตอนใช้งาน</h4>

<h5>แก้ข้อมูลที่ขาด</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>เลือกประเภท (Employers/Employees)</li>
        <li>กดที่ record ในตาราง — ระบบบอกว่าขาดอะไรบ้าง (เช่น "ขาด: เลขผู้เสียภาษี, รูปถ่าย")</li>
        <li>กด "แก้ไข" → ระบบพาไปหน้าแก้ไขของ record นั้น</li>
        <li>กรอกข้อมูลให้ครบ → บันทึก</li>
        <li>เมื่อกลับมา record จะ<strong>หายจากรายการ "ข้อมูลไม่ครบ"</strong></li>
    </ol>
</div>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>

<div class="manual-tip">
    <strong>ตรวจทุกสัปดาห์:</strong> เมนูนี้ช่วยให้ระบบมีข้อมูลครบถ้วน — ทำงานต่อเนื่องไม่สะดุดเพราะข้อมูลขาด
</div>

<div class="manual-tip">
    <strong>ก่อนสร้างใบกำกับภาษี:</strong> เช็คเมนูนี้ก่อน — ถ้านายจ้างไม่มีเลขผู้เสียภาษี ออกใบกำกับไม่ได้
</div>
