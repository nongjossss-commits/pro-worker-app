{{-- User Manual: Registration Resolution (มติลงทะเบียน) --}}

<h4><i class="bi bi-file-earmark-text-fill me-2"></i>เมนูนี้คืออะไร?</h4>
<p>
    เมนู <strong>"มติลงทะเบียน (Registration Resolution)"</strong> ใช้สำหรับจัดการ
    <strong>มติ ครม.</strong> เกี่ยวกับการลงทะเบียนแรงงานต่างด้าวรอบใหม่ที่รัฐบาลออกมาเป็นระยะๆ
    ระบบจะจัดเก็บแบบฟอร์ม, ระยะเวลา, และลูกจ้างที่จะเข้าระบบมตินั้น
</p>

<h4><i class="bi bi-person-check me-2"></i>ใครเข้าเมนูนี้ได้?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — เข้าได้เต็มที่</li>
    <li><span class="manual-role">Caretaker</span> — ทำงานประจำวันได้ (ข้อมูลลูกจ้าง, นัดหมาย) · ติ๊กขั้นตอนได้เมื่อได้รับสิทธิ์ "อัปเดตขั้นตอนความคืบหน้า"</li>
    <li><span class="manual-role">Employer</span> (บัญชีลูกค้า) — เข้าเมนูนี้ไม่ได้</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>หน้าตาของหน้านี้</h4>
<ol>
    <li><strong>แถบมติ (Tabs)</strong> — แต่ละแถบคือ 1 มติ ครม. (เช่น มติ พ.ย. 2566, มติ มี.ค. 2567)</li>
    <li><strong>การ์ดนายจ้าง</strong> — แสดงนายจ้างที่มีลูกจ้างอยู่ในมตินี้</li>
    <li><strong>ตัวกรองสถานะ</strong> — กรองตามขั้นตอน (รอ, กำลังทำ, เสร็จ)</li>
    <li><strong>ตัวกรองความคืบหน้า</strong> — กรองตาม visa-only / both / renewal</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>ขั้นตอนใช้งาน</h4>

<h5>1. เลือกมติที่ต้องการ</h5>
<div class="manual-step">
    คลิกที่แถบ tab ของมตินั้น → จะแสดงนายจ้าง + ลูกจ้างทั้งหมดที่อยู่ในมตินั้น
</div>

<h5>2. ลงทะเบียนลูกจ้างเข้ามติ</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>เปิดการ์ดนายจ้าง</li>
        <li>กดปุ่ม "เพิ่มลูกจ้างเข้ามติ"</li>
        <li>เลือกลูกจ้างที่จะเข้ามตินี้</li>
        <li>กด "ยืนยัน"</li>
    </ol>
</div>

<h5>3. ติดตามสถานะลูกจ้างแต่ละคน</h5>
<div class="manual-step">
    การ์ดลูกจ้างแสดง:
    <ul class="mb-0">
        <li>สีฟ้า = visa only (ทำเฉพาะ visa)</li>
        <li>สีฟ้าเข้ม = both (ทำทั้ง visa + work permit)</li>
        <li>กรอบทึบ = ขั้นตอนสูงสุดที่ทำแล้ว</li>
    </ul>
</div>

<h5>4. กรองด้วยตัวกรองหลายชุด</h5>
<div class="manual-step">
    เลือกหลายสถานะพร้อมกันด้วยการกด Ctrl/Cmd ค้าง — กรองหลายความคืบหน้าได้ในครั้งเดียว
</div>

<h5>5. Auto Settings — ตั้งค่าแยกแต่ละแถบมติ (Per-tab)</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>เปิดแถบมติที่ต้องการ → กดปุ่ม <strong>"Auto Settings"</strong></li>
        <li>หัว popup จะแสดง<strong>ชื่อแถบ</strong> + เตือนว่าใช้กับแถบนี้เท่านั้น</li>
        <li>กรอก Auto WP/Visa Expiry + MOU Group → Save</li>
        <li>แต่ละแถบมี Auto Settings ของตัวเอง ไม่ทับซ้อนกัน</li>
    </ol>
</div>

<h5>6. Auto-pull ลูกจ้างเข้าเมนูอัตโนมัติ (Add-only)</h5>
<div class="manual-step">
    ลูกจ้างที่มี WP หรือ Visa หมดอายุตรงกับ Auto Settings → <strong>auto-pull เข้าเมนูทันที</strong>
    <br>
    ลูกจ้างที่อยู่ในเมนูแล้ว <strong>ไม่ถูกดีดออก</strong>เมื่ออัพเดทวันที่ — สีจะเปลี่ยนตาม progress (none / visa_only / work_permit_only / both)
    <br>
    เฉพาะการกดเสร็จสิ้น / ยกเลิก manual เท่านั้นที่จะเอาลูกจ้างออกจากเมนู
</div>

<h5>7. เลือกลูกจ้างที่ทำเสร็จแล้ว และ Select All แบบ 3 ทาง</h5>
<div class="manual-step">
    Checkbox ของลูกจ้างที่กดเสร็จแล้วจะซ่อนระหว่างช่วง Undo 24 ชม. และกลับมาให้เลือกได้หลังพ้นช่วงนั้น ·
    กด Select All ของนายจ้างที่มีทั้งคนเสร็จและยังไม่เสร็จ ระบบจะถามว่าจะเลือก <strong>ทั้งหมด / เฉพาะที่เสร็จ / เฉพาะที่ยังไม่เสร็จ</strong>
    (ใช้กับ ส่งออก / แก้ไขหลายคน / ดาวน์โหลด)
</div>

<h5>8. จัดทีม</h5>
<div class="manual-step">
    ปุ่ม <strong>จัดทีม</strong> บนการ์ดลูกจ้าง → เลือกหรือสร้างทีม (เช่น "ชุดที่ 1") · ทีมแยกตามแถบมติและตามนายจ้าง
    ชื่อทีมของนายจ้างหนึ่งไม่ปนกับนายจ้างอื่น · แก้ชื่อ/ลบทีมได้ ปุ่มอัปเดตทันทีไม่ต้องรีโหลด
</div>

<h5>9. นัดหมายและเลขคำขอแยกตามแถบ</h5>
<div class="manual-step">
    วันนัด / สถานที่นัด / เลขคำขอ ของลูกจ้างเก็บ<strong>แยกตามแถบมติ</strong> — ตั้งค่าในแถบหนึ่งไม่ไปโผล่ในอีกแถบหรืออีกเมนู
</div>

<h5>10. ป้ายแจ้งเตือนของแถบ (Super Admin)</h5>
<div class="manual-step">
    ปุ่มเปิด/ปิดป้ายข้างปุ่มแก้ไขแถบ — ใช้กับแถบที่เตรียมไว้ล่วงหน้าแต่ยังไม่เริ่มจริง ลูกจ้างในแถบยังทำงานได้ปกติ
    แต่จะไม่แสดงป้าย "อยู่ในกลุ่มมติ..." บนการ์ดและไม่นับในป้ายแจ้งเตือน จะได้ไม่สับสนกับรอบที่กำลังทำอยู่
</div>

<h5>11. ย้ายไฟล์แนบของลูกจ้างหลายคน (Super Admin)</h5>
<div class="manual-step">
    เลือกลูกจ้างด้วย checkbox → เครื่องมือ <strong>ย้ายไฟล์แนบ</strong> → เลือกช่องต้นทาง/ปลายทาง และวิธี: สลับ / ย้ายแล้วลบต้นทาง / <strong>รวมเข้าช่อง B</strong> (รวมหน้า PDF ของทั้ง 2 ไฟล์)
    มีผลเฉพาะลูกจ้างที่เลือกเท่านั้น (Super Admin มอบสิทธิ์นี้ให้ Admin/Staff บางคนได้)
</div>

<h5>12. ลบแถบมติที่มีการวางบิลแล้ว</h5>
<div class="manual-step">
    กดลบแถบ = ซ่อนแถบไว้ 7 วัน (กู้คืนได้) แล้วลบถาวร · งานที่<strong>มีบิลแล้ว</strong>จะไม่ถูกลบ บิลและประวัติการชำระเงินยังอยู่ครบ
    เปิดดู เก็บเงินต่อ หรือออกใบลดหนี้ได้ในเมนูการเงิน (มีป้ายสีแดง "แถบถูกลบแล้ว")
</div>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>

<div class="manual-tip">
    <strong>สีของป้ายความคืบหน้า:</strong> ระบบใช้สี 4 ระดับเพื่อให้เห็นง่ายว่าลูกจ้างคนไหนอยู่ขั้นตอนไหน
</div>

<div class="manual-tip">
    <strong>ตัวกรองสถานะแสดงเฉพาะที่ตรง:</strong> ถ้ากรอง "Visa only" จะเห็นเฉพาะนายจ้างที่มีลูกจ้างทำ visa เท่านั้น
</div>
<div class="manual-tip">
    <strong>ส่งข้อมูลไปแชท LINE:</strong> ลากปุ่ม <i class="bi bi-grid-3x2-gap-fill"></i> บนการ์ดไปวางในแชท หรือคลิกเพื่อคัดลอกข้อความ / รูปการ์ด / แชร์ — ดูรายละเอียดที่คู่มือเมนูลูกจ้าง ข้อ 11
</div>

<h4><i class="bi bi-question-circle me-2"></i>คำถามที่พบบ่อย</h4>
<dl>
    <dt>Q: เพิ่มมติใหม่ได้ไหม?</dt>
    <dd>A: Super Admin กดปุ่ม <strong>+ เพิ่มแถบ</strong> บนแถบมติ</dd>

    <dt>Q: ลูกจ้างในมติลงทะเบียนไปโผล่ในมติต่ออายุด้วย?</dt>
    <dd>A: ถูกต้อง — ถ้าวันหมดอายุตรงกับวันเป้าหมายของแถบต่ออายุ ลูกจ้างจะแสดงคู่ในแถบต่ออายุด้วย โดยข้อมูลในมติลงทะเบียนไม่เปลี่ยน</dd>

    <dt>Q: ลูกจ้างคนหนึ่งอยู่ได้หลายมติไหม?</dt>
    <dd>A: ได้ — ลูกจ้าง 1 คนสามารถเข้าได้หลายมติ แสดงในการ์ดของทุกมติที่เข้าร่วม</dd>

    <dt>Q: ทำไมการ์ดนายจ้างหายไป?</dt>
    <dd>A: ถ้านายจ้างคนนั้นไม่มีลูกจ้างใน scope ตัวกรองปัจจุบัน การ์ดจะไม่แสดง</dd>
</dl>
