<h4><i class="bi bi-exclamation-diamond-fill me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"အချက်အလက် မပြည့်စုံ (Incomplete Data)"</strong> မီနူးသည် စနစ်ရှိ ဒေတာ
    <strong>တစ်စုံတစ်ရာ ချို့တဲ့နေဆဲ</strong> ဖြစ်သော <strong>အလုပ်ရှင်/ဝန်ထမ်းများ</strong>ကို စုစည်းသည် — ဥပမာ- အခွန် ID မရှိ၊ ဓာတ်ပုံမရှိ၊ နိုင်ငံကူးလက်မှတ် မရှိ —
    ရုံးက ၎င်းတို့ကို မြင်ပြီး ချို့တဲ့နေသောအရာများကို ဖြည့်စွက်နိုင်ရန်
</p>

<h4><i class="bi bi-person-check me-2"></i>မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — ဝင်ရောက်နိုင်သည် (<code>manage-tickets</code> ခွင့်ပြုချက် လိုအပ်သည်)</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာ ဘယ်လိုပုံစံရှိသနည်း</h4>
<ol>
    <li><strong>အမျိုးအစား တဘ်များ</strong> — အလုပ်ရှင် / ဝန်ထမ်း</li>
    <li><strong>ဇယား</strong> — ဒေတာချို့တဲ့နေသော မှတ်တမ်းများ + အတိအကျ ချို့တဲ့နေသောအရာကို ပြသသည်</li>
    <li><strong>ပြင်ဆင်ရန် ခလုတ်</strong> — ချို့တဲ့နေသော ဒေတာကို ဖြည့်ရန် နှိပ်ပါ</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>အသုံးပြုနည်း</h4>

<h5>ချို့တဲ့နေသော ဒေတာကို ပြင်ဆင်ရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>အမျိုးအစား ရွေးပါ (အလုပ်ရှင်/ဝန်ထမ်း)</li>
        <li>ဇယားရှိ မှတ်တမ်းကို နှိပ်ပါ — စနစ်သည် ချို့တဲ့နေသောအရာကို ပြောပြပါလိမ့်မည် (ဥပမာ- "ချို့တဲ့နေသည်: အခွန် ID၊ ဓာတ်ပုံ")</li>
        <li>"ပြင်ဆင်ရန်" ကို နှိပ်ပါ → စနစ်သည် ထိုမှတ်တမ်း၏ ပြင်ဆင်ရေး စာမျက်နှာသို့ ပို့ဆောင်ပါလိမ့်မည်</li>
        <li>ချို့တဲ့နေသော ဒေတာကို ဖြည့်ပါ → သိမ်းမည်</li>
        <li>ပြန်သွားသောအခါ မှတ်တမ်းသည် <strong>"အချက်အလက် မပြည့်စုံ" စာရင်းမှ ပျောက်ဆုံးသွားပါလိမ့်မည်</strong></li>
    </ol>
</div>

<h4><i class="bi bi-lightbulb me-2"></i>အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>အပတ်စဉ် စစ်ဆေးပါ:</strong> ဤမီနူးသည် စနစ်၏ ဒေတာအားလုံးကို ပြည့်စုံအောင် ထိန်းသိမ်းပေးသည် — ဒေတာချို့တဲ့မှုကြောင့် နေ့စဉ်လုပ်ငန်း မထိခိုက်စေရန်
</div>

<div class="manual-tip">
    <strong>အခွန်ဘေဂျင် မဖန်တီးမီ:</strong> ဤမီနူးကို အရင်စစ်ဆေးပါ — အလုပ်ရှင်တွင် အခွန် ID မရှိပါက ဘေဂျင် ထုတ်၍မရပါ
</div>
