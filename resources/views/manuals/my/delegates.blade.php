<h4><i class="bi bi-people me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"ကိုယ်စားလှယ်များ (Delegates)"</strong> မီနူးသည်
    ကျွန်ုပ်တို့ ရုံးနှင့် ဆက်သွယ်ရန် <strong>အလုပ်ရှင်က ခန့်အပ်သော</strong> ပုဂ္ဂိုလ်များ၏ အချက်အလက်ကို သိမ်းဆည်းသည် —
    ဥပမာ- ဖောက်သည်ကုမ္ပဏီ၏ HR ဝန်ထမ်း၊ အတွင်းရေးမှူး၊ သို့မဟုတ် နေရာတွင် အလုပ်သမားများကို စီမံသော ကြီးကြပ်ရေးမှူး
</p>
<p>
    <strong>အရေးကြီးသောမှတ်ချက်:</strong> အချို့ အခန်းကဏ္ဍများ၏ ဘယ်ဘက်မီနူးတွင် "ဝန်ထမ်းအချက်အလက်" ဟု ခေါ်ဆိုနိုင်သော်လည်း
    ၎င်းသည် ဤ Delegates မီနူးပင် ဖြစ်သည် — <strong>ရွှေ့ပြောင်းအလုပ်သမား မဟုတ်ပါ</strong>
</p>

<h4><i class="bi bi-person-check me-2"></i>ဤမီနူးကို မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — ဝင်ရောက်နိုင်သည်</li>
    <li><span class="manual-role">Caretaker</span> — ကြည့်ရှုရုံသာ</li>
    <li><span class="manual-role">Employer</span> — မိမိ၏ ကိုယ်စားလှယ်များကိုသာ ကြည့်ရှုနိုင်သည်</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာ ဘယ်လိုပုံစံရှိသနည်း</h4>
<ol>
    <li><strong>ကိုယ်စားလှယ် ဇယား</strong> — အမည်၊ ချိတ်ဆက်ထားသော အလုပ်ရှင်၊ ရာထူး၊ ဖုန်းနံပါတ်၊ အီးမေးလ်</li>
    <li><strong>"+ ကိုယ်စားလှယ်အသစ် ထည့်ရန်"</strong> ခလုတ် — ကိုယ်စားလှယ် ဖန်တီးရန်</li>
    <li><strong>စစ်ထုတ်ရန်</strong> — အလုပ်ရှင်ဖြင့် စစ်ထုတ်ပြီး အမည်/ဖုန်းနံပါတ်ဖြင့် ရှာနိုင်သည်</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>အသုံးပြုနည်း</h4>

<h5>၁။ ကိုယ်စားလှယ်အသစ် ထည့်ရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>"+ ကိုယ်စားလှယ်အသစ် ထည့်ရန်" ကို နှိပ်ပါ</li>
        <li>အလုပ်ရှင် ရွေးပါ</li>
        <li>အမည်အပြည့်အစုံ၊ ရာထူး၊ ဖုန်းနံပါတ်၊ အီးမေးလ်၊ လိပ်စာ ဖြည့်ပါ</li>
        <li>ရရှိနိုင်ပါက ID ကတ်မိတ္တူ တင်ပါ</li>
        <li>"သိမ်းမည်" ကို နှိပ်ပါ</li>
    </ol>
</div>

<h5>၂။ အချက်အလက် ပြင်ဆင်ရန်</h5>
<div class="manual-step">
    ဇယားရှိ ကိုယ်စားလှယ်၏ အမည်ကို နှိပ်ပါ → ပြင်ဆင်ပါ → သိမ်းမည်
</div>

<h5>၃။ ကိုယ်စားလှယ် ဖျက်ရန်</h5>
<div class="manual-step">
    ကိုယ်စားလှယ်၏ လိုင်းပေါ်ရှိ အမှိုက်ပုံး အိုင်ကွန်ကို နှိပ်ပါ — စနစ်က အတည်ပြုချက် တောင်းပါလိမ့်မည်
</div>

<h4><i class="bi bi-lightbulb me-2"></i>အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>Delegate ≠ Employee:</strong> Delegate = ဆက်သွယ်ရေးအတွက် အလုပ်ရှင်ကို ကိုယ်စားပြုသော ပုဂ္ဂိုလ် (HR၊ အတွင်းရေးမှူး)၊
    Employee = နေရာတွင် အမှန်တကယ် အလုပ်လုပ်နေသော ရွှေ့ပြောင်းအလုပ်သမား
</div>

<div class="manual-tip">
    <strong>အလုပ်ရှင် ၁ ဦး = ကိုယ်စားလှယ် များစွာ:</strong> အလုပ်ရှင်တစ်ဦးတွင် HR ဝန်ထမ်း များစွာ၊ ဝယ်ယူရေးအဖွဲ့ စသည်တို့ ရှိနိုင်သည်
</div>

<h4><i class="bi bi-question-circle me-2"></i>မေးလေ့ရှိသော မေးခွန်းများ</h4>
<dl>
    <dt>မေး: မီနူးတွင် Delegate ကို "ဝန်ထမ်းအချက်အလက်" ဟု ဘာကြောင့် ခေါ်ဆိုသနည်း?</dt>
    <dd>ဖြေ: "Employer" အခန်းကဏ္ဍအောက်တွင် ဖောက်သည်များက ဤအမည်ဖြင့် ဤမီနူးကို မြင်ရသောကြောင့် ဖြစ်သည် — ၎င်းတို့၏ ရှုထောင့်မှ ပိုမိုနားလည်လွယ်စေရန်</dd>

    <dt>မေး: ကိုယ်စားလှယ်တစ်ဦးကို အလုပ်ရှင် များစွာနှင့် ချိတ်ဆက်နိုင်ပါသလား?</dt>
    <dd>ဖြေ: မရပါ — ကိုယ်စားလှယ် မှတ်တမ်း ၁ ခု = အလုပ်ရှင် ၁ ဦး ဖြစ်သည်။ လူတစ်ဦးတည်းသည် ကုမ္ပဏီများစွာအတွက် အလုပ်လုပ်ပါက မှတ်တမ်း သီးခြားစီ ဖန်တီးရန် လိုအပ်သည်</dd>
</dl>
