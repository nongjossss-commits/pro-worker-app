<h4><i class="bi bi-speedometer2 me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"ဒက်ရှ်ဘုတ် (Dashboard)"</strong> သည် အကောင့်ဝင်ပြီးနောက် ပထမဆုံးမြင်ရသော စာမျက်နှာဖြစ်သည်။
    စနစ်၏ ခြုံငုံသုံးသပ်ချက်ကို ပြသသည် — အလုပ်ရှင်အရေအတွက်၊ ဝန်ထမ်းအရေအတွက်၊ လုပ်ဆောင်နေသော အလုပ်များ၊ သက်တမ်းကုန်ဆုံးခါနီးသော အရာများနှင့် အရေးကြီးသည့် အကြောင်းကြားချက်များ။
</p>

<h4><i class="bi bi-person-check me-2"></i>မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<p><code>view-dashboard</code> ခွင့်ပြုချက်ရှိသော အခန်းကဏ္ဍ မည်သည်မဆို — ပုံမှန်အားဖြင့် အထူးအခန်းကဏ္ဍများမှလွဲ၍ လူတိုင်း</p>

<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာအပိုင်းများ</h4>
<ol>
    <li><strong>အမှတ်တံဆိပ်အရောင် ခေါင်းစီး</strong> — ရက်စွဲ၊ update အချိန်နှင့် ထင်ရှားသော ကိန်းဂဏန်းများ: ၁၂ လအတွင်း ပြီးဆုံးမှု · နိုင်ငံသား · ဆောင်ရွက်ဆဲ အလုပ်ရှိသော tab · ၁၄ ရက် လုပ်ဆောင်ချက်</li>
    <li><strong>အဓိက ကိန်းဂဏန်း ကတ်များ</strong> — လက်ရှိ အလုပ်သမား · အလုပ်ရှင် · ဆောင်ရွက်ဆဲ · ဤလ ပြီးဆုံးမှု (ယခင်လနှင့် နှိုင်းယှဉ်) · ၃၀ ရက်အတွင်း သက်တမ်းကုန်မည့် စာရွက်စာတမ်း · (ငွေကြေးခွင့်ရှိသူ) ဤလ လက်ခံရရှိငွေနှင့် ရရန်ကျန်ငွေ — အသေးစိတ်နှင့် တွက်နည်းကြည့်ရန် <strong>ကတ်ပေါ်တွင် mouse တင်ပါ</strong></li>
    <li><strong>လစဉ် ပြီးဆုံးသော အလုပ်</strong> (၁၂ လ၊ Workflow / မှတ်ပုံတင် / သက်တမ်းတိုး ဆုံးဖြတ်ချက်) နှင့် <strong>လစဉ် လက်ခံရရှိငွေ</strong> (အမှန်တကယ် ငွေလက်ခံရက်အလိုက်၊ ဈေးနှုန်းစာ မပါ — ငွေကြေးမီနူးနှင့် တူ)</li>
    <li><strong>tab အလိုက် ဆောင်ရွက်ဆဲ အလုပ်</strong> — ဘားကိုနှိပ်၍ ထို tab ကို ဖွင့်နိုင် · <strong>နိုင်ငံသားအလိုက် အလုပ်သမား</strong></li>
    <li><strong>စာရွက်စာတမ်း သက်တမ်းကုန်မည့် အခြေအနေ</strong> (ဗီဇာ / အလုပ်လုပ်ခွင့် / ပတ်စပို့: ကုန်ပြီး · ၃၀ · ၆၀ · ၉၀ ရက်) · <strong>အလုပ်သမား အများဆုံး အလုပ်ရှင် ၈ ခု</strong></li>
    <li><strong>စနစ် လုပ်ဆောင်ချက် (၁၄ ရက်)</strong> နှင့် <strong>မကြာသေးမီ လုပ်ဆောင်ချက်</strong></li>
</ol>
<p class="small">လက်ရှိ အလုပ်သမား = အလုပ်ထွက်ကြောင်း မတင်ပြရသေး၊ မဖျက်ရသေး၊ ပယ်ဖျက်အခြေအနေ မဟုတ်သူ · ငွေကြေးကိန်းဂဏန်းများကို ငွေကြေးကြည့်ခွင့်ရှိသူများသာ မြင်ရပြီး ငွေကြေးမီနူးတွင် စကားဝှက်ရှိလျှင် အရင် လော့ခ်ဖွင့်ရမည် ("ငွေကြေးကိန်းဂဏန်းများ လော့ခ်ချထားသည်" ပြမည်) · ကိန်းဂဏန်းအားလုံးသည် ထိုအကောင့် ကြည့်ခွင့်ရှိသော အလုပ်ရှင်များသာ · အလင်း/အမှောင် မုဒ်နှင့် ဘာသာ ၄ မျိုးလုံး အသုံးပြုနိုင်</p>

<h4><i class="bi bi-shield-lock me-2"></i>Login နှင့် လုံခြုံရေး</h4>
<ol>
    <li>Email နှင့် စကားဝှက်ဖြင့် <strong>Login</strong> (မျက်လုံးပုံ နှိပ်၍ ရိုက်ထားသော စကားဝှက် ကြည့်နိုင်)</li>
    <li><strong>Remember me</strong> သည် ထိုစက်တွင် <strong>email</strong> ကို မှတ်သည်၊ စကားဝှက်ပါ ဖြည့်စေလိုပါက browser မေးသည့်အခါ "Save password" ကို နှိပ်ပါ</li>
    <li><strong>Browser / app ပိတ်လျှင် = ပြန် login ဝင်ရ</strong>၊ ပရိုဂရမ်စာမျက်နှာ တစ်ခုမျှ ၅ မိနစ်ထက်ပို မဖွင့်ထားလျှင် (ဥပမာ ဖုန်း app ကို နောက်ခံတွင် ထားခြင်း) အလိုအလျောက် logout — အခြားသူ၏ စက်တွင် logout မေ့ခြင်းကို ကာကွယ်</li>
    <li>Refresh သို့မဟုတ် tab အသစ်တွင် ဖွင့်ခြင်း ပုံမှန်အတိုင်း သုံးနိုင်</li>
    <li><strong>စကားဝှက်မေ့:</strong> "Forgot your password?" → email → ၆၀ မိနစ်အတွင်း link ဖွင့် (အကြိမ်ကြိမ် တောင်းလျှင် နောက်ဆုံး email ၏ link သာ အလုပ်လုပ်)</li>
    <li><strong>စကားဝှက်ထားသော မီနူးများ</strong> (ဥပမာ ငွေကြေး) တွင် မီနူးစကားဝှက် ထည့်ရ၊ ဖွင့်ပြီးလျှင် အသုံးပြုနေစဉ် ၃၀ မိနစ် ဆက်ဖွင့်ထား</li>
</ol>

<h4><i class="bi bi-circle-half me-2"></i>ပြသမှု မုဒ် (အလင်း / အမှောင်)</h4>
<ol>
    <li>မုဒ်ခလုတ်သည် အပေါ်ဘားတွင် ဘာသာစကားခလုတ်၏ နောက်တွင် ရှိသည် — ရွေးချယ်စရာ ၃ ခု: <strong>အလင်း</strong>, <strong>အမှောင်</strong>, <strong>စက်ပစ္စည်း အတိုင်း</strong> (မူလ)</li>
    <li>refresh မလိုဘဲ ချက်ချင်း ပြောင်းသည်၊ ရိုက်ထားသည်များ မပျောက်၊ ဖွင့်ထားသော အခြား tab များလည်း လိုက်ပြောင်းသည်</li>
    <li><strong>စက်ပစ္စည်း အတိုင်း:</strong> စက်တွင် သတ်မှတ်ထားသော မုဒ်ကို သုံးသည် (ဥပမာ ညဘက် အမှောင်ပြောင်းသော ဖုန်း — ပရိုဂရမ်လည်း ချက်ချင်း လိုက်ပြောင်းသည်)</li>
    <li>ရွေးထားသည်ကို <strong>စက်တစ်ခုချင်းစီ</strong> မှတ်ထားသည် — ကွန်ပျူတာနှင့် ဖုန်း မတူသော မုဒ် သုံးနိုင်သည်</li>
    <li>print ထုတ်လျှင် အမှောင်မုဒ်တွင်ပင် နောက်ခံအဖြူဖြင့် အမြဲ ထွက်သည်</li>
</ol>

<h4><i class="bi bi-lightbulb me-2"></i>အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>နံနက်တိုင်း စစ်ဆေးပါ:</strong> အလုပ်မစတင်မီ ဒက်ရှ်ဘုတ်က ယနေ့ဂရုစိုက်ရမည့်အရာများကို ပြောပြပါလိမ့်မည်။
</div>

<div class="manual-tip">
    <strong>အသေးစိတ်ကြည့်ရန် mouse တင်ပါ:</strong> ကိန်းဂဏန်းကတ် သို့မဟုတ် ဇယားပေါ်တွင် mouse တင်လျှင် မီနူးမဖွင့်ဘဲ အသေးစိတ် ချက်ချင်းပြသည် · "tab အလိုက် ဆောင်ရွက်ဆဲ အလုပ်" တွင် ဘားကိုနှိပ်၍ ထို tab ကို ဖွင့်နိုင်
</div>

<div class="manual-tip">
    <strong>ဖုန်းတွင်:</strong> မီနူးတိုင်းရှိ စာရင်းဇယားများ (အလုပ်ရှင်၊ တင်သွင်းသူ၊ အေဂျင်စီ၊ အသုံးပြုသူ၊ ဆက်တင်၊ Labor …) ကို တစ်တန်းလျှင် ကတ်တစ်ခုစီ ပြသည် — ပထမကြောင်းတွင် အမည်၊ တန်ဖိုးတစ်ခုစီတွင် ကော်လံအမည်၊ ကြည့်/ပြင်/ဖျက် ခလုတ်များ ကတ်အောက်ခြေတွင်၊ ဘေးတိုက် ဆွဲစရာမလို · "အားလုံးရွေး" ကတ်များ၏ အပေါ်တွင် · စာရင်းကိုင် အစီရင်ခံစာ / လယ်ဂျာ / ရှင်းတမ်းများ ဘေးတိုက်ဆွဲသည့် ဇယားအတိုင်း · ကွန်ပျူတာတွင် ပုံမှန်ဇယား
</div>
