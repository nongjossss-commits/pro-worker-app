<h4><i class="bi bi-trash-fill me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"ဗဟိုအမှိုက်ပုံး (Central Trash)"</strong> မီနူးတွင် စနစ်ရှိ <strong>ဖျက်ထားသော ဒေတာအားလုံး</strong> —
    အလုပ်ရှင်၊ ဝန်ထမ်း၊ ကိုယ်စားလှယ်၊ လိပ်စာ စသည်တို့ — ကို <strong>နေရာတစ်ခုတည်း</strong>တွင် ထိန်းသိမ်းထားသဖြင့်
    <strong>ပြန်လည်ရယူခြင်း</strong> သို့မဟုတ် <strong>အပြီးတိုင်ဖျက်ခြင်း</strong> ကို လွယ်ကူစွာ ပြုလုပ်နိုင်သည်
</p>

<h4><i class="bi bi-person-check me-2"></i>ဤမီနူးကို မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> — ဝင်ရောက်နိုင်သည်</li>
    <li>ဒေတာအမျိုးအစားပေါ်မူတည်၍ <code>view-trash</code> ခွင့်ပြုချက် + <code>restore-*</code> သို့မဟုတ် <code>force-delete-*</code> လိုအပ်သည်</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာ ဘယ်လိုပုံစံရှိသနည်း</h4>
<ol>
    <li><strong>တဘ်များ</strong> — ဒေတာအမျိုးအစားအလိုက် ခွဲထားသည် (အလုပ်ရှင်၊ ဝန်ထမ်း၊ ကိုယ်စားလှယ် စသည်)</li>
    <li><strong>ဇယား</strong> — ဖျက်ထားသော အရာများ + ဖျက်သည့်ရက်စွဲ + ဖျက်သူကို ပြသသည်</li>
    <li>လိုင်းတစ်ခုစီတွင် <strong>ပြန်လည်ရယူရန် ခလုတ် + အပြီးတိုင်ဖျက်ရန် ခလုတ်</strong></li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>အသုံးပြုနည်း</h4>

<h5>၁။ ဖျက်ထားသော အရာကို ပြန်လည်ရယူရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>ဒေတာအမျိုးအစား တဘ် ရွေးပါ (ဥပမာ- ဝန်ထမ်း)</li>
        <li>ပြန်လည်ရယူလိုသော မှတ်တမ်းကို ရှာပါ</li>
        <li><i class="bi bi-arrow-counterclockwise"></i> "ပြန်လည်ရယူရန်" ခလုတ်ကို နှိပ်ပါ</li>
        <li>အတည်ပြုပါ — မှတ်တမ်းသည် မူလမီနူးသို့ ပြန်ရောက်ပါလိမ့်မည်</li>
    </ol>
    <div class="manual-warn mt-2 mb-0">
        <i class="bi bi-exclamation-triangle-fill"></i>
        ဝန်ထမ်းတစ်ဦးကို ပြန်လည်ရယူခြင်းသည် စနစ်ခွဲတမ်းကို ကျော်လွန်နိုင်သည် — ကျော်လွန်ပါက ခွဲတမ်း မတိုးမြှင့်မချင်း ပြန်လည်ရယူ၍ မရနိုင်ပါ
    </div>
</div>

<h5>၂။ အပြီးတိုင် ဖျက်ရန် (ရိုးရိုးမလုပ်ပါနှင့်!)</h5>
<div class="manual-warn">
    <i class="bi bi-x-circle-fill text-danger"></i> "အပြီးတိုင်ဖျက်ရန်" ခလုတ်ကို နှိပ်ပါ → နှစ်ကြိမ် အတည်ပြုပါ → မှတ်တမ်းသည် <strong>အပြီးတိုင် ပျောက်ဆုံးသွားပြီး</strong> ပြန်လည်ရယူ၍မရတော့ပါ
    <br><br>
    အောက်ပါ ကိစ္စများအတွက်သာ အသုံးပြုပါ:
    <ul class="mb-0">
        <li>မှားယွင်းစွာ ထည့်သွင်းမိသော ထပ်နေသည့် ဒေတာ</li>
        <li>မေ့နေသော စမ်းသပ်ဒေတာ</li>
        <li>အမှန်တကယ် ရှင်းလင်းရန် လိုအပ်သော ရှေးဟောင်းဒေတာ</li>
    </ul>
</div>

<h4><i class="bi bi-lightbulb me-2"></i>အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>Soft Delete vs Force Delete:</strong> Soft Delete = အမှိုက်ပုံးသို့ ရွှေ့သည် (ပြန်လည်ရယူနိုင်သည်)၊ Force Delete = တကယ်တမ်း ဖျက်သည် (ပြန်လည်ရယူ၍မရပါ)
</div>

<div class="manual-tip">
    <strong>ပြန်လည်ရယူပြီးနောက်:</strong> ပြန်လည်ရယူထားသော မှတ်တမ်းတွင် ဒေတာ ပဋိပက္ခ မရှိကြောင်း စစ်ဆေးပါ (ဥပမာ- အလုပ်ရှင်ကို ပြန်လည်ရယူပြီးသော်လည်း ၎င်း၏ဝန်ထမ်းများ အမှိုက်ပုံးတွင် ကျန်ရှိနေခြင်း)
</div>

<h4><i class="bi bi-question-circle me-2"></i>မေးလေ့ရှိသော မေးခွန်းများ</h4>
<dl>
    <dt>မေး: တစ်ခုခုကို အပြီးတိုင် ဖျက်မိသည်၊ ပြန်ရနိုင်ပါသလား?</dt>
    <dd>ဖြေ: <strong>မရနိုင်ပါ</strong> — server စီမံခန့်ခွဲသူနှင့်အတူ database backup ကို စစ်ဆေးရန် လိုအပ်သည်</dd>

    <dt>မေး: အမှိုက်ပုံးသည် အရာများကို မည်မျှကြာ ထိန်းသိမ်းသနည်း?</dt>
    <dd>ဖြေ: အကန့်အသတ်မရှိပါ — စနစ်သည် အလိုအလျောက် ဖျက်ပေးခြင်း မပြုပါ၊ ရှင်းလင်းလိုပါက ကိုယ်တိုင် ဖျက်ရမည်</dd>

    <dt>မေး: အလုပ်ရှင်ကို ဖျက်လိုက်သည်၊ ဝန်ထမ်းများ ဘယ်ရောက်သွားသနည်း?</dt>
    <dd>ဖြေ: ဝန်ထမ်းများသည် ပုံမှန်အတိုင်း ကျန်ရှိနေသည် — အလုပ်ရှင်နှင့် ချိတ်ဆက်မှုသာ ပြတ်တောက်သွားသဖြင့် ပြန်လည်ချိတ်ဆက်ပေးရန် လိုအပ်သည်</dd>
</dl>
