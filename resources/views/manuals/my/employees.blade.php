<h4><i class="bi bi-question-circle me-2"></i>မေးလေ့ရှိသော မေးခွန်းများ</h4>

<dl>
    <dt>မေး: ဝန်ထမ်း ထည့်၍မရ၊ "ခွဲတမ်းကျော်လွန်ပြီ" ဟု ပြသနေသည်?</dt>
    <dd>ဖြေ: စနစ်ခွဲတမ်း ပြည့်နေပါသည် — တိုးမြှင့်ရန် Super Admin ကို ဆက်သွယ်ပါ သို့မဟုတ် အသုံးမပြုတော့သော ဝန်ထမ်းဟောင်းများကို အလုပ်ထုတ်ပါ</dd>

    <dt>မေး: Excel တင်သွင်းရာတွင် ဘာကြောင့် အမှားပြသနည်း?</dt>
    <dd>ဖြေ: သင့် Excel ဖိုင်ရှိ ကော်လံခေါင်းစီးများသည် ဒေါင်းလုဒ်ဆွဲထားသော နမူနာနှင့် အတိအကျ ကိုက်ညီကြောင်း စစ်ဆေးပါ — ကော်လံအမည်များ မပြောင်းလဲပါနှင့်</dd>

    <dt>မေး: ဝန်ထမ်းတစ်ဦး အလုပ်ရှင်အသစ်သို့ ပြောင်းသွားသည်?</dt>
    <dd>ဖြေ: ဝန်ထမ်းကို ပြင်ဆင်ပါ → "အလုပ်ရှင်" ကို အသစ်သို့ ပြောင်းပါ → သိမ်းမည်</dd>

    <dt>မေး: ကုမ္ပဏီတစ်ခုတည်း၏ ဝန်ထမ်းများကိုသာ မြင်ရသည်?</dt>
    <dd>ဖြေ: "Employer" အခန်းကဏ္ဍဖြင့် အကောင့်ဝင်ထားပါက မိမိ၏ ဝန်ထမ်းများကိုသာ မြင်ရပါမည် — လူတိုင်းကို မြင်ရန် Admin/Staff အခန်းကဏ္ဍ သို့မဟုတ် ပိုမြင့်သော အဆင့် လိုအပ်သည်</dd>
</dl>
