<h4><i class="bi bi-people-fill me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"ဝန်ထမ်း (Employees)"</strong> မီနူးသည် ရုံးမှ စီမံခန့်ခွဲသော နိုင်ငံခြားအလုပ်သမားများ (မြန်မာ/လာအို/ကမ္ဘောဒီးယား) ၏ ဒေတာဘေ့စ် ဖြစ်သည်။
    အခြေခံအချက်အလက်များ (အမည်အပြည့်အစုံ၊ လူမျိုး၊ နိုင်ငံကူးလက်မှတ်နံပါတ်၊ ဗီဇာ၊ အလုပ်လုပ်ခွင့်ပြုချက်၊ MOU စာချုပ်) ကို သိမ်းဆည်းပြီး
    ဝန်ထမ်းလုပ်ကိုင်နေသော <strong>အလုပ်ရှင်</strong>နှင့် ချိတ်ဆက်ထားသည်။
</p>

<h4><i class="bi bi-person-check me-2"></i>ဤမီနူးကို မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> — အလုပ်ထုတ်/ပြန်လည်ရယူ/အပြီးတိုင်ဖျက် အပါအဝင် အပြည့်အဝ အသုံးပြုနိုင်သည်</li>
    <li><span class="manual-role">Staff</span> — ကြည့်ရှု / ထည့်သွင်း / ပြင်ဆင် နိုင်သည်၊ အပြီးတိုင် ဖျက်၍မရပါ</li>
    <li><span class="manual-role">Caretaker</span> — ကြည့်ရှု / ထည့်သွင်း / ပြင်ဆင် + ဝန်ထမ်း အလုပ်ထုတ် နိုင်သည်</li>
    <li><span class="manual-role">Employer</span> — မိမိ၏ ဝန်ထမ်းများကိုသာ မြင်နိုင်သည်</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာ ဘယ်လိုပုံစံရှိသနည်း</h4>
<ol>
    <li>အပေါ်ရှိ <strong>စစ်ထုတ်ရေးဘား</strong> — လူမျိုး၊ ဗီဇာအခြေအနေ၊ အလုပ်ရှင်အလိုက် စစ်ထုတ်ပြီး အမည်/နိုင်ငံကူးလက်မှတ်နံပါတ်ဖြင့် ရှာနိုင်သည်</li>
    <li><strong>အခြေအနေ တဘ်များ</strong> — အသုံးပြုနေဆဲ / အလုပ်ထုတ်ပြီး / စာချုပ်ကုန်ဆုံးပြီး / အမှိုက်ပုံး</li>
    <li><strong>ဝန်ထမ်း ကတ်များ</strong> — ကတ်တစ်ခုစီတွင် ဓာတ်ပုံ၊ အမည်၊ လူမျိုး၊ ဗီဇာအခြေအနေ၊ အလုပ်ရှင် ပါဝင်သည်</li>
    <li>ညာဘက်အပေါ်ထောင့်ရှိ <strong>"+ ဝန်ထမ်းအသစ် ထည့်ရန်"</strong> နှင့် <strong>"Excel မှ တင်သွင်းရန်"</strong> ခလုတ်များ</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>အသုံးများသော လုပ်ဆောင်ချက်များ</h4>

<h5>၁။ ဝန်ထမ်းတစ်ဦးချင်း ထည့်ရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>ညာဘက်အပေါ်ထောင့်ရှိ <strong>"+ ဝန်ထမ်းအသစ် ထည့်ရန်"</strong> ကို နှိပ်ပါ</li>
        <li>အခြေခံအချက်အလက် ဖြည့်ပါ — အမည်အပြည့်အစုံ (ထိုင်း/အင်္ဂလိပ်)၊ လိင်၊ လူမျိုး၊ မွေးသက္ကရာဇ်</li>
        <li><strong>နိုင်ငံကူးလက်မှတ်</strong> နံပါတ် + သက်တမ်းကုန်ဆုံးရက် ဖြည့်ပါ</li>
        <li>ဤဝန်ထမ်း လုပ်ကိုင်မည့် <strong>အလုပ်ရှင်</strong> ကို ရွေးပါ</li>
        <li>ရရှိနိုင်ပါက ဓာတ်ပုံ + စာရွက်စာတမ်းများ (နိုင်ငံကူးလက်မှတ်မိတ္တူ၊ ဗီဇာ၊ အလုပ်လုပ်ခွင့်ပြုချက်) တင်ပါ</li>
        <li><strong>"သိမ်းမည်"</strong> ကို နှိပ်ပါ</li>
    </ol>
</div>

<h5>၂။ ဝန်ထမ်းများကို အစုလိုက် တင်သွင်းရန် (Excel Bulk Import)</h5>
<div class="manual-step">
    တစ်ချိန်တည်းတွင် ဝန်ထမ်းများစွာ ခေါ်ဆောင်လာသော အလုပ်ရှင်များအတွက် အသင့်တော်ဆုံး ဖြစ်သည်
    <ol class="mb-0 mt-2">
        <li><strong>"Excel မှ တင်သွင်းရန်"</strong> ကို နှိပ်ပါ</li>
        <li>ပထမဆုံး <strong>"နမူနာ (Template)"</strong> ဖိုင်ကို ဒေါင်းလုဒ်ဆွဲပါ — နမူနာတွင် စနစ် လိုအပ်သော ကော်လံခေါင်းစီးများ ပါဝင်သည်</li>
        <li>ကော်လံခေါင်းစီးများအတိုင်း Excel တွင် ဝန်ထမ်းအချက်အလက် ဖြည့်ပါ (တစ်ဦးလျှင် တစ်လိုင်း)</li>
        <li>ဖိုင်ကို စနစ်ထဲသို့ ပြန်တင်ပါ</li>
        <li>အတည်ပြုမီ <strong>အစမ်းကြည့်ခြင်း</strong> ကို စစ်ဆေးပါ — စနစ်သည် ထည့်မည့်မှတ်တမ်းများကို ပြသပြီး အမှားများရှိပါက သတိပေးပါမည်</li>
        <li><strong>"အတည်ပြုမည်"</strong> ကို နှိပ်ပါ — စနစ်သည် အားလုံးကို တစ်ပြိုင်နက် ထည့်ပေးပါမည်</li>
    </ol>
</div>

<h5>၃။ အလုပ်ထုတ်ရန် / စာချုပ်ကုန်ဆုံးရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>အလုပ်ထုတ်မည့် ဝန်ထမ်း၏ ကတ်ကို ဖွင့်ပါ</li>
        <li><strong>"အလုပ်ထုတ်ရန် / စာချုပ်ကုန်ဆုံးရန်"</strong> ကို နှိပ်ပါ</li>
        <li>အကြောင်းရင်း + အလုပ်ထုတ်ရက် ရွေးပါ</li>
        <li><strong>"အတည်ပြုမည်"</strong> ကို နှိပ်ပါ — အခြေအနေသည် "အလုပ်ထုတ်ပြီး" သို့ ပြောင်းလဲပြီး အသုံးပြုနေဆဲ ခွဲတမ်းတွင် မရေတွက်တော့ပါ</li>
    </ol>
    <div class="manual-tip mt-2 mb-0">
        <i class="bi bi-info-circle-fill"></i> <strong>အကြံပြုချက်:</strong>
        အလုပ်ထုတ်ခံရသော ဝန်ထမ်းသည် ပျောက်ဆုံးသွားခြင်း မဟုတ်ပါ — "အလုပ်ထုတ်ပြီး" တဘ်အောက်တွင် ဆက်ရှိနေပြီး ပြန်လည်ငှားရမ်းပါက ပြန်လည်ရယူနိုင်ပါသည်
    </div>
</div>

<h5>၄။ အလုပ်ထုတ်ခံရသော ဝန်ထမ်းကို ပြန်လည်ရယူရန် (Reinstate)</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>အပေါ်ရှိ <strong>"အလုပ်ထုတ်ပြီး"</strong> အခြေအနေတဘ်ကို နှိပ်ပါ</li>
        <li>ပြန်လည်ရယူလိုသော ဝန်ထမ်းကို ရှာပါ</li>
        <li><strong>"ပြန်လည်အလုပ်ပြန်ခန့်ရန်"</strong> ကို နှိပ်ပါ</li>
    </ol>
</div>

<h5>၅။ ဝန်ထမ်းကို အပြီးတိုင် ဖျက်ရန် (Force Delete)</h5>
<div class="manual-warn">
    <strong>Admin/Super Admin သာ</strong> — မှားယွင်းစွာ ထည့်သွင်းမိသော သို့မဟုတ် ထပ်နေသော ဝန်ထမ်းများအတွက် အသုံးပြုသည်၊ တစ်ကြိမ်ဖျက်ပြီးလျှင် <strong>ပြန်ပြင်၍မရပါ</strong>
    <br>
    အဆင့်များ: "အမှိုက်ပုံး" တဘ်သို့ သွားပါ → အပြီးတိုင် ဖျက်ရန် အိုင်ကွန်ကို နှိပ်ပါ → နှစ်ကြိမ် အတည်ပြုပါ
</div>

<h4><i class="bi bi-lightbulb me-2"></i>သိထားသင့်သည်များ / အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>အများဆုံး ဝန်ထမ်း ခွဲတမ်း:</strong> Super Admin သည် အသုံးပြုနေဆဲ ဝန်ထမ်းအရေအတွက်ကို ကန့်သတ်နိုင်သည်
    (Super Admin Settings → ခွဲတမ်းဆက်တင်များ တွင် သတ်မှတ်ပါ) — ခွဲတမ်း ပြည့်ပါက ဝန်ထမ်းအသစ် ထည့်၍မရပါ
</div>

<div class="manual-tip">
    <strong>ဝန်ထမ်း vs ကိုယ်စားလှယ် (Delegate):</strong> အချို့သော အခန်းကဏ္ဍများ၏ ဘယ်ဘက်မီနူးရှိ "ဝန်ထမ်းအချက်အလက်"
    သည် အမှန်တကယ် <strong>အလုပ်ရှင်၏ ကိုယ်စားလှယ် (Delegate)</strong> ကို ရည်ညွှန်းသည်၊ ရွှေ့ပြောင်းအလုပ်သမား မဟုတ်ပါ — ၎င်းတို့သည် မီနူးနှစ်ခု ခွဲခြားထားသည်
</div>

<div class="manual-tip">
    <strong>ဗီဇာ/နိုင်ငံကူးလက်မှတ် သက်တမ်းကုန်ဆုံးခါနီး:</strong> သက်တမ်းကုန်ဆုံးခါနီးလာသောအခါ စနစ်သည် <strong>အကြောင်းကြားချက်များ</strong>တွင်
    အလိုအလျောက် သတိပေးပါလိမ့်မည် — နံနက်တိုင်း စစ်ဆေးပါ
</div>

<div class="manual-warn">
    <strong>ဝန်ထမ်းကို အပြီးတိုင် မဖျက်မီ:</strong> Production / Workflow အလုပ် သို့မဟုတ် အခွန်ဘေဂျင် တစ်ခုမျှ
    ဤဝန်ထမ်းကို မကိုးကားထားကြောင်း သေချာပါစေ
</div>

<h4><i class="bi bi-question-circle me-2"></i>မေးလေ့ရှိသော မေးခွန်းများ</h4>

<dl>
    <dt>မေး: ဝန်ထမ်း ထည့်၍မရ၊ "ခွဲတမ်းကျော်လွန်ပြီ" ဟု ပြသနေသည်?</dt>
    <dd>ဖြေ: စနစ်ခွဲတမ်း ပြည့်နေပါသည် — တိုးမြှင့်ရန် Super Admin ကို ဆက်သွယ်ပါ သို့မဟုတ် အသုံးမပြုတော့သော ဝန်ထမ်းဟောင်းများကို အလုပ်ထုတ်ပါ</dd>

    <dt>မေး: Excel တင်သွင်းရာတွင် ဘာကြောင့် အမှားပြသနည်း?</dt>
    <dd>ဖြေ: သင့် Excel ဖိုင်ရှိ ကော်လံခေါင်းစီးများသည် ဒေါင်းလုဒ်ဆွဲထားသော နမူနာနှင့် အတိအကျ ကိုက်ညီကြောင်း စစ်ဆေးပါ — ကော်လံအမည်များ မပြောင်းလဲပါနှင့်</dd>

    <dt>မေး: ဝန်ထမ်းတစ်ဦး အလုပ်ရှင်အသစ်သို့ ပြောင်းသွားသည်?</dt>
    <dd>ဖြေ: ဝန်ထမ်းကို ပြင်ဆင်ပါ → "အလုပ်ရှင်" ကို အသစ်သို့ ပြောင်းပါ → သိမ်းမည်</dd>

    <dt>မေး: ကုမ္ပဏီတစ်ခုတည်း၏ ဝန်ထမ်းများကိုသာ မြင်ရသည်?</dt>
    <dd>ဖြေ: "Employer" အခန်းကဏ္ဍဖြင့် အကောင့်ဝင်ထားပါက မိမိ၏ ဝန်ထမ်းများကိုသာ မြင်ရပါမည် — လူတိုင်းကို မြင်ရန် Admin/Staff အခန်းကဏ္ဍ သို့မဟုတ် ပိုမြင့်သော အဆင့် လိုအပ်သည်</dd>
</dl>
