<h4><i class="bi bi-people-fill me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"အုပ်စု နှင့် အဖွဲ့ (Group &amp; Team)"</strong> မီနူးကို ဝန်ထမ်းများကို အဖွဲ့သေးများအဖြစ်
    <strong>စုစည်းရန်</strong> အသုံးပြုသည်၊ ဥပမာ- <em>"A စက်ရုံ မနက်ဝေဒ်ရှစ်လ် အဖွဲ့"</em>၊ <em>"အိမ်တွင်းအလုပ် အဖွဲ့"</em>၊ <em>"အဆောက်အအုံ အဖွဲ့"</em>။
    <strong>Production / Workflow အလုပ်များကို အစုလိုက် ဖန်တီးရန်</strong>၊ <strong>အစုလိုက် ငွေတောင်းခံရန်</strong>နှင့် <strong>ဒေတာကို စနစ်တကျ ထားရှိရန်</strong> အသုံးပြုသည်
</p>

<h4><i class="bi bi-person-check me-2"></i>ဤမီနူးကို မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — အပြည့်အဝ အသုံးပြုနိုင်သည်</li>
    <li><span class="manual-role">Caretaker</span> — ၎င်းကြီးကြပ်သော အလုပ်ရှင်များ၏ အုပ်စုများကိုသာ စီမံနိုင်သည်</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာ ဘယ်လိုပုံစံရှိသနည်း</h4>
<p>မီနူးကို ဝင်ရောက်သောအခါ <strong>ရွေးချယ်စရာ ၂ ခု</strong> တွေ့ရပါမည်:</p>
<ol>
    <li><strong>Affiliated with Employer (အလုပ်ရှင်နှင့် ဆက်စပ်သော)</strong> — အလုပ်ရှင်တစ်ဦးတည်းနှင့် ချည်နှောင်ထားသော အုပ်စု၊ အုပ်စုထဲရှိ ဝန်ထမ်းများသည် ထိုအလုပ်ရှင်၏ ဝန်ထမ်းဖြစ်ရမည်</li>
    <li><strong>Independent / No Employer (လွတ်လပ်သော)</strong> — အလုပ်ရှင် မည်သူနှင့်မျှ မချည်နှောင်ထားသော အုပ်စု၊ အလုပ်ရှင်မည်သူ့ဝန်ထမ်းမဆို ထည့်နိုင်သည်</li>
</ol>
<p>နှစ်မျိုးစလုံးတွင် <strong>အုပ်စုတစ်ခုစီ၏ accordion</strong> + ၎င်း၏ <strong>အဖွဲ့ခွဲများ</strong>ကို ပြသသော <strong>စီမံရေး</strong> စာမျက်နှာ ရှိသည်</p>

<h4><i class="bi bi-list-check me-2"></i>အသုံးပြုနည်း</h4>

<h5>၁။ အုပ်စုအသစ် ဖန်တီးရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>"အုပ်စု နှင့် အဖွဲ့" သို့ သွားပါ → အုပ်စုအမျိုးအစား ရွေးပါ (Affiliated / Independent)</li>
        <li>Affiliated ဖြစ်ပါက → အလုပ်ရှင် ရွေးပါ</li>
        <li>"<strong>+ အုပ်စုအသစ် ဖန်တီးရန်</strong>" ကို နှိပ်ပါ</li>
        <li>အုပ်စုကို အမည်ပေးပါ (ဥပမာ- "A စက်ရုံ မနက်ဝေဒ်ရှစ်လ် အဖွဲ့") → အတည်ပြုပါ</li>
    </ol>
</div>

<h5>၂။ အုပ်စုထဲသို့ ဝန်ထမ်းများ ထည့်ရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>အုပ်စု၏ accordion ကို ဖွင့်ပါ → "+ အဖွဲ့ဝင် ထည့်ရန်" ကို နှိပ်ပါ</li>
        <li>အမည် / နိုင်ငံကူးလက်မှတ်နံပါတ် ရိုက်ထည့်၍ ရှာပါ → စာရင်းမှ ဝန်ထမ်းကို ရွေးပါ → အတည်ပြုပါ</li>
        <li>Affiliated: ထိုအလုပ်ရှင်၏ ဝန်ထမ်းများကိုသာ ပြသသည်</li>
        <li>Independent: စနစ်ထဲရှိ ဝန်ထမ်းအားလုံးကို ပြသသည်</li>
    </ol>
</div>

<h5>၃။ အုပ်စုကို အဖွဲ့ခွဲများအဖြစ် ခွဲရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>အုပ်စုကို ဖွင့်ပါ → "<strong>+ အဖွဲ့ခွဲ ဖန်တီးရန်</strong>" ကို နှိပ်ပါ</li>
        <li>အဖွဲ့ကို အမည်ပေးပါ (ဥပမာ- "A1 အဖွဲ့"၊ "A2 အဖွဲ့")</li>
        <li>ဝန်ထမ်းများကို အဖွဲ့ထဲသို့ ဆွဲယူပါ (Drag &amp; Drop) သို့မဟုတ် အဖွဲ့ပေါ်ရှိ "ထည့်ရန်" ကို နှိပ်ပါ</li>
    </ol>
</div>

<h5>၄။ အလုပ်ဖန်တီးသောအခါ အုပ်စုကို အသုံးပြုရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>Pre-Prod / Workflow / Production ကို ဖွင့်ပါ</li>
        <li>"+ အလုပ် ထည့်ရန်" ကို နှိပ်သောအခါ → ဖန်တီးထားသော Group Name ကို သတ်မှတ်ပါ</li>
        <li>စနစ်သည် အုပ်စု၏ ဝန်ထမ်းများကို အတူတကွ ဆွဲယူပေးသည် — တစ်ခုတည်းအဖြစ် စီမံနိုင်သည်</li>
    </ol>
</div>

<h5>၅။ အုပ်စုကို ရွှေ့/ဖျက်/အမည်ပြောင်းရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>အုပ်စု၏ accordion ကို ဖွင့်ပါ → <i class="bi bi-pencil-square"></i> အိုင်ကွန်ဖြင့် အမည်ပြောင်းနိုင်သည်</li>
        <li><i class="bi bi-trash"></i> အိုင်ကွန်ဖြင့် အုပ်စုကို ဖျက်နိုင်သည် (ဝန်ထမ်းများသည် အုပ်စုမှ ဖယ်ရှားခံရသော်လည်း စနစ်မှ ဖျက်ခြင်း မခံရပါ)</li>
        <li>ဝန်ထမ်းများကို အဖွဲ့များအကြား သို့မဟုတ် အုပ်စုမှ ဖယ်ရန် ဆွဲယူ၍ ဖယ်ရှားနိုင်သည်</li>
    </ol>
</div>

<h4><i class="bi bi-lightbulb me-2"></i>အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>မှန်ကန်သော အုပ်စုအမျိုးအစား ရွေးပါ:</strong>
    <ul class="mb-0">
        <li><strong>Affiliated</strong> — အလုပ်ရှင်တစ်ဦးတည်း၏ ဝန်ထမ်းများအတွက် အသင့်တော်ဆုံး၊ ဥပမာ- "ABC စက်ရုံ ဝန်ထမ်းအားလုံး"</li>
        <li><strong>Independent</strong> — အလုပ်ရှင်ပေါင်းစုံ၏ ဝန်ထမ်းများအတွက် အသင့်တော်ဆုံး၊ ဥပမာ- စက်ရုံများစွာမှ ခေါ်ယူထားသော "တစ်နေ့တည်းတွင် အင်တာဗျူး ဖြေဆိုရမည့် ဝန်ထမ်းများ"</li>
    </ul>
</div>

<div class="manual-tip">
    <strong>အလုပ်များတွင် Group Name:</strong> Production Order သို့မဟုတ် Workflow item ဖန်တီးသောအခါ ဤနေရာရှိ အုပ်စုနှင့် ကိုက်ညီသော Group Name ကို သတ်မှတ်ပါ — စနစ်သည် အလိုအလျောက် ချိတ်ဆက်ပေးပါလိမ့်မည်
</div>

<div class="manual-warn">
    <strong>အုပ်စု ဖျက်ခြင်း:</strong> အုပ်စု ဖျက်ခြင်းသည် ထိုအုပ်စုမှ ဝန်ထမ်းများကို ဖယ်ရှားရုံသာ ဖြစ်သည် — စနစ်မှ ဝန်ထမ်းများကို ဖျက်ခြင်း မဟုတ်ပါ။
    သို့ရာတွင် <strong>အဖွဲ့ခွဲကို ဖျက်ခြင်း</strong>သည် ၎င်း၏ ဝန်ထမ်းများကို မိဘအုပ်စုသို့ ပြန်ရွှေ့ရုံသာ ဖြစ်သည် (ပျောက်ဆုံးခြင်း မရှိပါ)
</div>

<h4><i class="bi bi-question-circle me-2"></i>မေးလေ့ရှိသော မေးခွန်းများ</h4>
<dl>
    <dt>မေး: ဝန်ထမ်းတစ်ဦးသည် အုပ်စု မည်မျှ ပါဝင်နိုင်သနည်း?</dt>
    <dd>ဖြေ: တစ်ချိန်တည်းတွင် <strong>အုပ်စုများစွာ</strong> ပါဝင်နိုင်သည် — ဥပမာ- "A စက်ရုံ ဝန်ထမ်းများ" (Affiliated) နှင့် "25/3/26 အင်တာဗျူး အဖွဲ့" (Independent) နှစ်ခုစလုံး</dd>

    <dt>မေး: ဝန်ထမ်းတစ်ဦး အလုပ်ရှင် ပြောင်းသွားသည် — မူလ Affiliated အုပ်စု ဘာဖြစ်သွားမည်နည်း?</dt>
    <dd>ဖြေ: Affiliated အုပ်စုများသည် အလုပ်ရှင်နှင့် ချည်နှောင်ထားသောကြောင့် ဝန်ထမ်းသည် မူလ Affiliated အုပ်စုမှ <strong>အလိုအလျောက် ဖယ်ရှားခံရသည်</strong> — Independent အုပ်စုများကို မထိခိုက်ပါ</dd>

    <dt>မေး: အုပ်စုနှစ်ခု အမည်တူနိုင်ပါသလား?</dt>
    <dd>ဖြေ: အလုပ်ရှင်တစ်ဦးတည်းအောက်တွင် မတူနိုင်ပါ — စနစ်က "အုပ်စုအမည် ထပ်နေသည်" ဟု သတိပေးပြီး ပြောင်းလဲရန် တောင်းဆိုပါလိမ့်မည်</dd>

    <dt>မေး: ဝန်ထမ်းကို အဖွဲ့များအကြား ဆွဲယူ၍ မရပါ?</dt>
    <dd>ဖြေ: အုပ်စုတစ်ခုတည်းအတွင်း ဖြစ်ရမည် — အုပ်စုမတူသော အဖွဲ့များအတွက် "အဖွဲ့ဝင် ထည့်ရန်" → ရွေးချယ်ခြင်းကို အသုံးပြုပါ</dd>
</dl>
