<h4><i class="bi bi-envelope-paper-fill me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"ပြဿနာတင်ပြရန် / တောင်းဆိုချက်ပို့ရန် (Employer Ticket)"</strong> မီနူးသည် <strong>အလုပ်ရှင်များ</strong>
    (<span class="manual-role">Employer</span> အခန်းကဏ္ဍ) ရုံးသို့ ပြဿနာများ တင်ပြရန်/တောင်းဆိုချက်များ ပို့ရန်အတွက် ဖြစ်သည် —
    ဥပမာ- အလုပ်ခန့်လက်မှတ် တောင်းဆိုခြင်း၊ ဝန်ထမ်း ပျက်ကွက်ခြင်း အသိပေးခြင်း၊ ဒေတာပြောင်းလဲရန် တောင်းဆိုခြင်း
</p>

<h4><i class="bi bi-person-check me-2"></i>မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Employer</span> — မိမိ၏ တောင်းဆိုချက်များကို ဖန်တီး + ကြည့်ရှုနိုင်သည်</li>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — ကြည့်ရှု + ပြန်ကြားနိုင်သည် (Ticket Inbox မှတစ်ဆင့်)</li>
</ul>

<h4><i class="bi bi-list-check me-2"></i>အသုံးပြုနည်း (အလုပ်ရှင်ဘက်)</h4>

<h5>တောင်းဆိုချက်အသစ် ဖန်တီးရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>"+ တောင်းဆိုချက်အသစ် ပို့ရန်" ကို နှိပ်ပါ</li>
        <li>အမျိုးအစား ရွေးပါ (လက်မှတ်တောင်းဆိုခြင်း၊ ပြဿနာတင်ပြခြင်း စသည်)</li>
        <li>အသေးစိတ် ရိုက်ထည့်ပါ</li>
        <li>ဖိုင်/ဓာတ်ပုံ ပူးတွဲနိုင်သည်</li>
        <li>"ပို့မည်" ကို နှိပ်ပါ — ရုံးက လက်ခံရရှိပြီး Ticket Inbox မှတစ်ဆင့် ပြန်ကြားပါလိမ့်မည်</li>
    </ol>
</div>

<h5>အခြေအနေ ခြေရာခံရန်</h5>
<div class="manual-step">
    တောင်းဆိုချက်စာရင်းတွင် "အဖြေစောင့်ဆိုင်းနေဆဲ"၊ "ဆောင်ရွက်နေဆဲ"၊ "ပိတ်ပြီး" အခြေအနေများ ပြသသည် —
    ရုံး၏ ပြန်ကြားချက်များကို ကြည့်ရန် တောင်းဆိုချက်ကို နှိပ်ပါ
</div>

<h4><i class="bi bi-lightbulb me-2"></i>အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>ဓာတ်ပုံ/စာရွက်စာတမ်း ပူးတွဲပါ:</strong> ပြဿနာကို ပိုမိုနားလည်လွယ်စေသည် — ဝန်ထမ်းများ ပိုမိုတိကျစွာ ပြန်ကြားနိုင်သည်
</div>
