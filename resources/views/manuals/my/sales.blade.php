<h4><i class="bi bi-megaphone-fill me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"ဖတ်ရန်နှင့် ရောင်းချရန် (Read and Sale)"</strong> မီနူးသည် အလုပ်ရှင် <strong>မဖြစ်သေးသော</strong> ဖောက်သည်များကို စီမံသည့်နေရာ ဖြစ်သည်။
    စုံစမ်းမှုများ (Lead) မှတ်တမ်းတင်ရန်၊ ဈေးနှုန်းပြသလွှာများ ဖန်တီးရန် အသုံးပြုပြီး ရောင်းချမှုပြီးသောအခါ
    စနစ်သည် <strong>အလုပ်ရှင် + ဝန်ထမ်း + Production အလုပ်</strong> ကို အလိုအလျောက် ဖန်တီးပေးသည်။
</p>
<p>
    ၎င်းသည် workflow တစ်ခုလုံး၏ အစပိုင်း ဖြစ်သည် — အရောင်းဌာနက ဖောက်သည်အသစ်ကို ဆွဲယူခြင်းမှ → ရောင်းချမှုပြီးစီးခြင်း → နေ့စဉ်စီမံခန့်ခွဲမှုသို့။
</p>

<h4><i class="bi bi-person-check me-2"></i>ဤမီနူးကို မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — ဝင်ရောက်နိုင်သည်</li>
    <li><span class="manual-role">Caretaker</span> <span class="manual-role">Employer</span> — ဝင်ရောက်၍မရပါ</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာ ဘယ်လိုပုံစံရှိသနည်း</h4>
<p>ဤစာမျက်နှာသည် <strong>Kanban Board</strong> ဖြစ်သည် — ဖောက်သည် အခြေအနေအလိုက် ကော်လံများပါဝင်သည်:</p>
<ol>
    <li><strong>အသစ် (Lead)</strong> — ဆက်သွယ်မှု အသစ်၊ မဆွေးနွေးရသေးပါ</li>
    <li><strong>ဆောင်ရွက်နေဆဲ</strong> — စည်းကမ်းချက်များ ညှိနှိုင်းနေဆဲ</li>
    <li><strong>ဈေးနှုန်းပြသပြီး</strong> — ဖောက်သည်ထံ ဈေးနှုန်းပြသလွှာ ပို့ပြီး၊ အဖြေစောင့်ဆိုင်းနေဆဲ</li>
    <li><strong>အောင်မြင်ပြီး</strong> — သဘောတူပြီ! စနစ်စစ်စစ်ထဲသို့ ဝင်ရောက်တော့မည်</li>
    <li><strong>လွတ်သွားပြီး</strong> — ဖောက်သည် ငြင်းဆိုသွားသည်</li>
</ol>
<p>ကတ်ကို ကော်လံအကြား ဆွဲယူ၍ အခြေအနေ ပြောင်းလဲနိုင်သည်</p>

<h4><i class="bi bi-list-check me-2"></i>အသုံးများသော လုပ်ဆောင်ချက်များ</h4>

<h5>၁။ ဖောက်သည်အသစ် ထည့်ရန် (Lead)</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>စာမျက်နှာ၏ အပေါ်ပိုင်းရှိ <strong>"+ Lead ထည့်ရန်"</strong> ကို နှိပ်ပါ</li>
        <li>အခြေခံအချက်အလက် ဖြည့်ပါ — ကုမ္ပဏီ/ပုဂ္ဂိုလ်အမည်၊ ဖုန်းနံပါတ်၊ ရင်းမြစ် (ဥပမာ- ဖုန်းခေါ်ဆိုမှု၊ ညွှန်းပို့ချက်၊ Facebook)</li>
        <li><strong>အလုပ်အမျိုးအစား</strong> ရွေးပါ (MOU၊ ဗီဇာ၊ အခြား)</li>
        <li><strong>"သိမ်းမည်"</strong> ကို နှိပ်ပါ — Lead သည် "အသစ်" ကော်လံတွင် ပေါ်လာပါမည်</li>
    </ol>
</div>

<h5>၂။ ဈေးနှုန်းပြသလွှာ ဖန်တီးရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>Lead ၏ ကတ်ကို ဖွင့်ပါ</li>
        <li><strong>"ဈေးနှုန်းပြသလွှာ ဖန်တီးရန်"</strong> ကို နှိပ်ပါ</li>
        <li>ပစ္စည်း/ဝန်ဆောင်မှု စာရင်း + စျေးနှုန်း + အရေအတွက် ထည့်ပါ</li>
        <li><strong>"ငွေကြေးပရိုဖိုင်"</strong> (ငွေတောင်းခံသူ) ကို ရွေးပါ — စာရွက်ပေါ်တွင် ပေါ်မည့် ရုံးပရိုဖိုင်</li>
        <li>PDF နမူနာ ကြည့်ရန် <strong>"အစမ်းကြည့်ရန်"</strong> ကို နှိပ်ပါ</li>
        <li><strong>"ပို့မည်"</strong> ကို နှိပ်ပါ — Lead သည် "ဈေးနှုန်းပြသပြီး" ကော်လံသို့ အလိုအလျောက် ရွှေ့သွားပါမည်</li>
    </ol>
</div>

<h5>၃။ ရောင်းချမှု ပြီးစီးရန် → စနစ်စစ်စစ်ထဲသို့ ဝင်ရောက်ရန်</h5>
<div class="manual-step">
    ဖောက်သည် သဘောတူပြီးသောအခါ:
    <ol class="mb-0 mt-2">
        <li>"ဈေးနှုန်းပြသပြီး" ရှိ ကတ်ကို ဖွင့်ပါ</li>
        <li><strong>"ရောင်းချမှု ပြီးစီးရန် / ဖောက်သည်စစ်စစ်သို့ ပြောင်းရန်"</strong> ကို နှိပ်ပါ</li>
        <li>စနစ်သည် <strong>အလုပ်ရှင်</strong> အသေးစိတ် (အခွန် ID၊ မှတ်ပုံတင်လိပ်စာ စသည်) ကို တောင်းဆိုပါလိမ့်မည်</li>
        <li>စီမံမည့် <strong>ဝန်ထမ်းစာရင်း</strong> ကို ထည့်ပါ (တစ်ဦးချင်း သို့မဟုတ် Excel မှတစ်ဆင့်)</li>
        <li><strong>"အတည်ပြု၍ ဖန်တီးမည်"</strong> ကို နှိပ်ပါ — စနစ်သည် ဤအရာအားလုံးကို တစ်ပြိုင်နက် ဖန်တီးပေးပါမည်:
            <ul>
                <li>"အလုပ်ရှင်" မီနူးတွင် အလုပ်ရှင်အသစ်</li>
                <li>"ဝန်ထမ်း" မီနူးတွင် ဝန်ထမ်းအားလုံး</li>
                <li>"P Production" မီနူးတွင် Production အလုပ်အသစ်</li>
            </ul>
        </li>
    </ol>
</div>

<h5>၄။ Lead ပယ်ဖျက်ရန်</h5>
<div class="manual-step">
    ကတ်ကို <strong>"လွတ်သွားပြီး"</strong> ကော်လံသို့ ဆွဲယူပါ သို့မဟုတ် ကတ်ပေါ်ရှိ "ပယ်ဖျက်ရန်" ကို နှိပ်ပြီး
    အကြောင်းရင်း ဖော်ပြပါ (ဥပမာ- "စျေးကြီးလွန်းသည်"၊ "ဆက်သွယ်၍မရပါ")
    <div class="manual-tip mt-2 mb-0">
        <i class="bi bi-info-circle-fill"></i> <strong>အကြံပြုချက်:</strong>
        ပယ်ဖျက်ထားသော Lead သည် မှတ်တမ်းတွင် ဆက်ရှိနေသည် — အကြောင်းရင်းနှင့် စာရင်းအင်းများကို ပြန်လည်ကြည့်ရှုနိုင်သည်
    </div>
</div>

<h4><i class="bi bi-lightbulb me-2"></i>သိထားသင့်သည်များ / အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>စနစ်စစ်စစ်ထဲသို့ ဝင်ရောက်မီ ဘာကြောင့် Lead ဖြင့် စတင်ရသနည်း?</strong>
    အကြောင်းမှာ Lead ၏ ၇၀-၈၀% သည် ပုံမှန်အားဖြင့် ပြီးစီး၍ မရသောကြောင့် ဖြစ်သည် — ချက်ချင်း အလုပ်ရှင် ဖန်တီးလိုက်ပါက စနစ်တွင် အသုံးမဝင်သော ဒေတာများ ပြည့်နှက်သွားနိုင်သည်။
    Lead/Sales ကို သီးခြားထားခြင်းသည် အလုပ်ရှင်စစ်စစ်စာရင်း သန့်ရှင်းပြီး ယုံကြည်စိတ်ချရအောင် ထိန်းသိမ်းရန် ဖြစ်သည်
</div>

<div class="manual-tip">
    <strong>ဈေးနှုန်းပြသလွှာ ≠ အခွန်ဘေဂျင်:</strong>
    ဈေးနှုန်းပြသလွှာ (Quotation) သည် အခွန်နှင့် မသက်ဆိုင်ပါ — စျေးနှုန်းကို ဆက်သွယ်ပြောကြားရန်သာ အသုံးပြုသည်။
    အခွန်ဘေဂျင် (Tax Invoice) ကို ဖောက်သည် ငွေပေးချေပြီးနောက် Finance မီနူးတွင် ထုတ်ပေးသည်
</div>

<div class="manual-tip">
    <strong>ကတ်ဆွဲယူ၍ အခြေအနေ ပြောင်းလဲရန်:</strong> ကတ်ကို ဖွင့်ရန် မလိုအပ်ပါ — မောက်စ်ဖြင့် ကော်လံများအကြား ဆွဲယူရုံသာ ဖြစ်သည်။
    စနစ်က အလိုအလျောက် သိမ်းဆည်းပေးပါလိမ့်မည်
</div>

<div class="manual-warn">
    <strong>ရောင်းချမှု ပြီးစီးပြီးနောက် ပြင်ဆင်၍မရပါ:</strong>
    "ရောင်းချမှု ပြီးစီးရန်" ကို နှိပ်ပြီး စနစ်သည် အလုပ်ရှင်/ဝန်ထမ်း ဖန်တီးပြီးသောအခါ
    မူလ Lead ကို "လော့ခ်ချ" ထားပြီး ထပ်မံ ပြင်ဆင်၍ မရတော့ပါ — ပြောင်းလဲမှုများကို အလုပ်ရှင်/ဝန်ထမ်းမှတ်တမ်းတွင် တိုက်ရိုက် ပြုလုပ်ရမည်
</div>

<h4><i class="bi bi-question-circle me-2"></i>မေးလေ့ရှိသော မေးခွန်းများ</h4>

<dl>
    <dt>မေး: ဤမီနူးကို ဘာကြောင့် မမြင်ရသနည်း?</dt>
    <dd>ဖြေ: ဤမီနူးသည် <strong>Super Admin / Admin / Staff</strong> အခန်းကဏ္ဍများကိုသာ ပြသသည် — Caretaker နှင့် Employer တွင် မြင်ခွင့် မရှိပါ</dd>

    <dt>မေး: ပို့ပြီးသား ဈေးနှုန်းပြသလွှာကို ပြင်ဆင်နိုင်ပါသလား?</dt>
    <dd>ဖြေ: ရနိုင်ပါသည်၊ ဖောက်သည် ရောင်းချမှု မပြီးမချင်း — ပြီးသွားလျှင် လော့ခ်ချသွားပါမည်</dd>

    <dt>မေး: ဖောက်သည်ဟောင်း ပြန်လာသည်၊ Lead အသစ် စတင်ရန် လိုပါသလား?</dt>
    <dd>ဖြေ: မလိုအပ်ပါ — စနစ်ထဲတွင် အလုပ်ရှင် ဖြစ်နေပြီးသားဖြစ်ပါက Production မီနူးတွင် Production အလုပ်အသစ် ထည့်ရုံသာ ဖြစ်သည်</dd>

    <dt>မေး: "Lead ပိုင်ရှင်" ဆိုသည်မှာ မည်သူနည်း?</dt>
    <dd>ဖြေ: Lead ကို ဖန်တီးသူသည် ၎င်း၏ <strong>ပိုင်ဆိုင်သော အရောင်းဝန်ထမ်း</strong> ဖြစ်လာပြီး နောင်တွင် ကော်မရှင် တွက်ချက်ရန် အသုံးပြုသည်</dd>
</dl>
