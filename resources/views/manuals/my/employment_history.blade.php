<h4><i class="bi bi-person-badge me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"အလုပ်ခန့်ထားမှု မှတ်တမ်း (Employment History)"</strong> မီနူးသည် စနစ်ထဲတွင် တစ်ချိန်ချိန် ရှိခဲ့ဖူးသော <strong>ဝန်ထမ်းအားလုံး</strong>ကို စုစည်းသည်၊
    <em>လက်ရှိ အသုံးပြုနေဆဲ</em>၊ <em>အလုပ်ထုတ်ပြီး (Resigned)</em>၊ <em>စာချုပ်ကုန်ဆုံးပြီး</em>၊ သို့မဟုတ် <em>အလုပ်ရှင်အသစ်သို့ ပြောင်းသွားပြီး</em> ဖြစ်ဖြစ်။
    <strong>အတိတ်မှတ်တမ်း ပြန်လည်ကြည့်ရှုရန်</strong>၊ <strong>ဝန်ထမ်းဟောင်း ရှာဖွေရန်</strong>၊ ဝန်ထမ်းဟောင်းများကို အလုပ်ရှင်အသစ်သို့ <strong>အစုလိုက်လွှဲပြောင်းရန်</strong> အသုံးပြုသည်
</p>

<h4><i class="bi bi-person-check me-2"></i>ဤမီနူးကို မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — အပြည့်အဝ အသုံးပြုနိုင်သည်</li>
    <li><span class="manual-role">Caretaker</span> — ၎င်းတို့ စီမံသော အလုပ်ရှင်များ၏ ဝန်ထမ်းများကိုသာ မြင်ရသည်</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာ ဘယ်လိုပုံစံရှိသနည်း</h4>
<ol>
    <li>အပေါ်ရှိ <strong>စစ်ထုတ်ရေးဘား</strong> — ရှာဖွေခြင်း၊ လူမျိုး/MOU အမျိုးအစား/ပန်းရောင်ကတ်/နိုင်ငံကူးလက်မှတ် အမျိုးအစားဖြင့် စစ်ထုတ်ခြင်း</li>
    <li><strong>ညာဘက်အပေါ်ထောင့်</strong> — CSV ထုတ်ယူရန် ခလုတ်၊ မြင်ကွင်း ပြောင်းလဲရန် (ကတ်/ဇယား)၊ စာမျက်နှာလျှင် အရေအတွက် ရွေးချယ်ခြင်း</li>
    <li><strong>ဝန်ထမ်းစာရင်း</strong> — အသုံးပြုနေဆဲနှင့် အသုံးမပြုတော့သူ (အလုပ်ထုတ်ပြီး/စာချုပ်ကုန်ဆုံးပြီး အပါအဝင်) အားလုံးကို ပြသသည်</li>
    <li><strong>အစုလိုက် လုပ်ဆောင်ချက် ဘား</strong> (အောက်ခြေတွင် ပေါ်နေသည်) — ဝန်ထမ်းများစွာ အမှန်ခြစ်ပြီးနောက် → အလုပ်ရှင် လွှဲပြောင်းရန် / ထုတ်ယူရန် / PDF ဖန်တီးရန်</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>အသုံးပြုနည်း</h4>

<h5>၁။ ဝန်ထမ်းဟောင်းများ ရှာဖွေရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>"ရှာဖွေရန်..." ဘောက်စ်တွင် အမည် / နိုင်ငံကူးလက်မှတ်နံပါတ် ရိုက်ထည့်ပါ</li>
        <li>လိုအပ်ပါက အခြားစစ်ထုတ်ချက်များ (လူမျိုး / MOU / နိုင်ငံကူးလက်မှတ်) ရွေးပါ</li>
        <li>"စစ်ထုတ်ရန်" ကို နှိပ်ပါ — ရလဒ်တွင် အသုံးပြုနေဆဲ + အသုံးမပြုတော့သူ နှစ်မျိုးလုံး ပါဝင်သည်</li>
        <li>စစ်ထုတ်ချက်များ ပြန်လည်သတ်မှတ်ရန် "ရှင်းရန်" ကို နှိပ်ပါ</li>
    </ol>
</div>

<h5>၂။ ဝန်ထမ်းဟောင်းများကို အလုပ်ရှင်အသစ်သို့ အစုလိုက် လွှဲပြောင်းရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>ရွှေ့လိုသော ဝန်ထမ်းများ၏ အမှန်ခြစ်ဘောက်စ် ခြစ်ပါ (အများအပြား ရွေးနိုင်သည်)</li>
        <li>အစုလိုက်လုပ်ဆောင်ချက်ဘားသည် အောက်ခြေတွင် ပေါ်လာသည် → "Actions" ကို နှိပ်ပါ → <strong>"အလုပ်ရှင် လွှဲပြောင်းရန်"</strong></li>
        <li>ခရီးဆုံး အလုပ်ရှင် ရွေးပါ → အတည်ပြုပါ</li>
        <li>စနစ်သည် ရွေးထားသော ဝန်ထမ်းအားလုံးကို အလုပ်ရှင်အသစ်သို့ ချက်ချင်း ရွှေ့ပေးပါလိမ့်မည်</li>
    </ol>
</div>

<h5>၃။ ဒေတာကို CSV / Excel အဖြစ် ထုတ်ယူရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>အထူးလိုအပ်ပါက ဒေတာကို အရင်စစ်ထုတ်ပါ</li>
        <li>ညာဘက်အပေါ်ထောင့်ရှိ "Export CSV" ကို နှိပ်ပါ — ဖိုင်သည် ချက်ချင်း ဒေါင်းလုဒ်ဆွဲပါလိမ့်မည်</li>
        <li>သို့မဟုတ် အစုလိုက်လုပ်ဆောင်ချက်ဘား → "Advanced Export" ကို အသုံးပြု၍ ကော်လံများ ရွေးချယ်နိုင်သည်</li>
    </ol>
</div>

<h5>၄။ PDF များကို အစုလိုက် ဖန်တီးရန်</h5>
<div class="manual-step">
    ဝန်ထမ်းများစွာ အမှန်ခြစ်ပါ → အစုလိုက်လုပ်ဆောင်ချက်ဘား → "Automated PDF" → နမူနာရွေးပါ → စနစ်သည် အားလုံးအတွက် PDF ကို တစ်ပြိုင်နက် ဖန်တီးပေးပါလိမ့်မည်
</div>

<h4><i class="bi bi-lightbulb me-2"></i>အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>"ဝန်ထမ်း" မီနူးနှင့် ဘယ်လိုကွာခြားသနည်း:</strong> ပုံမှန် ဝန်ထမ်းမီနူးသည် အသုံးပြုနေဆဲ ဝန်ထမ်းများကိုသာ ပြသပြီး၊
    ဤမီနူးသည် အလုပ်ထုတ်ပြီး/စာချုပ်ကုန်ဆုံးပြီးသူများ အပါအဝင် <strong>လူတိုင်း</strong>ကို ပြသသည် — အဟောင်းရှာသည့်အခါ သို့မဟုတ် အတိတ်မှတ်တမ်း ပြန်ကြည့်သည့်အခါ အသုံးပြုပါ
</div>

<div class="manual-tip">
    <strong>ဇယား vs ကတ် မြင်ကွင်း:</strong> ဇယားမြင်ကွင်းသည် လူများစွာ၏ ဒေတာကို တစ်ပြိုင်နက် နှိုင်းယှဉ်ရန် အသင့်တော်ဆုံးဖြစ်ပြီး၊
    ကတ်မြင်ကွင်းသည် ပုဂ္ဂိုလ်တစ်ဦး၏ အသေးစိတ်ကို ဓာတ်ပုံနှင့် badge များအတူ တစ်ကြိမ်လျှင် တစ်ဦးစီ ကြည့်ရန် အသင့်တော်ဆုံး ဖြစ်သည်
</div>

<div class="manual-warn">
    <strong>အလုပ်ရှင် လွှဲပြောင်းခြင်း:</strong> လွှဲပြောင်းခံရသော ဝန်ထမ်း၏ <strong>employer_id ပြောင်းလဲသွားသည်</strong>။
    စနစ်သည် ထိုဝန်ထမ်း၏ ဆိုင်းငံ့ထားသော "အလုပ်ထုတ်အကြောင်းကြားချက်" မှတ်တမ်းကို (ရှိလျှင်) ချက်ချင်း <strong>အလိုအလျောက် ပယ်ဖျက်</strong>ပါမည်
</div>

<h4><i class="bi bi-question-circle me-2"></i>မေးလေ့ရှိသော မေးခွန်းများ</h4>
<dl>
    <dt>မေး: ကျွန်ုပ် မျှော်မှန်းထားသည်ထက် ဝန်ထမ်း နည်းနေသည်?</dt>
    <dd>ဖြေ: အသုံးပြုသူ၏ ခွင့်ပြုချက်ကို စစ်ဆေးပါ — Caretaker ဖြစ်ပါက ၎င်းစီမံသော အလုပ်ရှင်များ၏ ဝန်ထမ်းများကိုသာ မြင်ရသည်</dd>

    <dt>မေး: အလုပ်ရှင် လွှဲပြောင်းပြီးနောက် ဝန်ထမ်းသည် "အလုပ်ထုတ်အကြောင်းကြားချက်" မီနူးမှ ချက်ချင်း ပျောက်သွားသည်?</dt>
    <dd>ဖြေ: မှန်ကန်ပါသည် — employer_id ပြောင်းလဲသောအခါ စနစ်သည် ထိုဝန်ထမ်း၏ ဆိုင်းငံ့ထားသော "အလုပ်ထုတ်အကြောင်းကြားချက်" မှတ်တမ်းကို အလိုအလျောက် ပယ်ဖျက်ပါသည်၊ အကြောင်းမှာ "အလုပ်ထုတ်အကြောင်းကြားချက်" သည် အလုပ်ရှင်ဟောင်းမှ ထွက်ခွာခြင်းအတွက် ဖြစ်၍ နောက်ထပ် မသက်ဆိုင်တော့ပါ</dd>

    <dt>မေး: ဖျက်ထားသော (အမှိုက်ပုံးရှိ) ဝန်ထမ်းများ ဤမီနူးတွင် ပေါ်ပါသလား?</dt>
    <dd>ဖြေ: မပေါ်ပါ — "ဗဟိုအမှိုက်ပုံး" မီနူးကို ကြည့်ပါ၊ ထိုနေရာမှ ပြန်လည်ရယူနိုင်သည်</dd>

    <dt>မေး: CSV ထုတ်ယူချက်တွင် မည်သည့်ကော်လံများ ပါဝင်သနည်း?</dt>
    <dd>ဖြေ: အခြေခံအစုံ — ကိုယ်ပိုင်ကော်လံများ ရွေးရန် "Advanced Export" ကို အသုံးပြုပါ (MOU၊ သက်တမ်းကုန်ဆုံးရက်၊ အခြေအနေ စသည် အပါအဝင်)</dd>
</dl>
