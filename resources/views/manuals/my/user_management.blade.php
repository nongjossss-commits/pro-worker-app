<h4><i class="bi bi-person-fill-gear me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"အသုံးပြုသူ စီမံခန့်ခွဲမှု (User Management)"</strong> မီနူးကို
    စနစ် <strong>အသုံးပြုသူအကောင့်များ</strong> ဖန်တီး/ပြင်ဆင်/ဖျက်ရန်နှင့် ပုဂ္ဂိုလ်တစ်ဦးစီအတွက် <strong>အခန်းကဏ္ဍ (Role)</strong> သတ်မှတ်ရန်
    အသုံးပြုပြီး၊ စာမျက်နှာ၏ အောက်ခြေတွင် အခန်းကဏ္ဍတစ်ခုစီ၏ <strong>ခွင့်ပြုချက်များ</strong>ကို ကြည့်ရှုနိုင်သည်
</p>

<h4><i class="bi bi-person-check me-2"></i>ဤမီနူးကို မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> — ဝင်ရောက်နိုင်သည်</li>
    <li>(Super Admin သည် super-admin အသုံးပြုသူအားလုံးကို မြင်ရသည်၊ Admin သည် super-admin များမှလွဲ၍ လူတိုင်းကို မြင်ရသည်)</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာ ဘယ်လိုပုံစံရှိသနည်း</h4>
<ol>
    <li><strong>ရှာဖွေရေးဘား</strong> + အခန်းကဏ္ဍဖြင့် စစ်ထုတ်ခြင်း</li>
    <li><strong>အခန်းကဏ္ဍ တဘ်များ</strong> — Super Admin၊ Admin၊ Caretaker၊ Staff၊ Employer</li>
    <li><strong>အသုံးပြုသူ ဇယား</strong> — အမည်၊ အီးမေးလ်၊ အခြေအနေ၊ လုပ်ဆောင်ချက်များ</li>
    <li>အောက်ခြေရှိ <strong>"အခန်းကဏ္ဍနှင့် ခွင့်ပြုချက်များ" အပိုင်း</strong> (manage-roles ခွင့်ပြုချက်ရှိသူများသာ မြင်ရသည်) — အခန်းကဏ္ဍအားလုံး + ၎င်းတို့နှင့် ချိတ်ဆက်ထားသော ခွင့်ပြုချက်များကို ကြည့်ရှုနိုင်သည်</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>အသုံးပြုနည်း</h4>

<h5>၁။ အသုံးပြုသူအသစ် ဖန်တီးရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>"+ အသုံးပြုသူအသစ် ထည့်ရန်" ကို နှိပ်ပါ</li>
        <li>အမည်၊ အီးမေးလ်၊ စကားဝှက် ဖြည့်ပါ</li>
        <li>အခန်းကဏ္ဍ ရွေးပါ (ဥပမာ- Staff၊ Caretaker)</li>
        <li>"သိမ်းမည်" ကို နှိပ်ပါ — အသုံးပြုသူ ယခု အကောင့်ဝင်နိုင်ပါပြီ</li>
    </ol>
</div>

<h5>၂။ အသုံးပြုသူ၏ အခန်းကဏ္ဍ ပြောင်းလဲရန်</h5>
<div class="manual-step">
    အသုံးပြုသူ၏ အမည်ကို နှိပ်ပါ → အခန်းကဏ္ဍအသစ် ရွေးပါ → သိမ်းမည်
</div>

<h5>၃။ အကောင့် ဖွင့်/ပိတ်ရန် (အခြေအနေ)</h5>
<div class="manual-step">
    အသုံးပြုသူ၏ လိုင်းပေါ်ရှိ အခြေအနေခလုတ်ကို နှိပ်ပါ — Active = အကောင့်ဝင်နိုင်သည်၊ Inactive = အကောင့်ဝင်၍မရပါ
</div>

<h5>၄။ စကားဝှက် ပြန်လည်သတ်မှတ်ရန်</h5>
<div class="manual-step">
    အမည်ကို နှိပ်ပါ → "စကားဝှက် ပြောင်းရန်" ကို နှိပ်ပါ → အသစ်ရိုက်ထည့်ပါ → သိမ်းမည်
</div>

<h5>၅။ အခန်းကဏ္ဍတစ်ခုစီ၏ ခွင့်ပြုချက်များ ကြည့်ရှုရန်</h5>
<div class="manual-step">
    စာမျက်နှာ၏ အောက်ခြေသို့ ရွှေ့ပါ — "အခန်းကဏ္ဍနှင့် ခွင့်ပြုချက်များ" အပိုင်းသည် အခန်းကဏ္ဍတိုင်း + ၎င်းနှင့်ပူးတွဲထားသော ခွင့်ပြုချက်များကို ပြသသည်
</div>

<h5>၆။ အသုံးပြုသူတစ်ဦးချင်း ခွင့်ပြုချက်များ</h5>
<div class="manual-step">
    အသုံးပြုသူ ပြင်ဆင်စာမျက်နှာတွင် တစ်ဦးချင်း ပေး/ရုပ်သိမ်းနိုင်သော ခွင့်ပြုချက်များ: <strong>တိုးတက်မှုအဆင့် အပ်ဒိတ်</strong> (အဆင့်များ အမှန်ခြစ်၊ Admin/Staff မူလရှိ၊ Caretaker မရှိ) · <strong>ဝန်ထမ်း ပြင်ဆင်</strong> (ဝန်ထမ်းဒေတာ၊ ချိန်းဆိုမှု၊ login — အဆင့်အမှန်ခြစ်ခြင်းနှင့် သီးခြား) · <strong>Workflow စီမံ</strong> (အလုပ်ဖန်တီး၊ အဆင့်နှင့် အသိပေးချက် သတ်မှတ်) · <strong>ငွေကြေးစီမံ</strong> (ဈေး၊ ဘေလ်၊ ငွေလက်ခံ) · <strong>ပူးတွဲဖိုင်ရွှေ့</strong> (Super Admin က Admin/Staff အချို့ကို ပေးနိုင်)။
</div>

<h5>၇။ Employer အကောင့်နှင့် Pro Walker Labour အကောင့်</h5>
<div class="manual-step">
    <strong>Employer</strong> အကောင့်သည် ကိုယ့်ကုမ္ပဏီ ဒေတာကိုသာ မြင်ရပြီး လုပ်ငန်းမီနူးများ (Pre-Production / Workflow / ဆုံးဖြတ်ချက်များ) ကို ဝင်မရပါ။ Pro Walker Labour အကောင့်များ (စာရင်းကိုင် / အစုရှယ်ယာရှင် / အဖွဲ့ခေါင်းဆောင် / အဖွဲ့ဝင်) ကို Super Admin သာ ဖန်တီးနိုင်ပြီး Labour module ကိုသာ ဝင်နိုင်သည်။
</div>

<h5>၈။ Login နှင့် လုံခြုံရေး</h5>
<div class="manual-step">
    Browser သို့မဟုတ် app ပိတ်ပြီးလျှင် အမြဲ ပြန် login ဝင်ရသည်၊ ပရိုဂရမ်စာမျက်နှာ တစ်ခုမျှ ၅ မိနစ်ထက်ပို မဖွင့်ထားလျှင် အလိုအလျောက် logout ဖြစ်သည်။ "Remember me" သည် ထိုစက်တွင် email ကိုသာ မှတ်သည် (စကားဝှက်ကို browser ဖြင့် သိမ်းပါ)။ စကားဝှက် အကြိမ်ကြိမ် မှားလျှင် login ကို ခေတ္တ ပိတ်ထားသည်။
</div>

<h4><i class="bi bi-lightbulb me-2"></i>အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>Pro-Worker ရှိ အခန်းကဏ္ဍ ၅ ခု:</strong>
    <ul class="mb-0 mt-1">
        <li><span class="manual-role">Super Admin</span> — အားလုံးကို အပြည့်အဝ အသုံးပြုနိုင်သည်</li>
        <li><span class="manual-role">Admin</span> — Super Admin Settings မှလွဲ၍ အပြည့်အဝ အသုံးပြုနိုင်သည်</li>
        <li><span class="manual-role">Staff</span> — နေ့စဉ်လုပ်ငန်းများ (ဝန်ထမ်း၊ အလုပ်ရှင်၊ ငွေကြေး)</li>
        <li><span class="manual-role">Caretaker</span> — ဝန်ထမ်းများကို စီမံသည် (ဖျက်၍မရပါ)</li>
        <li><span class="manual-role">Employer</span> — မိမိ၏ ဒေတာကို ကြည့်ရှုရန် အကောင့်ဝင်သော ဖောက်သည်</li>
    </ul>
</div>

<div class="manual-warn">
    <strong>သတိပြုရန်:</strong> မန်နေဂျာ မဟုတ်သူကို <strong>Admin</strong> အခန်းကဏ္ဍ မပေးပါနှင့် — Admin သည် အားလုံးကို ဖျက်နိုင်၊ ပြင်ဆင်နိုင်သည်
</div>

<h4><i class="bi bi-question-circle me-2"></i>မေးလေ့ရှိသော မေးခွန်းများ</h4>
<dl>
    <dt>မေး: အသုံးပြုသူကို မှားဖျက်မိသည်၊ ပြန်ရနိုင်ပါသလား?</dt>
    <dd>ဖြေ: ဗဟိုအမှိုက်ပုံးသို့ သွားပါ → ပြန်လည်ရယူရန် နှိပ်ပါ (Super Admin သာ)</dd>

    <dt>မေး: အခန်းကဏ္ဍ၏ ခွင့်ပြုချက်များကို ပြောင်းလဲနိုင်ပါသလား?</dt>
    <dd>ဖြေ: UI မှတစ်ဆင့် မရပါ — command line (Tinker) သို့မဟုတ် Seeder ပြင်ဆင်ရန် လိုအပ်သည်</dd>

    <dt>မေး: ကျွန်ုပ်၏ Staff အသုံးပြုသူသည် အချို့မီနူးများကို ဘာကြောင့် ဝင်ရောက်၍မရသနည်း?</dt>
    <dd>ဖြေ: "အခန်းကဏ္ဍနှင့် ခွင့်ပြုချက်များ" အပိုင်းကို စစ်ဆေးပါ — Staff တွင် မည်သည့်ခွင့်ပြုချက်များ ရှိသည်ကို ကြည့်ပါ၊ တစ်ခုခု ချို့တဲ့နေပါက Super Admin ကို ထည့်ပေးရန် တောင်းဆိုပါ</dd>
</dl>
