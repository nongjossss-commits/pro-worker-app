<h4><i class="bi bi-file-earmark-text-fill me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"မှတ်ပုံတင်ဆုံးဖြတ်ချက် (Registration Resolution)"</strong> မီနူးကို
    အစိုးရမှ အချိန်အလိုက် ထုတ်ပြန်သော ရွှေ့ပြောင်းအလုပ်သမား မှတ်ပုံတင်လှည့်ပတ်အသစ်များနှင့် ပတ်သက်သော
    <strong>ကက်ဘိနက် ဆုံးဖြတ်ချက်များ</strong> စီမံရန် အသုံးပြုသည်။
    စနစ်သည် ဖောင်များ၊ အချိန်ဇယားများနှင့် ထိုဆုံးဖြတ်ချက်ထဲသို့ ဝင်ရောက်သော ဝန်ထမ်းများကို သိမ်းဆည်းသည်
</p>

<h4><i class="bi bi-person-check me-2"></i>ဤမီနူးကို မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — အပြည့်အဝ အသုံးပြုနိုင်သည်</li>
    <li><span class="manual-role">Caretaker</span> — နေ့စဉ်အလုပ် (ဝန်ထမ်းအချက်အလက်၊ ချိန်းဆိုမှု) လုပ်နိုင်သော်လည်း လုပ်ငန်းစဉ်ဖွဲ့စည်းပုံ သို့မဟုတ် ငွေကြေးဒေတာကို ပြင်၍မရပါ၊ "တိုးတက်မှုအဆင့် အပ်ဒိတ်" ခွင့်ပြုချက် ရမှသာ အဆင့်များကို အမှန်ခြစ်နိုင်သည်</li>
    <li><span class="manual-role">Employer</span> (ဖောက်သည်အကောင့်) — ဤမီနူးကို ဝင်၍မရပါ</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာ ဘယ်လိုပုံစံရှိသနည်း</h4>
<ol>
    <li><strong>ဆုံးဖြတ်ချက် တဘ်များ</strong> — တဘ်တစ်ခုစီသည် ကက်ဘိနက် ဆုံးဖြတ်ချက် ၁ ခု (ဥပမာ- နိုဝင်ဘာ 2023 ဆုံးဖြတ်ချက်၊ မတ် 2024 ဆုံးဖြတ်ချက်)</li>
    <li><strong>အလုပ်ရှင် ကတ်များ</strong> — ဤဆုံးဖြတ်ချက်တွင် ဝန်ထမ်းရှိသော အလုပ်ရှင်များကို ပြသသည်</li>
    <li><strong>အခြေအနေ စစ်ထုတ်ချက်</strong> — အဆင့်ဖြင့် စစ်ထုတ်နိုင်သည် (ဆိုင်းငံ့ထား၊ ဆောင်ရွက်နေဆဲ၊ ပြီးစီး)</li>
    <li><strong>တိုးတက်မှု စစ်ထုတ်ချက်</strong> — ဗီဇာသာ / နှစ်ခုစလုံး / သက်တမ်းတိုး ဖြင့် စစ်ထုတ်နိုင်သည်</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>အသုံးပြုနည်း</h4>

<h5>၁။ လိုချင်သော ဆုံးဖြတ်ချက် ရွေးရန်</h5>
<div class="manual-step">
    ထိုဆုံးဖြတ်ချက်၏ တဘ်ကို နှိပ်ပါ → ထိုဆုံးဖြတ်ချက်ရှိ အလုပ်ရှင် + ဝန်ထမ်းအားလုံးကို ပြသပါလိမ့်မည်
</div>

<h5>၂။ ဝန်ထမ်းကို ဆုံးဖြတ်ချက်ထဲသို့ မှတ်ပုံတင်ရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>အလုပ်ရှင်၏ ကတ်ကို ဖွင့်ပါ</li>
        <li>"ဝန်ထမ်းကို ဆုံးဖြတ်ချက်ထဲသို့ ထည့်ရန်" ကို နှိပ်ပါ</li>
        <li>ဤဆုံးဖြတ်ချက်တွင် ထည့်လိုသော ဝန်ထမ်းများကို ရွေးပါ</li>
        <li>"အတည်ပြုမည်" ကို နှိပ်ပါ</li>
    </ol>
</div>

<h5>၃။ ဝန်ထမ်းတစ်ဦးစီ၏ အခြေအနေကို ခြေရာခံရန်</h5>
<div class="manual-step">
    ဝန်ထမ်းကတ်များတွင် ပြသည်:
    <ul class="mb-0">
        <li>ပန်းရောင်ပါလ် အပြာ = ဗီဇာသာ (ဗီဇာကိုသာ ဆောင်ရွက်နေခြင်း)</li>
        <li>ပြာရင့်ရင့် = နှစ်ခုစလုံး (ဗီဇာ + အလုပ်လုပ်ခွင့်ပြုချက် ဆောင်ရွက်နေခြင်း)</li>
        <li>အစပ်ခြေ ခမ်းမ = ယခုအထိ ပြီးစီးထားသော အမြင့်ဆုံးအဆင့်</li>
    </ul>
</div>

<h5>၄။ စည်းမျဉ်း များစွာဖြင့် စစ်ထုတ်ရန်</h5>
<div class="manual-step">
    Ctrl/Cmd ကို ဖိထားပြီး အခြေအနေများစွာကို တစ်ပြိုင်နက် ရွေးနိုင်သည် — တိုးတက်မှုအခြေအနေ များစွာဖြင့် တစ်ကြိမ်တည်း စစ်ထုတ်နိုင်သည်
</div>

<h5>၅။ Auto Settings — တဘ်တစ်ခုစီ သတ်မှတ်ခြင်း</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>လိုချင်သော ဆုံးဖြတ်ချက်တဘ်ကို ဖွင့်ပါ → <strong>"Auto Settings"</strong> ကို နှိပ်ပါ</li>
        <li>popup ခေါင်းစီးတွင် <strong>တဘ်အမည်</strong> ပြသသည် + ဤတဘ်တွင်သာ သက်ရောက်ကြောင်း မှတ်ချက်</li>
        <li>Auto WP/Visa Expiry + MOU Group ကို ဖြည့်ပါ → Save</li>
        <li>တဘ်တစ်ခုစီတွင် ကိုယ်ပိုင် သီးခြား Auto Settings ရှိပြီး တစ်ခုနှင့်တစ်ခု ထပ်နေခြင်း မရှိပါ</li>
    </ol>
</div>

<h5>၆။ ဝန်ထမ်းများကို မီနူးထဲသို့ အလိုအလျောက် ဆွဲယူခြင်း (Add-only)</h5>
<div class="manual-step">
    WP သို့မဟုတ် ဗီဇာ သက်တမ်းကုန်ဆုံးရက်သည် Auto Settings နှင့် ကိုက်ညီသော ဝန်ထမ်းသည် <strong>မီနူးထဲသို့ ချက်ချင်း အလိုအလျောက် ဆွဲယူခံရသည်</strong>
    <br>
    မီနူးထဲတွင် ရှိနေပြီးသား ဝန်ထမ်းသည် ရက်စွဲများ update လုပ်ချိန်တွင် <strong>ဘယ်တော့မှ ထုတ်မခံရပါ</strong> — တိုးတက်မှုအလိုက် အရောင်သာ ပြောင်းလဲသည် (none / visa_only / work_permit_only / both)
    <br>
    ကိုယ်တိုင် Finish / Cancel နှိပ်မှသာ ဝန်ထမ်းကို မီနူးမှ ဖယ်ရှားနိုင်သည်
</div>

<h5>၇။ ပြီးသော ဝန်ထမ်းများ ရွေးခြင်းနှင့် ၃ မျိုး အားလုံးရွေး</h5>
<div class="manual-step">
    ပြီးသော ဝန်ထမ်း၏ checkbox ကို ၂၄ နာရီ Undo ကာလအတွင်း ဝှက်ထားပြီး ထို့နောက် ပြန်ပေါ်သည်။ ပြီး/မပြီး ရောနေသော အလုပ်ရှင်တွင် အားလုံးရွေးလျှင် <strong>အားလုံး / ပြီးသူများသာ / မပြီးသေးသူများသာ</strong> ဟု မေးသည် (export၊ အစုလိုက်ပြင်ဆင်၊ ဒေါင်းလုဒ်အတွက်)။
</div>

<h5>၈။ အဖွဲ့ခွဲခြင်း</h5>
<div class="manual-step">
    ဝန်ထမ်းကတ်ပေါ်ရှိ <strong>အဖွဲ့စီမံ</strong> → အဖွဲ့ရွေး သို့မဟုတ် ဖန်တီး (ဥပမာ "အသုတ် ၁")။ အဖွဲ့များကို ဆုံးဖြတ်ချက် tab နှင့် အလုပ်ရှင်အလိုက် သီးခြားထားပြီး အမည်ပြောင်း/ဖျက်မှု ချက်ချင်း သက်ရောက်သည်။
</div>

<h5>၉။ ချိန်းဆိုမှုနှင့် လျှောက်လွှာနံပါတ် tab အလိုက်</h5>
<div class="manual-step">
    ချိန်းဆိုရက်/နေရာ နှင့် လျှောက်လွှာနံပါတ်ကို <strong>ဆုံးဖြတ်ချက် tab အလိုက်</strong> သိမ်းသည် — tab တစ်ခုတွင် သတ်မှတ်ခြင်းသည် အခြား tab သို့မဟုတ် မီနူးတွင် မပေါ်ပါ။
</div>

<h5>၁၀။ Tab အမှတ်အသား ခလုတ် (Super Admin)</h5>
<div class="manual-step">
    Tab ပြင်ဆင်ခလုတ်ဘေးတွင် — ကြိုတင်ပြင်ဆင်ထားပြီး မစတင်ရသေးသော tab အတွက်: ဝန်ထမ်းများ ပုံမှန်လုပ်နိုင်သော်လည်း ကတ်ပေါ်ရှိ "ဆုံးဖြတ်ချက်အုပ်စုတွင်…" အမှတ်အသားနှင့် အသိပေးအမှတ်အသားကို ဝှက်ထားသဖြင့် လက်ရှိအသုတ်နှင့် မရောထွေးပါ။
</div>

<h5>၁၁။ ဝန်ထမ်းများစွာ၏ ပူးတွဲဖိုင် ရွှေ့ခြင်း (Super Admin)</h5>
<div class="manual-step">
    ဝန်ထမ်းများကို ရွေး → <strong>ပူးတွဲဖိုင်ရွှေ့</strong> → လဲလှယ် / ရွှေ့ပြီး မူရင်းဖျက် / <strong>B ထဲ ပေါင်း</strong> (PDF ၂ ခု ပေါင်း)။ ရွေးထားသူများသာ၊ Admin/Staff အချို့ကို ခွင့်ပြုနိုင်သည်။
</div>

<h5>၁၂။ ဘေလ်တင်ပြီးသော tab ကို ဖျက်ခြင်း</h5>
<div class="manual-step">
    Tab ဖျက်လျှင် ၇ ရက် ဝှက်ထားပြီး (ပြန်ယူနိုင်) ထို့နောက် အပြီးဖျက်သည်။ <strong>ဘေလ်ရှိသော</strong> အလုပ်များကို မဖျက်ပါ — ဘေလ်နှင့် ငွေလက်ခံမှတ်တမ်း ကျန်ရှိပြီး ငွေကြေးမီနူးတွင် ဆက်ကောက်ရန် သို့မဟုတ် credit note ထုတ်ရန် ရသည် (အနီရောင် "tab ဖျက်ပြီး" အမှတ်အသား)။
</div>

<h4><i class="bi bi-lightbulb me-2"></i>အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>တိုးတက်မှု badge အရောင်များ:</strong> ဝန်ထမ်းတစ်ဦးစီ မည်သည့်အဆင့်တွင် ရှိသည်ကို လျင်မြန်စွာ မြင်နိုင်ရန် စနစ်သည် အရောင် ၄ မျိုး အသုံးပြုသည်
</div>

<div class="manual-tip">
    <strong>အခြေအနေ စစ်ထုတ်ချက်သည် ကိုက်ညီသည့်အရာများကိုသာ ပြသသည်:</strong> "Visa only" ဖြင့် စစ်ထုတ်ပါက ဗီဇာကိုသာ ဆောင်ရွက်နေသော ဝန်ထမ်းရှိသည့် အလုပ်ရှင်များကိုသာ မြင်ရပါမည်
</div>
<div class="manual-tip">
    <strong>LINE ချက်သို့ ပို့ရန်:</strong> ကတ်ပေါ်ရှိ <i class="bi bi-grid-3x2-gap-fill"></i> ခလုတ်ကို ချက်ထဲ ဆွဲထည့်ပါ သို့မဟုတ် စာသား / ကတ်ပုံ ကူးယူရန် / မျှဝေရန် နှိပ်ပါ — အလုပ်သမား လက်စွဲ အပိုင်း ၁၁ ကို ကြည့်ပါ
</div>

<h4><i class="bi bi-question-circle me-2"></i>မေးလေ့ရှိသော မေးခွန်းများ</h4>
<dl>
    <dt>မေး: ဆုံးဖြတ်ချက်အသစ် ထည့်နိုင်ပါသလား?</dt>
    <dd>ဖြေ: ထည့်နိုင်ပါသည် — Super Admin သည် Resolution Tabs Settings မီနူးမှတစ်ဆင့် ထည့်နိုင်သည်</dd>

    <dt>မေး: ဝန်ထမ်းတစ်ဦးသည် ဆုံးဖြတ်ချက် များစွာတွင် ပါဝင်နိုင်ပါသလား?</dt>
    <dd>ဖြေ: ပါဝင်နိုင်ပါသည် — ဝန်ထမ်းတစ်ဦးသည် ဆုံးဖြတ်ချက် များစွာတွင် ပါဝင်နိုင်ပြီး ပါဝင်သော ဆုံးဖြတ်ချက်တိုင်း၏ ကတ်ပေါ်တွင် ပေါ်လာပါမည်</dd>

    <dt>မေး: အလုပ်ရှင်ကတ် ဘာကြောင့် ပျောက်သွားသနည်း?</dt>
    <dd>ဖြေ: ထိုအလုပ်ရှင်တွင် လက်ရှိစစ်ထုတ်ချက်နယ်ပယ်အတွင်း ဝန်ထမ်း မရှိပါက ၎င်း၏ကတ်ကို မပြသပါ</dd>
</dl>
