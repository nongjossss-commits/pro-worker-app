{{-- User Manual: Notifications (Myanmar) --}}

<h4><i class="bi bi-bell-fill me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"အကြောင်းကြားချက်များ (Notifications)"</strong> မီနူးတွင် စနစ်မှ အလိုအလျောက် ဖန်တီးသော သတိပေးချက်အားလုံး ပါဝင်သည် —
    ဥပမာ- နိုင်ငံကူးလက်မှတ် သက်တမ်းကုန်ဆုံးခါနီး၊ ဗီဇာ သက်တမ်းကုန်ဆုံးခါနီး၊ သတ်မှတ်ရက်နီးလာသော အလုပ်များ၊ အလုပ်ရှင်များထံမှ မက်ဆေ့ချ်အသစ်များ
</p>

<h4><i class="bi bi-person-check me-2"></i>မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<p><code>view-notifications</code> ခွင့်ပြုချက်ရှိသူ မည်သူမဆို</p>

<h4><i class="bi bi-list-check me-2"></i>အသုံးပြုနည်း</h4>

<h5>၁။ အကြောင်းကြားချက်များ ကြည့်ရှုရန်</h5>
<div class="manual-step">
    navbar ရှိ ခေါင်းလောင်း အိုင်ကွန်ကို နှိပ်ပါ သို့မဟုတ် Notifications မီနူးကို ဖွင့်ပါ — အသစ်ဆုံးအရာများကို အရင်ပြသသည်
</div>

<h5>၂။ ဖတ်ပြီးအဖြစ် အမှတ်အသားပြုရန်</h5>
<div class="manual-step">
    အကြောင်းကြားချက်ကို နှိပ်ပါ → စနစ်သည် ဖတ်ပြီးအဖြစ် အလိုအလျောက် အမှတ်အသားပြုပါလိမ့်မည်
</div>

<h5>၃။ အကြောင်းကြားချက် ပယ်ဖျက်/ဖျက်ရန်</h5>
<div class="manual-step">
    အကြောင်းကြားချက်ပေါ်ရှိ X အိုင်ကွန်ကို နှိပ်ပါ — <code>cancel-notifications</code> ခွင့်ပြုချက်ရှိသူများသာ ပြုလုပ်နိုင်သည်
</div>

<h5>၄။ အကြောင်းကြားချက် ရွှေ့ဆိုင်းရန်</h5>
<div class="manual-step">
    အချို့ အကြောင်းကြားချက်များကို ရွှေ့ဆိုင်းနိုင်သည် (ဥပမာ- ဗီဇာသက်တမ်းကုန် သတိပေးချက်ကို ရွှေ့ဆိုင်းခြင်း) — "ရွှေ့ဆိုင်းရန်" ခလုတ်ကို နှိပ်ပါ
</div>

<h4><i class="bi bi-lightbulb me-2"></i>အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>Web Push:</strong> အချိန်နှင့်တပြေးညီ သတိပေးချက်များ ရရှိရန် browser တွင် notification ခွင့်ပြုချက် ဖွင့်ပါ
</div>

<div class="manual-tip">
    <strong>သက်တမ်းကုန်ဆုံးမှု စကင်ဖတ်စနစ်:</strong> စနစ်သည် နံနက်တိုင်း သက်တမ်းကုန်ဆုံးရက်များကို စကင်ဖတ်သည် (CheckExpiries cron job) — အကြောင်းကြားချက်အသစ်များကို အလိုအလျောက် ဖန်တီးပေးသည်
</div>
