<h4><i class="bi bi-cash-coin me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"ငွေကြေး (Finance)"</strong> မီနူးသည် ရုံး၏ အဓိက စာရင်းကိုင်/ငွေကြေး စင်တာ ဖြစ်သည် —
    Ledger၊ အခွန်ဘေဂျင်များ၊ ရင်းမြစ်မှနုတ်ယူသော အခွန် (WHT) ထုတ်ပေးခြင်း၊
    အခွန်အစီရင်ခံစာများ (ภ.พ.30၊ ภ.ง.ด.3/53)၊ ဘဏ်ချိန်ညှိခြင်းနှင့် လုပ်ဆောင်ချက် မှတ်တမ်း တို့ ပါဝင်သည်
</p>

<h4><i class="bi bi-person-check me-2"></i>ဤမီနူးကို မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> — အပြည့်အဝ အသုံးပြုနိုင်သည်</li>
    <li><span class="manual-role">Staff</span> — တစ်စိတ်တစ်ပိုင်း အသုံးပြုနိုင်သည် (<code>manage-finance</code> ခွင့်ပြုချက်အပေါ် မူတည်သည်)</li>
    <li><span class="manual-role">Caretaker</span> <span class="manual-role">Employer</span> — ခွင့်ပြုချက် မရှိပါ</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>Finance မီနူး၏ အပိုင်းများ</h4>
<ol>
    <li><strong>Ledger</strong> — ဝင်ငွေ/အသုံးစရိတ် အားလုံးကို ရက်စွဲအလိုက် မှတ်တမ်းတင်သည်</li>
    <li><strong>အခွန်ဘေဂျင်များ</strong> — အခွန်ဘေဂျင် ဖန်တီး/ကြည့်ရှု/ပရင့်ထုတ် + ငွေပေးချေမှု နည်းလမ်းများ</li>
    <li><strong>WHT (ရင်းမြစ်မှနုတ်ယူသော အခွန်)</strong> — ရရှိသော WHT 3%/5% မှတ်တမ်းတင်ခြင်း + စာရွက်စာတမ်း ထုတ်ပေးခြင်း</li>
    <li><strong>အခွန်အစီရင်ခံစာများ</strong> — ภ.พ.30 + ภ.ง.ด.3/53 — အခွန်တင်သွင်းရန် လစဉ် အနှစ်ချုပ်များ</li>
    <li><strong>ဘဏ်ချိန်ညှိခြင်း</strong> — ဘဏ်အကောင့်လက်ကျန်ကို စနစ်မှတ်တမ်းနှင့် ချိန်ညှိသည်</li>
    <li><strong>လုပ်ဆောင်ချက် မှတ်တမ်း</strong> — ငွေကြေးဒေတာ ပြောင်းလဲမှု မှတ်တမ်း အပြည့်အစုံ ကြည့်ရှုနိုင်သည်</li>
    <li><strong>လစဉ် အစုအဝေး</strong> — လကုန်ပိတ်ရန် စာရွက်စာတမ်းအားလုံးကို ZIP အဖြစ် ဒေါင်းလုဒ်ဆွဲနိုင်သည်</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>အသုံးများသော လုပ်ဆောင်ချက်များ</h4>

<h5>၁။ ဝင်ငွေအသစ် မှတ်တမ်းတင်ရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>Ledger သို့ သွားပါ → "+ မှတ်တမ်းတင်ရန်" ကို နှိပ်ပါ</li>
        <li>"ဝင်ငွေ" ကို ရွေးပါ</li>
        <li>ရက်စွဲ၊ ဖောက်သည်၊ ပမာဏ၊ VAT အမျိုးအစား ဖြည့်ပါ</li>
        <li>ရှိပါက ငွေလွှဲချလွှာပုံ ပူးတွဲပါ</li>
        <li>"သိမ်းမည်" ကို နှိပ်ပါ</li>
    </ol>
</div>

<h5>၂။ အခွန်ဘေဂျင် ဖန်တီးရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>အခွန်ဘေဂျင်များသို့ သွားပါ → "+ အသစ်ဖန်တီးရန်" ကို နှိပ်ပါ</li>
        <li><strong>ထုတ်ပေးသူ ပရိုဖိုင်</strong> (ကျွန်ုပ်တို့ ရုံး) ကို ရွေးပါ</li>
        <li>ဖောက်သည်အမည် + အခွန် ID + လိပ်စာ ဖြည့်ပါ</li>
        <li>ပမာဏ + VAT နှုန်း (ပုံမှန် 7%) ဖြည့်ပါ</li>
        <li>ငွေပေးချေမှု နည်းလမ်း အမှန်ခြစ်ပါ (ငွေသား၊ ငွေလွှဲ၊ PromptPay)</li>
        <li>"ငွေလွှဲ" ကို ရွေးပါက — ပရိုဖိုင်မှ ဘဏ်အကောင့် ရွေးပါ</li>
        <li>"သိမ်းပြီး ထုတ်ပေးမည်" ကို နှိပ်ပါ — စနစ်သည် ဘေဂျင်နံပါတ်ကို လော့ခ်ချပြီး PDF ထုတ်ပေးပါမည်</li>
    </ol>
</div>

<h5>၃။ လစဉ် အခွန်အစီရင်ခံစာ ထုတ်ရန်</h5>
<div class="manual-step">
    အခွန်အစီရင်ခံစာများသို့ သွားပါ → လ ရွေးပါ → ภ.พ.30 သို့မဟုတ် ภ.ง.ด.3/53 ဒေါင်းလုဒ်ဆွဲပါ
</div>

<h5>၄။ ဘဏ် ချိန်ညှိရန်</h5>
<div class="manual-step">
    ဘဏ်ချိန်ညှိခြင်းသို့ သွားပါ → ဘဏ်ရှင်းတမ်း တင်ပါ → စနစ်သည် စနစ်မှတ်တမ်းနှင့် အလိုအလျောက် ကိုက်ညီစေပါမည်
</div>

<h5>၅။ လကုန်ပိတ်ရန် (လစဉ် အစုအဝေး)</h5>
<div class="manual-step">
    လစဉ် အစုအဝေးသို့ သွားပါ → လ ရွေးပါ → "ထုတ်ပေးမည်" ကို နှိပ်ပါ → ထိုလ၏ စာရွက်စာတမ်းအားလုံး ပါဝင်သော ZIP ဒေါင်းလုဒ်ဆွဲပါ
</div>

<h5>၆။ ခြုံငုံကြည့်ရှုမှုနှင့် စာရင်းအင်းကတ်များ (နှိပ်၍ စစ်ထုတ်နိုင်)</h5>
<div class="manual-step">
    ကတ် ၄ ခု: <strong>ယနေ့ / ဤလ ဝင်ငွေ</strong> = ထိုနေ့/လတွင် အမှန်တကယ် ရရှိသောငွေ၊ ငွေလက်ခံသည့် ရက်အလိုက် တွက်သည် (ယခင်လ တစ်စိတ်တစ်ပိုင်းပေးပြီး ဤလ ကျန်ငွေပေးသော ဘေလ်ကို လအလိုက် မှန်ကန်စွာ ခွဲပြီး ထပ်မတွက်ပါ)၊ <strong>ဆောင်ရွက်ရန်ကျန်ငွေ</strong> = မပေးရသေး/တစ်စိတ်ပေးပြီး ဘေလ်များ၏ ကျန်ငွေ၊ <strong>သတ်မှတ်ရက်ကျော်ငွေ</strong> = ရက်ကျော်အဖြစ် မှတ်ထားသော ဘေလ်များ၏ ကျန်ငွေ။ <strong>ကတ်ကိုနှိပ်</strong>လျှင် ထိုဂဏန်းနောက်ကွယ်ရှိ ဘေလ်များသာ ပြသည် (ထပ်နှိပ်လျှင် ပယ်ဖျက်)။ ဝင်ငွေကတ်တွင် "ပေးပြီး" အောက်၌ ငွေလက်ခံမှုတိုင်းကို ပြသည် — စာလုံးထူ = ဤကာလ၊ မှိန် = အခြားကာလ။ စစ်ထုတ်ရလဒ်အကျဉ်းရှိ "ဤကာလအတွင်း လက်ခံငွေ" သည် ကတ်ဂဏန်းနှင့် တူညီသည်။ ဈေးနှုန်းကမ်းလှမ်းချက်များကို မတွက်ပါ။
</div>

<h5>၇။ ဘေလ်၏ မူလအရင်းအမြစ် — အမှတ်အသားနှင့် filter</h5>
<div class="manual-step">
    အလုပ်ရှင်/ပရောဂျက်အမည်အောက်တွင် မူလအရင်းအမြစ် အမှတ်အသား ပြသည်၊ ဥပမာ <code>Workflow › MOU သက်တမ်းတိုး</code>၊ <code>သက်တမ်းတိုးဆုံးဖြတ်ချက် › Tab X</code>၊ <code>Manual ဘေလ်</code>။ မူလ tab ဖျက်ပြီးပါက အမှတ်အသားသည် <strong>အနီရောင်</strong> ("tab ဖျက်ပြီး" + ရက်စွဲ) ဖြစ်သည် — ဘေလ်သည် အမှန်တကယ်ဖြစ်ဆဲ၊ ငွေဆက်ကောက်ရန် သို့မဟုတ် credit note ထုတ်ရန် ဆုံးဖြတ်ပါ။ <strong>မူလအရင်းအမြစ်</strong> filter: အားလုံး / အသုံးပြုနေသော tab မှ / ဖျက်ပြီး tab မှ။ ဖျက်ပြီး tab မှ မပေးရသေးသော ဘေလ်ရှိပါက အနီရောင် သတိပေးဘား ပေါ်သည်။
</div>

<h5>၈။ လုပ်ငန်းမီနူးအလိုက် tab များ</h5>
<div class="manual-step">
    <strong>Workflow နှင့် Pre-Production</strong>၊ <strong>မှတ်ပုံတင်ဆုံးဖြတ်ချက်</strong>၊ <strong>သက်တမ်းတိုးဆုံးဖြတ်ချက်</strong> tab များတွင် အလုပ်ရှင်အလိုက် စုစုပေါင်း / ဘေလ်တင်ပြီး / ကျန်ငွေ ပြသည်၊ <strong>ငွေကြေးစီမံ</strong> ဖြင့် ဈေးသတ်မှတ်၊ ဘေလ်တင်၊ ငွေလက်ခံ လုပ်နိုင်သည်။ <strong>Manual ဘေလ်</strong> နှင့် <strong>ဈေးနှုန်းကမ်းလှမ်းချက်</strong> tab များ သီးခြားဖြစ်ပြီး ဈေးနှုန်းမှတ်တမ်းသည် ဘေလ်အစစ်နှင့် မရောပါ။
</div>

<h5>၉။ ငွေလက်ခံခြင်း (Payment History)</h5>
<div class="manual-step">
    ဘေလ်ဖွင့် → <strong>ပမာဏ</strong>၊ <strong>ငွေလက်ခံရက်</strong>၊ <strong>လက်ခံအကောင့်</strong> ထည့်ပြီး slip တွဲပါ။ အရစ်ကျ အကြိမ်ကြိမ် လက်ခံနိုင်ပြီး အခြေအနေသည် "တစ်စိတ်ပေးပြီး"/"ပေးပြီး" သို့ အလိုအလျောက် ပြောင်းသည် (credit note ပါ တွက်)။ အကောင့်မရွေးလျှင် ဘဏ်လက်ကျန်ထဲ <strong>မဝင်</strong>သဖြင့် အတည်ပြုခိုင်းသည်။ အကောင့်ရွေးထားသော ငွေလက်ခံမှုကို လက်ခံရက်အလိုက် Ledger ထဲ မှတ်သည်။
</div>

<h5>၁၀။ Credit Note (ကြွေးလျှော့စာ)</h5>
<div class="manual-step">
    ထုတ်ပြီး ဘေလ်၏ ပမာဏကို လျှော့ရန် (လျှော့ဈေး သို့မဟုတ် ကျန်ငွေကို မကောက်တော့ခြင်း): <strong>Credit Notes</strong> → <strong>အသစ်</strong> → ဘေလ်၊ ပမာဏ၊ အကြောင်းပြချက် (မူကြမ်းအဖြစ် သိမ်း) → <strong>ထုတ်ပေး</strong> ဖြင့် နံပါတ်ကို ပိတ်ပြီး ကျန်ငွေကို ချက်ချင်း လျှော့သည်။ မှားထုတ်လျှင် <strong>Void</strong>၊ မူကြမ်းကို ဖျက်နိုင်သည်။ Credit note များကို လစဉ်အစုအဝေးတွင် ထည့်သွင်းသည်။
</div>

<h5>၁၁။ Manual ဘေလ် ဖန်တီးခြင်း</h5>
<div class="manual-step">
    <strong>စာရွက်စာတမ်း အမျိုးအစား</strong> ကို ဦးစွာရွေး: <strong>ဈေးနှုန်းကမ်းလှမ်းချက်</strong> (အလုပ်ရှင် မလိုအပ်) သို့မဟုတ် <strong>Invoice</strong> (အလုပ်ရှင် လိုအပ်)။ <strong>မူကြမ်းဝန်ထမ်း</strong> ထည့်နိုင်သည် (ဝန်ထမ်းအစစ် မဖန်တီးဘဲ အမည်/နိုင်ငံသား/ပတ်စ်ပို့/ဓာတ်ပုံ — manual ဘေလ်အတွက်သာ)။ ဈေးနှုန်းကမ်းလှမ်းချက်တွင် <strong>စုစုပေါင်း</strong> ပြရန် သို့မဟုတ် ယူနစ်ဈေးသာ ပြရန် ရွေးနိုင်သည်။ စာရွက်တိုင်းတွင် သတ်မှတ်ထားသော VAT/WHT မှတ်ချက် ပါသည်။
</div>

<h5>၁၂။ လစဉ်အစီရင်ခံစာ</h5>
<div class="manual-step">
    <strong>လစဉ်အစီရင်ခံစာ</strong> → လ/ဘေလ်ထုတ်သူ → ZIP (CSV + slip + WHT စာရွက်)။ ဝင်ငွေကို <strong>ငွေလက်ခံမှု တစ်ကြိမ်လျှင် တစ်တန်း</strong>၊ အမှန်လက်ခံရက်အလိုက် ပြသည် — လများစွာ ပေးသော ဘေလ်သည် လတိုင်း၏ အစီရင်ခံစာတွင် ပေါ်သည်။ ဘေလ်၏ WHT ကို နောက်ဆုံးအရစ်တန်းတွင် တစ်ကြိမ်သာ ပြသည်။ ဈေးနှုန်းကမ်းလှမ်းချက် မပါဝင်ပါ။
</div>

<h4><i class="bi bi-lightbulb me-2"></i>အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>VAT 7%:</strong> ထိုင်းနိုင်ငံ၏ မူလနှုန်း ဖြစ်ပြီး ဒဿမနေရာ ၂ နေရာသို့ ရေတိုင်းသည်
</div>

<div class="manual-tip">
    <strong>WHT 3% vs 5%:</strong> 3% = ယေဘုယျ ဝန်ဆောင်မှုကြေး၊ 5% = ပစ္စည်း/ပုဂ္ဂိုလ်ရေး ငှားရမ်းခ
</div>

<div class="manual-warn">
    <strong>ထုတ်ပေးပြီးသား အခွန်ဘေဂျင်ကို ပြင်ဆင်၍မရပါ:</strong> ဥပဒေအရ ပြောင်းလဲ၍မရပါ — ပယ်ဖျက်ပြီး အသစ်ထုတ်ပေးရမည်
</div>

<h4><i class="bi bi-question-circle me-2"></i>မေးလေ့ရှိသော မေးခွန်းများ</h4>
<dl>
    <dt>မေး: ဘဏ်အကောင့် ရွေးစရာ မတွေ့ပါ?</dt>
    <dd>ဖြေ: ငွေကြေးပရိုဖိုင်တွင် ဘဏ်အကောင့် အရင်ဖန်တီးရမည် — Financial Profiles သို့ သွားပါ → ပရိုဖိုင် ရွေးပါ → အကောင့် ထည့်ပါ</dd>

    <dt>မေး: အခွန်ဘေဂျင် နံပါတ်များသည် အစဉ်လိုက် ဖြစ်ပါသလား?</dt>
    <dd>ဖြေ: အစဉ်လိုက် ဖြစ်ပါသည် — စနစ်သည် အခွန်နှစ်တစ်ခုတည်းအတွင်း နောက်ဆုံးဘေဂျင်မှ ဆက်လက်ရေတွက်ပြီး ကျန်ရစ်ခြင်း မရှိပါ</dd>

    <dt>မေး: မှားယွင်းစွာ ထုတ်ပေးမိသော အခွန်ဘေဂျင်ကို ဖျက်နိုင်ပါသလား?</dt>
    <dd>ဖြေ: <strong>ပယ်ဖျက် (Void)</strong> နိုင်သည်၊ တကယ်တမ်း ဖျက်၍မရပါ — အစီအစဉ်ကို ထိန်းသိမ်းရန် ဘေဂျင်နံပါတ်ကို စနစ်တွင် ဆက်ထားပါမည်</dd>
</dl>
