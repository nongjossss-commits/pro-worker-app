<h4><i class="bi bi-journal-text me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"လုပ်ဆောင်ချက် မှတ်တမ်းများ (Activity Logs)"</strong> မီနူးသည် စနစ်တွင် ဖြစ်ပေါ်သော
    <strong>ပြောင်းလဲမှု တိုင်း</strong>ကို မှတ်တမ်းတင်သည် — မည်သူ မည်သည့်အရာ မည်သည့်အချိန်တွင် လုပ်ဆောင်သနည်း။
    <strong>စစ်ဆေးရေး + အတည်ပြုရေး</strong> အတွက် အသုံးပြုသည်၊ ဥပမာ- ဤအလုပ်ရှင်ကို မည်သူဖျက်ခဲ့သည်၊ စျေးနှုန်းကို မည်သူပြောင်းလဲခဲ့သည်၊ ဝန်ထမ်း၏ အခြေအနေကို မည်သူပြောင်းလဲခဲ့သည်
</p>

<h4><i class="bi bi-person-check me-2"></i>မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> — ဝင်ရောက်နိုင်သည်</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာ ဘယ်လိုပုံစံရှိသနည်း</h4>
<ol>
    <li><strong>စစ်ထုတ်ရေး</strong> — ရက်စွဲ၊ အသုံးပြုသူ၊ လုပ်ဆောင်ချက်အမျိုးအစား (ဖန်တီး / ပြင်ဆင် / ဖျက်) အလိုက်</li>
    <li><strong>မှတ်တမ်းဇယား</strong> — ရက်စွဲ/အချိန်၊ အသုံးပြုသူ၊ လုပ်ဆောင်ချက်၊ ပြောင်းလဲသော အရာ</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>အသုံးပြုနည်း</h4>

<h5>မည်သူ မည်သည့်အရာ ပြောင်းလဲခဲ့သည်ကို ရှာဖွေရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>ရက်စွဲအပိုင်းအခြား ရွေးပါ (မှ-သို့)</li>
        <li>လိုအပ်ပါက အသုံးပြုသူ ရွေးပါ</li>
        <li>လုပ်ဆောင်ချက်အမျိုးအစား ရွေးပါ</li>
        <li>"ရှာဖွေရန်" ကို နှိပ်ပါ — ဇယားသည် ကိုက်ညီသော မှတ်တမ်းများကိုသာ ပြသပါလိမ့်မည်</li>
    </ol>
</div>

<h4><i class="bi bi-lightbulb me-2"></i>အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>စစ်ဆေးရေးသည် သင့်သက်သေခံချက် ဖြစ်သည်:</strong> Activity Log ကို ဥပဒေရေးရာ သက်သေခံအဖြစ် အသုံးပြုနိုင်သည် — စနစ်သည် ၎င်းကို အလိုအလျောက် ဖျက်ခြင်း လုံးဝ မပြုပါ
</div>
