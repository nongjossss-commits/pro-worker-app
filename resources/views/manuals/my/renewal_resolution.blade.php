<h4><i class="bi bi-arrow-clockwise me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"သက်တမ်းတိုးဆုံးဖြတ်ချက် (Renewal Resolution)"</strong> မီနူးသည်
    အလုပ်လုပ်ခွင့်ပြုချက် သက်တမ်းတိုးခြင်း၊ ဗီဇာ သက်တမ်းတိုးခြင်း၊ MOU သက်တမ်းတိုးခြင်းကဲ့သို့သော
    ရွှေ့ပြောင်းအလုပ်သမား စာရွက်စာတမ်း <strong>သက်တမ်းတိုးရေး</strong>နှင့် ပတ်သက်သော <strong>ကက်ဘိနက် ဆုံးဖြတ်ချက်များ</strong>ကို စီမံသည်
</p>
<p>
    <strong>Registration Resolution</strong> ကဲ့သို့ ဖြစ်သော်လည်း — စနစ်ထဲတွင် ရှိပြီးသား အလုပ်သမားများကို သက်တမ်းတိုးရန်သာ အာရုံစိုက်သည်၊ လူသစ် မှတ်ပုံတင်ခြင်း မဟုတ်ပါ
</p>

<h4><i class="bi bi-person-check me-2"></i>ဤမီနူးကို မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — ဝင်ရောက်နိုင်သည်</li>
    <li><span class="manual-role">Caretaker</span> — နေ့စဉ်အလုပ် (ဝန်ထမ်းအချက်အလက်၊ ချိန်းဆိုမှု) လုပ်နိုင်သော်လည်း လုပ်ငန်းစဉ်ဖွဲ့စည်းပုံ သို့မဟုတ် ငွေကြေးဒေတာကို ပြင်၍မရပါ၊ "တိုးတက်မှုအဆင့် အပ်ဒိတ်" ခွင့်ပြုချက် ရမှသာ အဆင့်များကို အမှန်ခြစ်နိုင်သည်</li>
    <li><span class="manual-role">Employer</span> (ဖောက်သည်အကောင့်) — ဤမီနူးကို ဝင်၍မရပါ</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာ ဘယ်လိုပုံစံရှိသနည်း</h4>
<ol>
    <li><strong>သက်တမ်းတိုးဆုံးဖြတ်ချက် တဘ်များ</strong> — တဘ်တစ်ခုစီသည် သက်တမ်းတိုးလှည့်ပတ်တစ်ခု (ဥပမာ- "2024 သက်တမ်းတိုး လှည့်ပတ် 1")</li>
    <li><strong>အလုပ်ရှင် + ဝန်ထမ်း ကတ်များ</strong> — Registration Resolution နှင့် တူညီသော ယန္တရားကို အသုံးပြုသည်</li>
    <li><strong>တိုးတက်မှု စစ်ထုတ်ချက်</strong> — ဗီဇာသာ၊ အလုပ်လုပ်ခွင့်ပြုချက်သာ၊ နှစ်ခုစလုံး</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>အသုံးပြုနည်း</h4>

<h5>၁။ သက်တမ်းတိုးဆုံးဖြတ်ချက် ရွေးရန်</h5>
<div class="manual-step">
    လိုချင်သော ဆုံးဖြတ်ချက်၏ တဘ်ကို နှိပ်ပါ
</div>

<h5>၂။ ဝန်ထမ်းကို ဆုံးဖြတ်ချက်ထဲသို့ မှတ်ပုံတင်ရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>အလုပ်ရှင်၏ ကတ်ကို ဖွင့်ပါ</li>
        <li>"ဝန်ထမ်းကို ဆုံးဖြတ်ချက်ထဲသို့ ထည့်ရန်" ကို နှိပ်ပါ</li>
        <li><strong>သက်တမ်းကုန်ဆုံးခါနီး</strong> ဝန်ထမ်းများကို ရွေးပါ (စနစ်က ၎င်းတို့ကို မီးမောင်းထိုးပြပါလိမ့်မည်)</li>
        <li>"အတည်ပြုမည်" ကို နှိပ်ပါ</li>
    </ol>
</div>

<h5>၃။ ခြုံငုံသုံးသပ် တိုးတက်မှု ကြည့်ရှုရန်</h5>
<div class="manual-step">
    အပေါ်ရှိ အနှစ်ချုပ်ကတ်တွင် ပြသသည်: ဤဆုံးဖြတ်ချက်ရှိ ဝန်ထမ်းစုစုပေါင်း၊ ပြီးစီးပြီးသူ၊ ကျန်ရှိနေသူ
</div>

<h5>၄။ တိုးတက်မှု အပ်ဒိတ်</h5>
<div class="manual-step">
    Workflow မှ ၂၄ နာရီတိုင်း အလိုအလျောက် ဆွဲယူခြင်း မရှိတော့ပါ — အသုံးပြုသူများက အရောင်စနစ်ဖြင့် ဝန်ထမ်းတစ်ဦးချင်း၏ တိုးတက်မှုကို အမှန်ခြစ်သည်။ <strong>Auto Settings</strong> က ဝန်ထမ်းကို ပြီးကြောင်း မှတ်ပြီး ၂၄ နာရီအကြာတွင် သက်တမ်းကုန်ရက်များကို အလိုအလျောက် အပ်ဒိတ်လုပ်သည်။
</div>

<h5>၅။ Auto Settings — တဘ်တစ်ခုစီ သတ်မှတ်ခြင်း</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>လိုချင်သော ဆုံးဖြတ်ချက်တဘ်ကို ဖွင့်ပါ → ညာဘက်အပေါ်ထောင့်ရှိ <strong>"Auto Settings"</strong> ကို နှိပ်ပါ</li>
        <li>popup ခေါင်းစီးတွင် <strong>တဘ်အမည်</strong> ပြသသည် (ဥပမာ- "31/03/2026") + ဤဆက်တင်သည် ဤတဘ်တွင်သာ သက်ရောက်ကြောင်း မှတ်ချက်</li>
        <li>အောက်ပါတို့ကို ဖြည့်ပါ:
            <ul>
                <li><strong>Auto Work Permit Expiry Date</strong> — ရည်မှန်းထားသော WP သက်တမ်းကုန်ဆုံးရက်</li>
                <li><strong>Auto Visa Expiry Date</strong> — ရည်မှန်းထားသော ဗီဇာ သက်တမ်းကုန်ဆုံးရက်</li>
                <li><strong>Auto MOU Group</strong> — ရည်မှန်းထားသော MOU အုပ်စု</li>
            </ul>
        </li>
        <li>Save ကို နှိပ်ပါ → <strong>ဤတဘ်တွင်သာ</strong> သက်ရောက်ပြီး အခြားတဘ်များကို မထိခိုက်ပါ</li>
        <li>တဘ်တစ်ခုစီတွင် ကိုယ်ပိုင် Auto Settings ရှိသည် — 31/03/2026 တဘ်ရှိ ဝန်ထမ်းများသည် ထိုတဘ်၏ ဆက်တင်များအတိုင်း အရောင်/တိုးတက်မှု ဆန်းစစ်ခြင်းခံရသည်၊ အခြားတဘ်၏ ဆက်တင် မဟုတ်ပါ</li>
    </ol>
</div>

<h5>၆။ ဝန်ထမ်း တိုးတက်မှု အရောင်စနစ်</h5>
<div class="manual-step">
    ကတ်တစ်ခုစီရှိ ဝန်ထမ်းများသည် Auto Settings အပေါ်မူတည်၍ တိုးတက်မှုပြသော အရောင် ရရှိသည်:
    <ul class="mb-0">
        <li>⚪ <strong>none</strong> = မသက်တမ်းတိုးရသေးပါ</li>
        <li>🟦 <strong>visa_only</strong> = ဗီဇာ သက်တမ်းတိုးပြီး (WP စောင့်ဆိုင်းနေဆဲ)</li>
        <li>🟧 <strong>work_permit_only</strong> = WP သက်တမ်းတိုးပြီး (ဗီဇာ စောင့်ဆိုင်းနေဆဲ)</li>
        <li>🟩 <strong>both</strong> = အပြည့်အဝ သက်တမ်းတိုးပြီး၊ ပိတ်ရန် အသင့်ဖြစ်</li>
        <li>✅ <strong>completed</strong> = ပိတ်ပြီး</li>
    </ul>
</div>

<h5>၇။ ဝန်ထမ်းများကို မီနူးထဲသို့ အလိုအလျောက် ဆွဲယူခြင်း</h5>
<div class="manual-step">
    WP သို့မဟုတ် ဗီဇာ သက်တမ်းကုန်ဆုံးရက်သည် တဘ်တစ်ခု၏ Auto Settings နှင့် ကိုက်ညီသော ဝန်ထမ်းသည် ရက်စွဲကို update လုပ်ချိန်တိုင်း <strong>ထိုတဘ်ထဲသို့ ချက်ချင်း အလိုအလျောက် ဆွဲယူခံရသည်</strong>
    <br>
    <strong>"Add-only" စနစ်:</strong> မီနူးထဲတွင် ရှိနေပြီးသား ဝန်ထမ်းသည် ရက်စွဲများ update လုပ်ချိန်တွင် <strong>ဘယ်တော့မှ ထုတ်မခံရပါ</strong> — တိုးတက်မှုအလိုက် အရောင်သာ ပြောင်းလဲသည် (ကိုယ်တိုင် ပြီးစီးရန် သို့မဟုတ် ပယ်ဖျက်ရန် နှိပ်မှသာ ဖယ်ရှားနိုင်သည်)
</div>

<h5>၈။ ပြီးသော ဝန်ထမ်းများ ရွေးခြင်းနှင့် ၃ မျိုး အားလုံးရွေး</h5>
<div class="manual-step">
    ပြီးသော ဝန်ထမ်း၏ checkbox ကို ၂၄ နာရီ Undo ကာလအတွင်း ဝှက်ထားပြီး ထို့နောက် ပြန်ပေါ်သည်။ ပြီး/မပြီး ရောနေသော အလုပ်ရှင်တွင် အားလုံးရွေးလျှင် <strong>အားလုံး / ပြီးသူများသာ / မပြီးသေးသူများသာ</strong> ဟု မေးသည် (export၊ အစုလိုက်ပြင်ဆင်၊ ဒေါင်းလုဒ်အတွက်)။
</div>

<h5>၉။ အဖွဲ့ခွဲခြင်း</h5>
<div class="manual-step">
    ဝန်ထမ်းကတ်ပေါ်ရှိ <strong>အဖွဲ့စီမံ</strong> → အဖွဲ့ရွေး သို့မဟုတ် ဖန်တီး (ဥပမာ "အသုတ် ၁")။ အဖွဲ့များကို ဆုံးဖြတ်ချက် tab နှင့် အလုပ်ရှင်အလိုက် သီးခြားထားပြီး အမည်ပြောင်း/ဖျက်မှု ချက်ချင်း သက်ရောက်သည်။
</div>

<h5>၁၀။ ချိန်းဆိုမှုနှင့် လျှောက်လွှာနံပါတ် tab အလိုက်</h5>
<div class="manual-step">
    ချိန်းဆိုရက်/နေရာ နှင့် လျှောက်လွှာနံပါတ်ကို <strong>ဆုံးဖြတ်ချက် tab အလိုက်</strong> သိမ်းသည် — tab တစ်ခုတွင် သတ်မှတ်ခြင်းသည် အခြား tab သို့မဟုတ် မီနူးတွင် မပေါ်ပါ။
</div>

<h5>၁၁။ Tab အမှတ်အသား ခလုတ် (Super Admin)</h5>
<div class="manual-step">
    Tab ပြင်ဆင်ခလုတ်ဘေးတွင် — ကြိုတင်ပြင်ဆင်ထားပြီး မစတင်ရသေးသော tab အတွက်: ဝန်ထမ်းများ ပုံမှန်လုပ်နိုင်သော်လည်း ကတ်ပေါ်ရှိ "ဆုံးဖြတ်ချက်အုပ်စုတွင်…" အမှတ်အသားနှင့် အသိပေးအမှတ်အသားကို ဝှက်ထားသဖြင့် လက်ရှိအသုတ်နှင့် မရောထွေးပါ။
</div>

<h5>၁၂။ ဝန်ထမ်းများစွာ၏ ပူးတွဲဖိုင် ရွှေ့ခြင်း (Super Admin)</h5>
<div class="manual-step">
    ဝန်ထမ်းများကို ရွေး → <strong>ပူးတွဲဖိုင်ရွှေ့</strong> → လဲလှယ် / ရွှေ့ပြီး မူရင်းဖျက် / <strong>B ထဲ ပေါင်း</strong> (PDF ၂ ခု ပေါင်း)။ ရွေးထားသူများသာ၊ Admin/Staff အချို့ကို ခွင့်ပြုနိုင်သည်။
</div>

<h5>၁၃။ ဘေလ်တင်ပြီးသော tab ကို ဖျက်ခြင်း</h5>
<div class="manual-step">
    Tab ဖျက်လျှင် ၇ ရက် ဝှက်ထားပြီး (ပြန်ယူနိုင်) ထို့နောက် အပြီးဖျက်သည်။ <strong>ဘေလ်ရှိသော</strong> အလုပ်များကို မဖျက်ပါ — ဘေလ်နှင့် ငွေလက်ခံမှတ်တမ်း ကျန်ရှိပြီး ငွေကြေးမီနူးတွင် ဆက်ကောက်ရန် သို့မဟုတ် credit note ထုတ်ရန် ရသည် (အနီရောင် "tab ဖျက်ပြီး" အမှတ်အသား)။
</div>

<h5>၁၄။ မှတ်ပုံတင်ဆုံးဖြတ်ချက်မှ ဝန်ထမ်းများ (နှစ်နေရာ ပြသ)</h5>
<div class="manual-step">
    မှတ်ပုံတင်ဆုံးဖြတ်ချက်ထဲ ရှိဆဲ ဝန်ထမ်း၏ ဗီဇာ/အလုပ်ပါမစ် သက်တမ်းကုန်ရက်သည် ဤသက်တမ်းတိုး tab ၏ ပစ်မှတ်ရက်နှင့် တူပါက <strong>"From Registration Resolution"</strong> အမှတ်အသားဖြင့် ဤနေရာတွင်လည်း ပေါ်သည် — မှတ်ပုံတင်အခြေအနေကို မပြောင်းဘဲ အမှန်ခြစ်/ပြီး/ပယ်/ပြန်ယူ လွတ်လပ်စွာ လုပ်နိုင်သည် (ဤကတ်များတွင် ဖျက်ခလုတ် ဝှက်ထားသည်)။
</div>

<h5>၁၅။ ဝန်ထမ်းထည့်နည်း ၃ မျိုး</h5>
<div class="manual-step">
