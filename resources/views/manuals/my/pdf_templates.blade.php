<h4><i class="bi bi-file-earmark-pdf-fill me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"PDF နမူနာများ (PDF Templates)"</strong> မီနူးကို အလုပ်ခန့်စာချုပ်၊ အလုပ်လက်မှတ်ကဲ့သို့သော
    စာရွက်စာတမ်းအမျိုးမျိုးအတွက် <strong>PDF နမူနာများ</strong> ဖန်တီးရန် အသုံးပြုသည်။
    တင်ထားသော PDF နမူနာပေါ်တွင် ဒေတာကွက်လပ်များကို <strong>ဆွဲယူထည့်သွင်း</strong>ခြင်းဖြင့်
    အမှန်စာရွက်စာတမ်း ဖန်တီးသောအခါ စနစ်သည် ဒေတာကို အလိုအလျောက် ဖြည့်ပေးသည်
</p>

<h4><i class="bi bi-person-check me-2"></i>ဤမီနူးကို မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> — အပြည့်အဝ အသုံးပြုနိုင်သည်</li>
    <li><span class="manual-role">Staff</span> — နမူနာများကို ကြည့်ရှု + အသုံးပြုနိုင်သည် (<code>view-pdf-templates</code> ခွင့်ပြုချက်)</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာ ဘယ်လိုပုံစံရှိသနည်း</h4>
<ol>
    <li><strong>နမူနာစာရင်း</strong> — ဖန်တီးထားသော နမူနာအားလုံးကို ပြသသည်</li>
    <li><strong>"+ နမူနာအသစ်"</strong> ခလုတ်</li>
    <li>(နမူနာကို ဖွင့်သောအခါ) <strong>ပြင်ဆင်ရေး စာမျက်နှာ</strong> — PDF အစမ်းကြည့်ချက် + ဆွဲယူနိုင်သော ကွက်လပ်စာရင်း</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>အသုံးပြုနည်း</h4>

<h5>၁။ နမူနာအသစ် ဖန်တီးရန် — နည်းလမ်း ၂ မျိုး</h5>
<div class="manual-step">
    <strong>နည်းလမ်း ၁: PDF အသစ် တင်ရန်</strong>
    <ol class="mb-2">
        <li>"+ နမူနာအသစ်" ကို နှိပ်ပါ</li>
        <li><strong>"Upload new PDF"</strong> ကို ရွေးပါ</li>
        <li>နမူနာကို အမည်ပေးပါ (ဥပမာ- "MOU အလုပ်ခန့်စာချုပ် - မြန်မာ")</li>
        <li>မူရင်း PDF တင်ပါ (ဥပမာ- ကွက်လပ်ချန်ထားသော စာချုပ်ဗလာ)</li>
        <li>"Upload &amp; Go to Builder" ကို နှိပ်ပါ → ပြင်ဆင်ရေးစာမျက်နှာသို့ ဝင်ရောက်ပါမည်</li>
    </ol>
    <strong>နည်းလမ်း ၂: ရှိပြီးသား နမူနာမှ ကူးယူရန် (Clone)</strong>
    <ol class="mb-0">
        <li>"+ နမူနာအသစ်" ကို နှိပ်ပါ</li>
        <li><strong>"Copy from existing template"</strong> ကို ရွေးပါ</li>
        <li>စာရင်းမှ မူရင်းနမူနာကို ရွေးပါ (ရှာဖွေနိုင်သည်)</li>
        <li>အမည်အသစ် ပေးပါ (ဥပမာ- "(Copy)" သို့မဟုတ် "v2" ထည့်ပါ) + အမျိုးအစား/အလုပ်ရှင် ရွေးပါ</li>
        <li>"Clone &amp; Go to Builder" ကို နှိပ်ပါ → စနစ်သည် PDF ဖိုင် + ကွက်လပ်နေရာများအားလုံးကို ကူးယူပေးပါမည် → လိုအပ်သည်များကိုသာ ချိန်ညှိပြီး သိမ်းပါ</li>
    </ol>
</div>

<h5>၂။ ကွက်လပ်များ ဆွဲယူထည့်သွင်းရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>ပြင်ဆင်ရေးစာမျက်နှာတွင် — ကွက်လပ်စာရင်းသည် ဘယ်ဘက်တွင် ရှိသည် (အလုပ်ရှင်အမည်၊ အခွန် ID စသည်)</li>
        <li>လိုချင်သော ကွက်လပ်ကို PDF အစမ်းကြည့်ချက်ပေါ်ရှိ လိုသောနေရာသို့ ဆွဲယူပါ</li>
        <li>ကွက်လပ်တစ်ခုစီ၏ အရွယ်အစား/ဖောင့် ပြောင်းနိုင်သည်</li>
        <li>"သိမ်းမည်" ကို နှိပ်ပါ</li>
    </ol>
</div>

<h5>၃။ နမူနာကို အသုံးပြု၍ စာရွက်စာတမ်း ဖန်တီးရန်</h5>
<div class="manual-step">
    ဝန်ထမ်း/အလုပ်ရှင် မီနူးတွင် — "စာရွက်စာတမ်း ဖန်တီးရန်" ကို နှိပ်ပါ → နမူနာ ရွေးပါ → စနစ်သည် ဒေတာကို အလိုအလျောက် ဖြည့်ပေးပါမည်
</div>

<h5>၄။ Quick Print ဖြင့် စာရွက်စာတမ်း ပရင့်ထုတ်ရန် (ဝန်ထမ်းဒေတာ မလိုအပ်သော နမူနာများအတွက်)</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>PDF Templates စာမျက်နှာ၏ အပေါ်ပိုင်းရှိ <strong>"စာရွက်စာတမ်း ပရင့်ထုတ်ရန်"</strong> ခလုတ် (အစိမ်းရောင်) ကို နှိပ်ပါ</li>
        <li>နမူနာ ရွေးပါ — စနစ်သည် မည်သူ့ဒေတာ လိုအပ်ကြောင်း ပြရန် <strong>ကွက်လပ်များကို ခွဲခြမ်းစိတ်ဖြာ</strong>ပါလိမ့်မည်:
            <ul>
                <li><span class="badge bg-warning text-dark">ဝန်ထမ်း</span> = ဝန်ထမ်းတစ်ဦးကို အရင်ရွေးရမည် — စနစ်က သတိပေးပြီး ဗလာပရင့်ထုတ်ခွင့် မပြုပါ</li>
                <li><span class="badge bg-primary">အလုပ်ရှင်</span> / <span class="badge bg-info">ကိုယ်စားလှယ်</span> / <span class="badge bg-success">Importer</span> = dropdown မှ ရွေးပြီး ပရင့်ထုတ်နိုင်သည်</li>
            </ul>
        </li>
        <li>နမူနာတွင် ဝန်ထမ်းကွက်လပ် ပါရှိပါက → <strong>"ဝန်ထမ်း ရွေးရန် သွားပါ"</strong> ကို နှိပ်ပါ → ဝန်ထမ်းစီမံရေးစာမျက်နှာတွင် လိုချင်သောသူကို ရွေးပါ → "Generate Automated PDF" ကို နှိပ်ပါ</li>
        <li>ဝန်ထမ်းကွက်လပ် မရှိပါက → Target အလုပ်ရှင်/ကိုယ်စားလှယ်/Importer (နမူနာအသုံးပြုသည့်အတိုင်း) ရွေးပါ → <strong>"PDF ဒေါင်းလုဒ်ဆွဲရန်"</strong> သို့မဟုတ် <strong>"ပရင့်ထုတ်ရန် / အစမ်းကြည့်ရန်"</strong> ကို နှိပ်ပါ</li>
    </ol>
</div>

<h4><i class="bi bi-lightbulb me-2"></i>အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>ထိုင်းဖောင့်:</strong> စနစ်သည် THSarabunNew + CP874 encoding ကို အသုံးပြုသည် — ထိုင်းဘာသာစကားကို အပြည့်အဝ ပံ့ပိုးသည်
</div>

<div class="manual-tip">
    <strong>လက်မှတ် + တံဆိပ်:</strong> ငွေကြေးပရိုဖိုင်မှ လက်မှတ်/တံဆိပ် ထည့်နိုင်သည် သို့မဟုတ် တိုက်ရိုက်ရေးဆွဲသော ပုံစံဖြင့် ထည့်နိုင်သည် (PDF ပေါ်တွင် တိုက်ရိုက် ရေးဆွဲသည်)
</div>

<div class="manual-tip">
    <strong>Clone သည် အောက်ပါအခြေအနေများတွင် အချိန်ကုန်သက်သာစေသည်:</strong> ဖောင်တူပြီး ကွက်လပ်အနည်းငယ်သာ ပြောင်းလိုသည့် နမူနာလိုအပ်ပါက — ဥပမာ- စာချုပ်တူသုံးပြီး ကုမ္ပဏီအမည် သို့မဟုတ် သေးငယ်သော အခြေအနေ ပြောင်းလဲရန်
</div>

<div class="manual-warn">
    <strong>Quick Print နှင့် ဝန်ထမ်းကွက်လပ်များ:</strong> နမူနာတွင် ဝန်ထမ်းဒေတာကွက်လပ်များ (ဝန်ထမ်းအမည်၊ နိုင်ငံကူးလက်မှတ် စသည်) ပါရှိပါက <strong>ဗလာပရင့်ထုတ်၍ မရပါ</strong> — ဝန်ထမ်းတစ်ဦးကို အရင်ရွေးရမည်၊ ဗလာပရင့်ထုတ်ပါက ထိုကွက်လပ်များ ဗလာဖြစ်ပြီး အသုံးမဝင်တော့ပါ
</div>

<h4><i class="bi bi-question-circle me-2"></i>မေးလေ့ရှိသော မေးခွန်းများ</h4>
<dl>
    <dt>မေး: တင်ထားသော PDF သည် စကင်ဖတ်ထားသော စာသား (ပုံ) ဖြစ်နေသည်?</dt>
    <dd>ဖြေ: စနစ်သည် ၎င်းကို နောက်ခံအဖြစ် ဆက်လက်အသုံးပြုနိုင်သည် — ဗလာနေရာများပေါ်တွင် ကွက်လပ်များကို ကိုယ်တိုင် ဆွဲယူထည့်ပါ</dd>

    <dt>မေး: ကွက်လပ်ကို နေရာမှားထားသည်?</dt>
    <dd>ဖြေ: နမူနာကို ဖွင့်ပါ → ကွက်လပ်ကို မှန်ကန်သောနေရာသို့ ဆွဲယူပါ → သိမ်းမည် — စနစ်သည် နေရာအသစ်ကို ချက်ချင်း သက်ရောက်စေပါမည်</dd>

    <dt>မေး: နမူနာကို Clone လုပ်ပြီး မူရင်းကို ဖျက်လိုက်ပါက Clone ထားသောနမူနာကို ထိခိုက်ပါသလား?</dt>
    <dd>ဖြေ: ထိခိုက်ခြင်း မရှိပါ — စနစ်သည် PDF ဖိုင်ကို လမ်းကြောင်းအသစ်တစ်ခုသို့ လုံးလုံး ကူးယူပေးသဖြင့် နမူနာနှစ်ခုစလုံး လုံးလုံး သီးခြားဖြစ်နေပါသည်</dd>

    <dt>မေး: "စာရွက်စာတမ်း ပရင့်ထုတ်ရန်" ကို နှိပ်ပြီးသောအခါ "ဒေါင်းလုဒ်" ခလုတ်သည် ဘာကြောင့် ပိတ်နေသနည်း?</dt>
    <dd>ဖြေ: ရွေးထားသော နမူနာတွင် ဝန်ထမ်းဒေတာကွက်လပ်များ ပါရှိသောကြောင့် ဖြစ်သည် — Quick Print က ၎င်းကို ပံ့ပိုးမပေးပါ၊ ယင်းအစား "ဝန်ထမ်းစီမံခန့်ခွဲမှု" မှ ဝန်ထမ်းကို ရွေးပြီး "Generate Automated PDF" ကို အသုံးပြုပါ</dd>
</dl>
