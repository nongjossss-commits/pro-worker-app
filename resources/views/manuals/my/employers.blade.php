<h4><i class="bi bi-building me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"အလုပ်ရှင် (Employers)"</strong> မီနူးသည် ကျွန်ုပ်တို့ ရုံးမှတစ်ဆင့် နိုင်ငံခြားအလုပ်သမားများ ငှားရမ်းသည့် ကုမ္ပဏီများ သို့မဟုတ် ပုဂ္ဂိုလ်များ၏ ဒေတာဘေ့စ် ဖြစ်သည်။
    ကုမ္ပဏီအမည်၊ အခွန် ID၊ လိပ်စာ၊ ဖုန်းနံပါတ်နှင့် စာရွက်စာတမ်းအမျိုးမျိုးကဲ့သို့သော အခြေခံအချက်အလက်များကို သိမ်းဆည်းပြီး
    ထိုအလုပ်ရှင်အတွက် လုပ်ကိုင်နေသော <strong>ဝန်ထမ်းများ</strong>နှင့် ချိတ်ဆက်ထားသည်။
</p>

<h4><i class="bi bi-person-check me-2"></i>ဤမီနူးကို မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> — အားလုံးကို အပြည့်အဝ အသုံးပြုနိုင်သည်</li>
    <li><span class="manual-role">Staff</span> — ကြည့်ရှု / ထည့်သွင်း / ပြင်ဆင် နိုင်သည်</li>
    <li><span class="manual-role">Caretaker</span> — ကြည့်ရှု / ထည့်သွင်း / ပြင်ဆင် နိုင်သည် (ဖျက်၍မရပါ)</li>
    <li><span class="manual-role">Employer</span> — မိမိ၏ ဒေတာကိုသာ မြင်နိုင်သည်</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာ ဘယ်လိုပုံစံရှိသနည်း</h4>
<ol>
    <li>အပေါ်ရှိ <strong>စစ်ထုတ်ရေးဘား</strong> — အခြေအနေအလိုက်၊ ဝန်ထမ်းရှိ/မရှိအလိုက် စစ်ထုတ်ပြီး အမည်/အခွန် ID ဖြင့် ရှာနိုင်သည်</li>
    <li><strong>အလုပ်ရှင် ကတ်များ</strong> — ကတ်တစ်ခုစီသည် ကုမ္ပဏီတစ်ခုကို ပြသည်: အမည်၊ ဝန်ထမ်းအရေအတွက်၊ အခြေအနေ</li>
    <li>ညာဘက်အပေါ်ထောင့်ရှိ <strong>"+ အလုပ်ရှင်အသစ် ထည့်ရန်"</strong> ခလုတ် — အလုပ်ရှင်အသစ် ဖန်တီးရန်</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>အသုံးများသော လုပ်ဆောင်ချက်များ</h4>

<h5>၁။ အလုပ်ရှင်အသစ် ထည့်ရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>ညာဘက်အပေါ်ထောင့်ရှိ <strong>"+ အလုပ်ရှင်အသစ် ထည့်ရန်"</strong> ကို နှိပ်ပါ</li>
        <li>အခြေခံအချက်အလက် ဖြည့်ပါ — ကုမ္ပဏီအမည် (ထိုင်း/အင်္ဂလိပ်)၊ ၁၃ ဂဏန်း အခွန် ID၊ လိပ်စာ</li>
        <li>သင့်လျော်ပါက <strong>"အလုပ်ပိုင်ရှင်"</strong> ကို ရွေးပါ (ဤဖောက်သည်ကို ကြီးကြပ်သော ဝန်ထမ်း)</li>
        <li>ရရှိနိုင်ပါက စာရွက်စာတမ်းများ (VAT မှတ်ပုံတင်မိတ္တူ၊ စီးပွားရေးမှတ်ပုံတင် စသည်) တင်ပါ</li>
        <li><strong>"သိမ်းမည်"</strong> ကို နှိပ်ပါ — စနစ်သည် အလုပ်ရှင်ကို ချက်ချင်း ဖန်တီးပေးပါမည်</li>
    </ol>
</div>

<h5>၂။ အလုပ်ရှင် ရှာဖွေရန်</h5>
<div class="manual-step">
    အပေါ်ရှိ ရှာဖွေရေးဘောက်စ်တွင် အမည် သို့မဟုတ် အခွန် ID ရိုက်ထည့်ပါ — စာရင်းသည် အလိုအလျောက် စစ်ထုတ်ပါလိမ့်မည်
</div>

<h5>၃။ အလုပ်ရှင် အချက်အလက် ပြင်ဆင်ရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>ပြင်ဆင်လိုသော အလုပ်ရှင်၏ ကတ်ကို နှိပ်ပါ</li>
        <li><i class="bi bi-pencil"></i> <strong>"ပြင်ဆင်ရန်"</strong> အိုင်ကွန်ကို နှိပ်ပါ</li>
        <li>လိုအပ်သော အချက်အလက်ကို ပြောင်းလဲပြီး <strong>"သိမ်းမည်"</strong> ကို နှိပ်ပါ</li>
    </ol>
</div>

<h5>၄။ ဤအလုပ်ရှင်၏ ဝန်ထမ်းများ ကြည့်ရှုရန်</h5>
<div class="manual-step">
    အလုပ်ရှင်ကတ်ကို နှိပ်ပါ → ဤအလုပ်ရှင်အတွက် လုပ်ကိုင်နေသော ဝန်ထမ်းအားလုံး၏ စာရင်းအပြည့်အစုံနှင့် တစ်ဦးစီ၏ အခြေအနေကို မြင်ရပါမည်
</div>

<h5>၅။ အလုပ်ရှင် ဖျက်ရန်</h5>
<div class="manual-step">
    ကတ်ပေါ်ရှိ <i class="bi bi-trash text-danger"></i> အိုင်ကွန်ကို နှိပ်ပါ — စနစ်က အတည်ပြုချက် အရင်တောင်းပါလိမ့်မည်
    <div class="manual-warn mt-2 mb-0">
        <i class="bi bi-exclamation-triangle-fill"></i> <strong>သတိပေးချက်:</strong>
        အလုပ်ရှင်တွင် ဝန်ထမ်းများ ဆက်ရှိနေပါက စနစ်သည် <strong>ဖျက်ခွင့်မပြုပါ</strong> — ဝန်ထမ်းအားလုံးကို လွှဲပြောင်း သို့မဟုတ် အလုပ်ထုတ်ပြီးမှသာ ဆက်လုပ်ရမည်
    </div>
</div>

<h4><i class="bi bi-lightbulb me-2"></i>သိထားသင့်သည်များ / အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>ထိုင်း vs အင်္ဂလိပ်:</strong> အမည်ကို ဘာသာစကားနှစ်မျိုးလုံးဖြင့် ဖြည့်ပါ —
    တရားဝင်စာရွက်စာတမ်းများ (MOU၊ အလုပ်ခန့်စာချုပ်) ပရင့်ထုတ်ရာတွင် အင်္ဂလိပ်အမည်ကို အသုံးပြုသည်
</div>

<div class="manual-tip">
    <strong>အခွန် ID:</strong> အတိအကျ ၁၃ ဂဏန်း ဖြစ်ရမည် — မှားယွင်းစွာ ထည့်သွင်းပါက စနစ်က သတိပေးပါမည်
</div>

<div class="manual-tip">
    <strong>လိပ်စာ အများအပြား:</strong> အလုပ်ရှင်တစ်ဦးတွင် လိပ်စာ အများအပြား ရှိနိုင်သည် — မှတ်ပုံတင်လိပ်စာနှင့် အလုပ်ခွင်လိပ်စာ
</div>

<div class="manual-warn">
    <strong>သတိပြုရန်:</strong> အလုပ်ရှင် မဖျက်မီ <strong>Production</strong> သို့မဟုတ် <strong>Workflow</strong> လုပ်ဆောင်ဆဲ အလုပ် မရှိကြောင်း သေချာပါစေ —
    ဖျက်ပါက ထိုအလုပ်၏ အခြေအနေကို မမှန်ကန်စေပါမည်
</div>

<h4><i class="bi bi-question-circle me-2"></i>မေးလေ့ရှိသော မေးခွန်းများ</h4>

<dl>
    <dt>မေး: အလုပ်ရှင် ဘာကြောင့် ထည့်၍မရသနည်း?</dt>
    <dd>ဖြေ: ကြယ်ပွင့် (*) ပါသော ကွက်လပ်တိုင်းကို ဖြည့်ထားကြောင်း စစ်ဆေးပါ၊ အထူးသဖြင့် အမည်နှင့် အခွန် ID</dd>

    <dt>မေး: ဝန်ထမ်းတစ်ဦး အလုပ်ရှင်ကတ်မှ ပျောက်ဆုံးသွားသည်?</dt>
    <dd>ဖြေ: အခြေအနေစစ်ထုတ်ချက်ကို စစ်ဆေးပါ — "အလုပ်ထုတ်ပြီး" သို့မဟုတ် "စာချုပ်ကုန်ဆုံးပြီး" အောက်တွင် ရှိနေနိုင်သည်၊ "အားလုံး" ကို ရွေးကြည့်ပါ</dd>

    <dt>မေး: အလုပ်ရှင်ကို မှားဖျက်မိသည်၊ ပြန်ရနိုင်ပါသလား?</dt>
    <dd>ဖြေ: ရနိုင်ပါသည် — <strong>"ဗဟိုအမှိုက်ပုံး"</strong> မီနူးသို့ သွားပြီး ပြန်လည်ရယူရန် နှိပ်ပါ (Admin/Super Admin သာ)</dd>
</dl>
