<h4><i class="bi bi-diagram-3-fill me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"Workflow"</strong> မီနူးသည် ရုံး၏ အဆင့်ဆင့် လုပ်ငန်းစဉ်များကို ဖြတ်သန်းနေသော အလုပ်များ၏ စင်တာ ဖြစ်သည် —
    ဥပမာ- အလုပ်သမားရေးရာဌာနတွင် တင်ပြခြင်း၊ နိုင်ငံကူးလက်မှတ် ဆောင်ရွက်ခြင်း၊ ဗီဇာ လျှောက်ထားခြင်း၊ အလုပ်လုပ်ခွင့်ပြုချက် ထုတ်ပေးခြင်း စသည်။
    အလုပ်တစ်ခုစီသည် သတ်မှတ်ထားသော "အဆင့်များ" ကို ဖြတ်သန်းသည်
</p>

<h4><i class="bi bi-person-check me-2"></i>ဤမီနူးကို မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — ဝင်ရောက်နိုင်သည်</li>
    <li><span class="manual-role">Caretaker</span> — ကြည့်ရှုရုံသာ၊ ပြင်ဆင်၍မရပါ</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာ ဘယ်လိုပုံစံရှိသနည်း</h4>
<ol>
    <li>အပေါ်ရှိ <strong>အဆင့်ဘား</strong> — အလုပ်ဖြတ်သန်းရမည့် အဆင့်တစ်ခုစီ + အဆင့်တစ်ခုစီရှိ အလုပ်အရေအတွက်ကို ပြသသည်</li>
    <li><strong>စစ်ထုတ်ရေးဘား</strong> — အဆင့်၊ အလုပ်ရှင်၊ အလုပ်အမျိုးအစားဖြင့် စစ်ထုတ်နိုင်သည်</li>
    <li><strong>အလုပ် ကတ်များ</strong> — ရွေးထားသော အဆင့်ရှိ အလုပ်အားလုံးကို ပြသသည်</li>
    <li><strong>"MOU အလိုအလျောက် သက်ရောက်စေရန်" ခလုတ်</strong> — MOU သက်တမ်းတိုးအလုပ်များကို စနစ်က အလိုအလျောက် ကိုင်တွယ်ရန်</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>အသုံးပြုနည်း</h4>

<h5>၁။ အဆင့်တစ်ခုစီရှိ အလုပ်များကို ကြည့်ရှုရန်</h5>
<div class="manual-step">
    အဆင့်ဘားရှိ အဆင့်တစ်ခုကို နှိပ်ပါ → ထိုအဆင့်ရှိ အလုပ်များကိုသာ ပြသပါလိမ့်မည်
</div>

<h5>၂။ အလုပ်ကို နောက်အဆင့်သို့ ရွှေ့ရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>အလုပ်၏ ကတ်ကို ဖွင့်ပါ</li>
        <li><strong>"ဆက်လုပ်ရန် / နောက်အဆင့်"</strong> ကို နှိပ်ပါ</li>
        <li>အဆင့်အသစ် လိုအပ်သော အချက်အလက် ဖြည့်ပါ (ဥပမာ- ဘေဂျင်နံပါတ်၊ ရက်စွဲ)</li>
        <li>"အတည်ပြုမည်" ကို နှိပ်ပါ — အလုပ်သည် အဆင့်အသစ်သို့ ရွှေ့သွားပါမည်</li>
    </ol>
</div>

<h5>၃။ အလုပ်ကို အဆင့်တစ်ဆင့် နောက်ပြန်ပို့ရန်</h5>
<div class="manual-step">
    အမှားရှိပါက <strong>"နောက်ပြန်ပို့ရန်"</strong> ခလုတ်ကို အသုံးပြု၍ အလုပ်ကို ယခင်အဆင့်သို့ ပြန်ပို့နိုင်သည်၊
    သို့မဟုတ် <strong>"Pre-Production သို့ ပြန်ပို့ရန်"</strong> ကို အသုံးပြု၍ Production မီနူးသို့ ပြန်ပို့နိုင်သည်
</div>

<h5>၄။ ကွက်လပ်ထပ်တိုး သတ်မှတ်ရန် (Custom Fields)</h5>
<div class="manual-step">
    MOU ကတ်ပေါ်ရှိ "Fields" ခလုတ်ကို နှိပ်ပါ → သင့်အဆင့် လိုအပ်သော ဒေတာထပ်တိုးကို ထည့်ပါ
    (ဥပမာ- "ပန်းရောင်ကတ်နံပါတ်"၊ "အင်တာဗျူး ချိန်းဆိုမှုရက်")
</div>

<h5>၅။ MOU သက်တမ်းတိုးမှု အလိုအလျောက် သက်ရောက်စေရန်</h5>
<div class="manual-step">
    စနစ်သည် MOU သက်တမ်းတိုးအလုပ်များကို ၂၄ နာရီတိုင်း <strong>အလိုအလျောက် သက်ရောက်စေသည်</strong>။
    Admin သည် Super Admin Settings → Workflow အပိုင်းတွင် သတ်မှတ်နိုင်သည်
</div>

<h5>၆။ တင်သွင်းထားသော MOU — Demand Card ဖန်တီးရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li><strong>"တင်သွင်းထားသော MOU"</strong> တဘ်ကို ဖွင့်ပါ → <strong>"Create Job"</strong> ကို နှိပ်ပါ</li>
        <li>Work Type = တင်သွင်းထားသော MOU ကို ရွေးပါ</li>
        <li><strong>အလုပ်ရှင် ရွေးပါ</strong> — scroll လှိမ့်မည့်အစား ရိုက်ထည့်ရှာနိုင်သည် (ထိုင်းအမည်/အင်္ဂလိပ်/ကုဒ်)</li>
        <li><strong>တင်သွင်းထားသော MOU အမျိုးအစား ရွေးပါ</strong>:
            <ul>
                <li><span class="badge bg-success">Return</span> = ဝန်ထမ်း ထိုင်းနိုင်ငံတွင် ရောက်ရှိပြီးဖြစ်သည် → ၎င်းတို့၏ ဒေတာကို ချက်ချင်း မှတ်တမ်းတင်နိုင်သည်</li>
                <li><span class="badge bg-primary">New from Origin</span> = မူရင်းနိုင်ငံမှ လူသစ် → ဝန်ထမ်းဒေတာ မရှိသေးပါ၊ Demand → အမည်စာရင်းကို စောင့်ဆိုင်းနေသည်</li>
                <li>မသေချာသေးပါက → အလွတ်ချန်ထားနိုင်သည်၊ စနစ်သည် <span class="badge bg-warning text-dark">Pending Classification</span> ဟု ပြသပါလိမ့်မည်</li>
            </ul>
        </li>
        <li>လူမျိုး + တင်သွင်းလိုသော အမျိုးသား/အမျိုးသမီး အရေအတွက် ဖြည့်ပါ</li>
        <li>"Create Demand Card" ကို နှိပ်ပါ</li>
    </ol>
</div>

<h5>၇။ တင်သွင်းထားသော MOU အမျိုးအစားကို နောက်မှ ပြောင်းလဲရန်</h5>
<div class="manual-step">
    Workflow "တင်သွင်းထားသော MOU" တဘ်တွင် → ကတ်ပေါ်ရှိ <strong>အရောင်ပါ badge (Return/New/Pending)</strong> ကို နှိပ်ပါ → အမျိုးအစားအသစ် ရွေးပါ → သိမ်းမည် ကို နှိပ်ပါ
</div>

<h5>၈။ "အလုပ်ထုတ်အကြောင်းကြားချက်" တဘ် — ပိတ်မီ ရက်စွဲနှင့် အကြောင်းရင်း ထည့်ပါ</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li><strong>"အလုပ်ထုတ်အကြောင်းကြားချက်"</strong> တဘ်ကို ဖွင့်ပါ → <strong>"+ ဝန်ထမ်း ထည့်ရန်"</strong> ကို နှိပ်ပါ</li>
        <li>သင့်အလုပ်ရှင်နယ်ပယ်တွင် ကန့်သတ်မထားဘဲ <strong>စနစ်ထဲရှိ ဝန်ထမ်းမည်သူ့ကိုမဆို</strong> ရှာနိုင်သည် (ကမ္ဘာလုံးဆိုင်ရာ ရှာဖွေမှု)</li>
        <li>လက်ရှိ <strong>သက်တမ်းတိုး / အလုပ်ရှင်လွှဲပြောင်းမှု</strong> အလုပ်ရှိနေသော ဝန်ထမ်းကို notify_out ထဲသို့ ဆက်လက်ထည့်နိုင်သည် (နှစ်ခုစလုံး တစ်ပြိုင်နက် လုပ်ဆောင်နိုင်သည်)</li>
        <li>notify_out ထဲတွင် ရှိနေပြီးသား ဝန်ထမ်းကို <strong>ပြီးစီးမချင်း ထပ်ထည့်၍မရပါ</strong></li>
        <li>စနစ်သည် ဝန်ထမ်း၏ <strong>လက်ရှိအလုပ်ရှင်အလိုက် အလိုအလျောက် အုပ်စုဖွဲ့ပေးပါလိမ့်မည်</strong> (အလုပ်ရှင် ၁ ဦး = order ၁ ခု)</li>
    </ol>
</div>

<div class="manual-step">
    <strong>notify_out မှတ်တမ်းတွင် Finish မနှိပ်မီ:</strong>
    <ol class="mb-0">
        <li>ဝန်ထမ်းကတ်၏ အောက်ခြေတွင် <strong>အဝါရောင်ဘား</strong> ပေါ်လာပါမည်</li>
        <li><strong>အလုပ်ထုတ်အကြောင်းကြားရက်</strong> ဖြည့်ပါ (ရက်စွဲရွေးစနစ် — လိုအပ်သည်)</li>
        <li><strong>အကြောင်းရင်း</strong> ရွေးပါ (dropdown: အလုပ်ထုတ်ပြီး / ထုတ်ပယ်ခံရသည် / စာချုပ်ကုန်ဆုံးပြီး / အလုပ်ရှင်ပြောင်းလဲမှု / ထွက်ပြေးသွားသည် / သေဆုံးသည်) — သို့မဟုတ် ကိုယ်တိုင် ရိုက်ထည့်နိုင်သည်</li>
        <li>ပြောင်းလဲမှုတိုင်းကို စနစ်က အလိုအလျောက် သိမ်းဆည်းသည် → badge သည် အစိမ်းရောင် <strong>"ပြီးစီးရန် အသင့်ဖြစ်"</strong> သို့ ပြောင်းသွားသည်</li>
        <li>"Finish" ကို နှိပ်ပါ → စနစ်သည် <strong>employee.terminated_at + termination_reason + status='resigned'</strong> ကို ချက်ချင်း အလိုအလျောက် Update လုပ်ပါလိမ့်မည်</li>
        <li><strong>အလုပ်ထုတ်အကြောင်းကြားရက် မဖြည့်ရသေးပါက</strong> → Finish နှိပ်၍မရပါ၊ "အလုပ်ထုတ်အကြောင်းကြားရက် အရင်ဖြည့်ပါ" ဟု သတိပေးပါလိမ့်မည်</li>
    </ol>
</div>

<h4><i class="bi bi-lightbulb me-2"></i>အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>စစ်ထုတ်ချက် များစွာ အသုံးပြုပါ:</strong> ခြုံငုံသုံးသပ်ချက်ကို ကြည့်ရန် အဆင့်များစွာကို တစ်ပြိုင်နက် ရွေးနိုင်သည်
</div>

<div class="manual-tip">
    <strong>အလုပ်ပိုင်ရှင်:</strong> သင့်ဝန်ထမ်းက စီမံသော အလုပ်များကိုသာ ကြည့်ရန် "အလုပ်ပိုင်ရှင်" စစ်ထုတ်ချက်ကို အသုံးပြုပါ
</div>

<div class="manual-warn">
    <strong>သတိပြုရန်:</strong> အဆင့်ရွှေ့ခြင်းသည် ဖောက်သည်ထံ ပို့သော အကြောင်းကြားချက်ကို ထိခိုက်စေသည် — မနှိပ်မီ ထပ်စစ်ဆေးပါ
</div>

<h4><i class="bi bi-question-circle me-2"></i>မေးလေ့ရှိသော မေးခွန်းများ</h4>
<dl>
    <dt>မေး: အလုပ်တစ်ခု ပျောက်နေသည် — Workflow တွင် ရှာမတွေ့ပါ?</dt>
    <dd>ဖြေ: သင့်စစ်ထုတ်ချက်များကို စစ်ဆေးပါ — မရွေးထားသော အဆင့်တွင် ရှိနေနိုင်သည်၊ "အားလုံး" ရွေးကြည့်ပါ သို့မဟုတ် အလုပ်ရှင်အမည်ဖြင့် စစ်ထုတ်ကြည့်ပါ</dd>

    <dt>မေး: အဆင့်အသစ် ထည့်နိုင်ပါသလား?</dt>
    <dd>ဖြေ: ထည့်နိုင်ပါသည် — အဆင့်ဆက်တင်များ မီနူးမှတစ်ဆင့် ထည့်ရန် Admin ကို ဆက်သွယ်ပါ</dd>

    <dt>မေး: အသုံးပြုနေဆဲ အဆင့်ကို ဖျက်နိုင်ပါသလား?</dt>
    <dd>ဖြေ: မဖျက်နိုင်ပါ — ထိုအဆင့်ထဲရှိ အလုပ်များ ပိတ်မိသွားနိုင်သည်၊ အခြားအဆင့်သို့ အရင်ရွှေ့ပါ</dd>

    <dt>မေး: ဝန်ထမ်း၏ notify_out မှတ်တမ်း တဘ်မှ ကိုယ်တိုင် ပျောက်သွားသည်?</dt>
    <dd>ဖြေ: ဝန်ထမ်းကို အလုပ်ရှင်အသစ်သို့ လွှဲပြောင်းသောအခါ စနစ်သည် ဆိုင်းငံ့ထားသော notify_out ကို <strong>အလိုအလျောက် ပယ်ဖျက်</strong>သည် — အကြောင်းမှာ notify_out ဆိုသည်မှာ "အလုပ်ရှင်ဟောင်းမှ ထွက်ခွာခြင်း" ဖြစ်၍ နောက်ထပ် မသက်ဆိုင်တော့သောကြောင့် ဖြစ်သည်။ "လုပ်ဆောင်ချက် မှတ်တမ်းများ" မီနူးတွင် မှတ်တမ်းကို ကြည့်ရှုနိုင်သည်၊ သို့မဟုတ် လိုအပ်ပါက အလုပ်ရှင်အသစ်အောက်တွင် notify_out အသစ် ဖန်တီးနိုင်သည်</dd>

