{{-- User Manual: Importers (Myanmar) --}}

<h4><i class="bi bi-globe2 me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"တင်သွင်းသူများ (Importers)"</strong> မီနူးသည်
    ထိုင်းနိုင်ငံသို့ အလုပ်သမားများ ပို့ဆောင်သော <strong>မူရင်းနိုင်ငံ</strong> (မြန်မာ၊ လာအို၊ ကမ္ဘောဒီးယား) ရှိ ကုမ္ပဏီများ၏ အချက်အလက်ကို သိမ်းဆည်းသည်။
    ဝန်ထမ်းတစ်ဦးသည် မည်သည့် Importer မှ ရောက်လာသည်ကို ခြေရာခံရန် + နိုင်ငံတကာ ကုန်သွယ်ရေး စာရွက်စာတမ်းများ ကိုင်တွယ်ရန် အသုံးပြုသည်
</p>

<h4><i class="bi bi-person-check me-2"></i>ဤမီနူးကို မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — ဝင်ရောက်နိုင်သည်</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာ ဘယ်လိုပုံစံရှိသနည်း</h4>
<ol>
    <li><strong>Importer ဇယား</strong> — ကုမ္ပဏီအမည်၊ နိုင်ငံ၊ လိပ်စာ၊ ဆက်သွယ်ရေးပုဂ္ဂိုလ်</li>
    <li><strong>"+ Importer အသစ် ထည့်ရန်"</strong> ခလုတ်</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>အသုံးပြုနည်း</h4>

<h5>၁။ Importer ထည့်ရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>"+ Importer အသစ် ထည့်ရန်" ကို နှိပ်ပါ</li>
        <li>ကုမ္ပဏီအမည် (ထိုင်း/အင်္ဂလိပ်)၊ နိုင်ငံ၊ လိပ်စာ ဖြည့်ပါ</li>
        <li>အဓိက ဆက်သွယ်ရေးပုဂ္ဂိုလ်၊ ဖုန်းနံပါတ်၊ အီးမေးလ် ဖြည့်ပါ</li>
        <li>Importer ၏ လိုင်စင်/အသိအမှတ်ပြု စာရွက်စာတမ်းများ ပူးတွဲပါ</li>
        <li>"သိမ်းမည်" ကို နှိပ်ပါ</li>
    </ol>
</div>

<h5>၂။ ဝန်ထမ်းကို Importer နှင့် ချိတ်ဆက်ရန်</h5>
<div class="manual-step">
    ဝန်ထမ်း၏ မှတ်တမ်းကို ဖွင့်ပါ → "Importer" ကွက်လပ် → dropdown မှ ရွေးပါ
</div>

<h4><i class="bi bi-lightbulb me-2"></i>အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>Importer များသည် မူရင်းနိုင်ငံတွင် တည်ရှိသည်:</strong> သံရုံးနှင့် စာရွက်စာတမ်းများ ညှိနှိုင်းရမည်ဖြစ်၍ MOU သက်တမ်းတိုးစဉ် အရေးပါသော အခန်းကဏ္ဍမှ ပါဝင်သည်
</div>

<h4><i class="bi bi-question-circle me-2"></i>မေးလေ့ရှိသော မေးခွန်းများ</h4>
<dl>
    <dt>မေး: ဝန်ထမ်းတစ်ဦးတွင် Importer မသတ်မှတ်ဘဲ ရှိနိုင်ပါသလား?</dt>
    <dd>ဖြေ: ရနိုင်ပါသည် — စနစ်တွင် ကြာမြင့်စွာ ရှိနေသော ဝန်ထမ်းဟောင်းများသည် Importer ဒေတာ မပူးတွဲထားနိုင်ပါ</dd>
</dl>
