<h4><i class="bi bi-clipboard-data-fill me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"P Production"</strong> မီနူးသည် ရုံးက ယခု ဆောင်ရွက်နေသော အလုပ်အားလုံး၏ စင်တာ ဖြစ်သည် —
    Sales မီနူးမှတစ်ဆင့် ပြီးစီးသော ဖောက်သည်အသစ်မှ → စာရွက်စာတမ်း ပြင်ဆင်ခြင်း (Pre-Production) သို့ ဝင်ရောက်ခြင်း
    → ထို့နောက် ဆက်လက်ဆောင်ရွက်ရန် Workflow သို့ လွှဲပြောင်းခြင်း
</p>

<h4><i class="bi bi-person-check me-2"></i>ဤမီနူးကို မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — အပြည့်အဝ အသုံးပြုနိုင်သည်</li>
    <li><span class="manual-role">Caretaker</span> — ကြည့်ရှုရုံသာ၊ အချို့အရာများ ပြင်ဆင်၍မရပါ</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာ ဘယ်လိုပုံစံရှိသနည်း</h4>
<ol>
    <li>အပေါ်ရှိ <strong>အနှစ်ချုပ်စာရင်းအင်းကတ်များ</strong> — သတ်မှတ်ရက်နီးလာသော၊ ဆောင်ရွက်နေဆဲ၊ စစ်ဆေးရန်စောင့်ဆိုင်းနေသော အလုပ်များ</li>
    <li><strong>စစ်ထုတ်ရေးဘား</strong> — အလုပ်ရှင်၊ အလုပ်ပိုင်ရှင်၊ အလုပ်အမျိုးအစား (MOU/ဗီဇာ) ဖြင့် စစ်ထုတ်နိုင်သည်</li>
    <li><strong>အလုပ် ကတ်များ</strong> — ကတ်တစ်ခုစီတွင် အရောင်းဝန်ထမ်း၏ ဓာတ်ပုံ + အလုပ်ရှင်အမည် + ဝန်ထမ်းအရေအတွက် + အဆင့်တစ်ခုစီ၏ အခြေအနေ ပါဝင်သည်</li>
    <li><strong>"Send to Workflow" ခလုတ်</strong> — အလုပ်ကို Workflow လုပ်ငန်းစဉ်ထဲသို့ ပို့သည် (approve-production ခွင့်ပြုချက်ရှိသော အခန်းကဏ္ဍများသာ)</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>အသုံးပြုနည်း</h4>

<h5>၁။ အလုပ်ကို ဖွင့်၍ အသေးစိတ် ကြည့်ရှုရန်</h5>
<div class="manual-step">
    အလုပ်ကတ်ကို နှိပ်ပါ → Edit Job စာမျက်နှာကို ဖွင့်ပေးသည် (တဘ်များစွာ: ဝန်ထမ်း၊ စာရွက်စာတမ်း၊ ငွေကြေး၊ အချိန်ဇယား)
</div>

<h5>၂။ ဝန်ထမ်းတစ်ဦးချင်း ပြင်ဆင်ရန်</h5>
<div class="manual-step">
    "ဝန်ထမ်း" တဘ်တွင် — ဝန်ထမ်းကတ်တစ်ခုစီတွင် ပြင်ဆင်ရန်၊ စာရွက်စာတမ်းကြည့်ရန်၊ ဓာတ်ပုံတင်ရန် ခလုတ်များ ရှိသည်။
    ကင်မရာမှ ဓာတ်ပုံကို တိုက်ရိုက် ရိုက်ယူ၍ စနစ်ထဲသို့ ထည့်ရန် <strong>Document Scanner</strong> ကို အသုံးပြုပါ
</div>

<h5>၃။ ကွက်လပ်ထပ်တိုး ထည့်ရန်</h5>
<div class="manual-step">
    အချို့အလုပ်များသည် အထူးဒေတာထပ်တိုး လိုအပ်သည် — ကတ်ပေါ်ရှိ "Fields" ခလုတ်ကို နှိပ်ပါ → လိုအပ်သော ကွက်လပ်အသစ်ကို ထည့်ပါ
    (ဥပမာ- "ဆေးလက်မှတ်နံပါတ်"၊ "အသိပေးရက်")
</div>

<h5>၄။ အလုပ်ကို Workflow သို့ ပို့ရန်</h5>
<div class="manual-step">
    စာရွက်စာတမ်းများ အသင့်ဖြစ်သောအခါ → <strong>"Send to Workflow"</strong> ကို နှိပ်ပါ
    <div class="manual-warn mt-2 mb-0">
        <i class="bi bi-exclamation-triangle-fill"></i>
        <code>approve-production</code> ခွင့်ပြုချက်ရှိသော အခန်းကဏ္ဍများသာ (Admin/Super Admin)
    </div>
</div>

<h5>၅။ တစ်စုလုံးကို တစ်ပြိုင်နက် ပို့ရန် (Bulk Send)</h5>
<div class="manual-step">
    MOU တစ်ခုတည်းအောက်တွင် ဝန်ထမ်းများစွာ ရှိပါက — အားလုံးကို တစ်ပြိုင်နက် ပို့ရန် MOU ကတ်ပေါ်ရှိ "တစ်စုလုံး ပို့ရန်" ကို နှိပ်ပါ
</div>

<h5>၆။ အလုပ်ပေါ်ရှိ ငွေကြေးတဘ်</h5>
<div class="manual-step">
    Edit Job ကို ဖွင့်သောအခါ → <strong>"Financial"</strong> တဘ်ကို နှိပ်ပါ သို့မဟုတ် အလုပ်ရှင်ကတ်ပေါ်ရှိ "ငွေကြေး" ကို နှိပ်ပါ
    <ul class="mb-0">
        <li>အလုပ်တစ်ခုတည်းအတွင်း <strong>ငွေကြေးတဘ် များစွာ ဖန်တီးနိုင်သည်</strong> (ဥပမာ- "MOU မြန်မာ ဝန်ဆောင်မှုကြေး"၊ "အလုပ်ရှင်ပြောင်းလဲမှု အရစ်ကျ")
            — <strong>"+ တဘ်ထည့်ရန်"</strong> ကို နှိပ်ပါ → တဘ်ကို အမည်ပေးပါ (လိုအပ်သည် — အလွတ်/ထပ်နေခြင်း မရှိရပါ)</li>
        <li>အမည်ပြောင်းရန် <i class="bi bi-pencil-square"></i> အိုင်ကွန်ကို နှိပ်ပါ သို့မဟုတ် <strong>တဘ်အမည်ကို နှစ်ချက်နှိပ်ပါ</strong></li>
        <li>တဘ်ဖျက်ရန် <i class="bi bi-trash"></i> အိုင်ကွန်ကို နှိပ်ပါ (သက်ရောက်မှုပြသော အတည်ပြုချက် ပေါ်လာပါမည်)</li>
    </ul>
</div>

<h5>၇။ တစ်ဦးချင်း စျေးနှုန်း + အရစ်ကျ မှတ်ချက်များ သတ်မှတ်ရန်</h5>
<div class="manual-step">
    ငွေကြေးတဘ်တွင် <strong>"တစ်ဦးချင်း (Per-head)"</strong> စနစ်ကို ရွေးပါ:
    <ul class="mb-0">
        <li>စျေးနှုန်းအဆင့်များ ထည့်ပါ — အဆင့်တစ်ခုစီတွင် စျေးနှုန်း + လူဦးရေ + <strong>မှတ်ချက်</strong> ပါဝင်သည်</li>
        <li>ပိုကြီးသော popup တည်းဖြတ်ကိရိယာ ဖွင့်ရန် <strong>မှတ်ချက်ဘောက်စ်</strong> သို့မဟုတ် <i class="bi bi-pencil-square"></i> အိုင်ကွန်ကို နှိပ်ပါ (စာလုံး ၅၀၀ ရေတွက်ကိရိယာ + Ctrl+Enter ဖြင့် သိမ်းနိုင်သည်)</li>
        <li>ဤမှတ်ချက်သည် ထိုအဆင့်အတွက် ထုတ်ပေးသော ဘေဂျင်/ငွေလက်ခံလွှာပေါ်တွင်လည်း ပေါ်လာပါမည်</li>
        <li>အဆင့်ဖျက်ရန် <i class="bi bi-trash"></i> ကို နှိပ်ပါ — အတည်ပြုချက် ပေါ်လာပြီး ဝန်ထမ်းများ ဆက်လက် သတ်မှတ်ထားပါက သတိပေးပါလိမ့်မည်</li>
    </ul>
</div>

<h4><i class="bi bi-lightbulb me-2"></i>အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>ခြုံငုံသုံးသပ်ချက်ကို တစ်ချက်ကြည့်ရုံဖြင့် သိနိုင်သည်:</strong> ကတ်၏ အရောင်သည် အရေးကြီးမှုကို ပြသည် — အဝါရောင် = သတ်မှတ်ရက်နီးလာ၊ အနီရောင် = သတ်မှတ်ရက် ကျော်လွန်ပြီး
</div>

<div class="manual-tip">
    <strong>Pre-Production vs. Workflow:</strong> ဤမီနူးရှိ အလုပ်များသည် Pre-Production (စာရွက်စာတမ်း ပြင်ဆင်ခြင်း) တွင် ရှိသည်။
    Send to Workflow ကို နှိပ်ပြီးနောက် အလုပ်သည် "Workflow" မီနူးသို့ ရွှေ့သွားပါမည်
</div>

<div class="manual-warn">
    <strong>သတိပြုရန်:</strong> Workflow သို့ ပို့ပြီးသော အလုပ်ကို Production တွင် ထပ်မံပြင်ဆင်၍ မရတော့ပါ — Workflow တွင်သာ ပြင်ဆင်ရမည်
</div>

<h4><i class="bi bi-question-circle me-2"></i>မေးလေ့ရှိသော မေးခွန်းများ</h4>
<dl>
    <dt>မေး: "Send to Workflow" ခလုတ်ကို ဘာကြောင့် မမြင်ရသနည်း?</dt>
    <dd>ဖြေ: သင့်အခန်းကဏ္ဍတွင် approve-production ခွင့်ပြုချက် မရှိပါ — ထည့်ပေးရန် Admin ကို တောင်းဆိုပါ</dd>

    <dt>မေး: Send to Workflow ကို နှိပ်ပြီးနောက် အလုပ် ဘယ်ရောက်သွားသနည်း?</dt>
    <dd>ဖြေ: "Workflow" မီနူးသို့ ရွှေ့သွားသည် — အလုပ်ရှင်အမည်ဖြင့် စစ်ထုတ်၍ ရှာနိုင်သည်</dd>

    <dt>မေး: Production တွင် ရှိနေဆဲ ဝန်ထမ်းတစ်ဦး အလုပ်ထွက်သွားသည်?</dt>
    <dd>ဖြေ: ဝန်ထမ်း၏ ကတ်ကို ဖွင့်ပါ → "အလုပ်ထုတ်ရန်" ကို နှိပ်ပါ — အလုပ်သည် Production မှ အလိုအလျောက် ဖယ်ရှားခံရပါလိမ့်မည်</dd>
</dl>
