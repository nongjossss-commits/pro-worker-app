<h4><i class="bi bi-person-vcard me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"ငွေကြေး ပရိုဖိုင်များ (Financial Profiles)"</strong> မီနူးသည်
    ဈေးနှုန်းပြသလွှာ၊ အခွန်ဘေဂျင်၊ ငွေလက်ခံလွှာကဲ့သို့သော ငွေကြေးစာရွက်စာတမ်းများတွင် ပေါ်လာသော
    <strong>ငွေတောင်းခံသူများ (Billers)</strong> နှင့် <strong>ဖောက်သည်များ (Customers)</strong> ၏ အချက်အလက်များ သိမ်းဆည်းရန် အသုံးပြုသည်
</p>
<p>
    ရုံးတစ်ခုတွင် ငွေတောင်းခံသူ ပရိုဖိုင် များစွာ ရှိနိုင်သည် (ဥပမာ- "ဘန်ကောက်ရုံးခွဲ"၊ "ချင်းမိုင်ရုံးခွဲ")။
    ပရိုဖိုင်တစ်ခုစီတွင် ကိုယ်ပိုင် လိုဂို၊ လက်မှတ်၊ တံဆိပ်နှင့် <strong>ဘဏ်အကောင့်များ</strong> ရှိသည်
</p>

<h4><i class="bi bi-person-check me-2"></i>ဤမီနူးကို မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> — ဝင်ရောက်နိုင်သည်</li>
    <li><span class="manual-role">Staff</span> — ဝင်ရောက်နိုင်သည် (<code>manage-finance</code> ခွင့်ပြုချက်အပေါ် မူတည်သည်)</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာ ဘယ်လိုပုံစံရှိသနည်း</h4>
<ol>
    <li><strong>ပရိုဖိုင်စာရင်း</strong> (ဘယ်ဘက်) — ပရိုဖိုင်အားလုံးကို Biller / Customer အမျိုးအစားခွဲ၍ ပြသသည်</li>
    <li><strong>ပြင်ဆင်ရေး ဖောင်</strong> (ညာဘက်) — ရွေးထားသော ပရိုဖိုင်၏ အချက်အလက်ကို ပြင်ဆင်ပါ</li>
    <li><strong>"ဘဏ်အကောင့်များ" panel</strong> — ပရိုဖိုင်ကို သိမ်းဆည်းပြီးနောက် ပေါ်လာသည် — ထိုပရိုဖိုင်၏ အကောင့်များကို ထည့်/ပြင်/ဖျက် နိုင်သည်</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>အသုံးပြုနည်း</h4>

<h5>၁။ ငွေတောင်းခံသူ ပရိုဖိုင် ဖန်တီးရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>"+ ပရိုဖိုင်အသစ် ထည့်ရန်" ကို နှိပ်ပါ</li>
        <li>"Biller" အမျိုးအစားကို ရွေးပါ</li>
        <li>ကုမ္ပဏီအမည်၊ အခွန် ID၊ လိပ်စာ၊ ဖုန်းနံပါတ်၊ အီးမေးလ် ဖြည့်ပါ</li>
        <li><strong>လိုဂို၊ လက်မှတ်၊ တံဆိပ်</strong> တင်ပါ</li>
        <li>PDF အစမ်းကြည့်ချက်ပေါ်တွင် ဆွဲယူ၍ <strong>လက်မှတ်/တံဆိပ် နေရာချထားမှု</strong> ကို သတ်မှတ်ပါ</li>
        <li>"သိမ်းမည်" ကို နှိပ်ပါ</li>
    </ol>
</div>

<h5>၂။ ပရိုဖိုင်တွင် ဘဏ်အကောင့် ထည့်ရန်</h5>
<div class="manual-step">
    ပရိုဖိုင်ကို သိမ်းဆည်းပြီးနောက် "ဘဏ်အကောင့်များ" panel ပေါ်လာသည်:
    <ol class="mb-0 mt-2">
        <li>"+ ဘဏ် ထည့်ရန်" ကို နှိပ်ပါ</li>
        <li>အမျိုးအစား ရွေးပါ: <strong>ထိုင်းဘဏ် / PromptPay / စိတ်ကြိုက်</strong></li>
        <li>"ထိုင်းဘဏ်" ရွေးပါက — စာရင်းမှ ဘဏ် ရွေးပါ (ဘဏ် ၁၇ ခု၊ အရောင်လိုဂိုများနှင့်တကွ)</li>
        <li>အကောင့်အမည် + အကောင့်နံပါတ် + ဘဏ်ခွဲ ဖြည့်ပါ</li>
        <li>"သိမ်းမည်" ကို နှိပ်ပါ</li>
    </ol>
</div>

<h5>၃။ ပရိုဖိုင် ပြင်ဆင်ရန်</h5>
<div class="manual-step">
    ဘယ်ဘက်စာရင်းရှိ ပရိုဖိုင်ကို နှိပ်ပါ → ညာဘက်ဖောင်တွင် ပြင်ဆင်ပါ → "သိမ်းမည်" ကို နှိပ်ပါ
</div>

<h5>၄။ ပရိုဖိုင် ဖျက်ရန်</h5>
<div class="manual-step">
    ပရိုဖိုင်ပေါ်ရှိ အမှိုက်ပုံး အိုင်ကွန်ကို နှိပ်ပါ — စနစ်က အတည်ပြုချက် တောင်းပါလိမ့်မည်
    <div class="manual-warn mt-2 mb-0">
        <i class="bi bi-exclamation-triangle-fill"></i>
        ပရိုဖိုင်ကို ထုတ်ပေးပြီးသား အခွန်ဘေဂျင်တွင် အသုံးပြုထားပါက — <strong>ဖျက်ခြင်း မပြုပါနှင့်</strong>၊ ၎င်းသည် ဟောင်းသား PDF အား ၎င်း၏ပရိုဖိုင်ကို ရှာမတွေ့စေနိုင်သည်
    </div>
</div>

<h4><i class="bi bi-lightbulb me-2"></i>အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>Biller vs Customer ပရိုဖိုင်:</strong> Biller = ကျွန်ုပ်တို့ (ထုတ်ပေးသူ)၊ Customer = မကြာခဏ ဆက်ဆံသော ဖောက်သည်များ
    (အခွန်ဘေဂျင်တွင် ၎င်းတို့၏ အချက်အလက်များ ပြန်ရိုက်စရာမလိုဘဲ အလိုအလျောက် ဖြည့်ပေးရန်)
</div>

<div class="manual-tip">
    <strong>Biller ပရိုဖိုင် များစွာ:</strong> ရုံးခွဲ/ဥပဒေရေးရာ အဖွဲ့အစည်း များစွာရှိသော ရုံးများအတွက် အသုံးဝင်သည်
</div>

<div class="manual-tip">
    <strong>ဘဏ်လိုဂိုများ:</strong> စနစ်သည် PDF ပေါ်တွင် အမှတ်တံဆိပ်အရောင် + အတိုကောက်ကို အလိုအလျောက် ထည့်ပေးသည်
    (ဥပမာ- KBANK = အစိမ်းရောင် K၊ SCB = ခရမ်းရောင် S)
</div>

<h4><i class="bi bi-question-circle me-2"></i>မေးလေ့ရှိသော မေးခွန်းများ</h4>
<dl>
    <dt>မေး: ဘဏ်အကောင့် ထည့်၍မရသနည်း?</dt>
    <dd>ဖြေ: <strong>ပရိုဖိုင်ကို အရင်သိမ်းဆည်းရမည်</strong> — ဘဏ်အကောင့်များ panel သည် သိမ်းဆည်းပြီးမှသာ ပေါ်လာမည်</dd>

    <dt>မေး: PDF ပေါ်တွင် လက်မှတ် မပေါ်ပါ?</dt>
    <dd>ဖြေ: လက်မှတ် တင်ပြီး အစမ်းကြည့်ချက်ပေါ်တွင် နေရာချထားကြောင်း စစ်ဆေးပါ — မထားပါက စနစ်သည် မည်သည့်နေရာတွင် ထားရမည်ကို မသိပါ</dd>

    <dt>မေး: ဘဏ်ရွေးပြီးနောက် dropdown ပိတ်၍မသွားပါ?</dt>
    <dd>ဖြေ: တစ်ခု ရွေးပြီးနောက် စနစ်သည် ချက်ချင်း chip အဖြစ် ခေါက်ပေးပါမည် — အခြားတစ်ခု ရွေးရန် "ပြောင်းမည်" ကို နှိပ်ပါ</dd>
</dl>
