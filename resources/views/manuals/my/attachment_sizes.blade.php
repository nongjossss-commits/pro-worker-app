<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာ ဘယ်လိုပုံစံရှိသနည်း</h4>
<ol>
    <li><strong>အရွယ်အစား ရွေးချယ်ရန်</strong> — 5 / 10 / 20 / 50 MB (မူလ 10 MB) နှင့် "ပြန်စကင်ဖတ်ရန်" ခလုတ်</li>
    <li><strong>အနှစ်ချုပ်ကတ်များ</strong> — ဖိုင်ကြီး အရေအတွက်၊ အသုံးပြုနေရာ၊ ဖိုင်အားလုံး၊ စကင်ဖတ်ချိန်</li>
    <li><strong>မှတ်တမ်းများတွင် ပူးတွဲထားသည်</strong> — ဖိုင်အမည်၊ အရွယ်အစား၊ ပုံ၏ resolution (px)၊ ပိုင်ရှင် နှင့် အကွက်</li>
    <li><strong>မည်သည့် မှတ်တမ်းနှင့်မျှ မချိတ်ဆက်ထားပါ</strong> — ဥပမာ စနစ်မှ ထုတ်ထားသော ဒေါင်းလုဒ်ဖိုင်များ</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>အသုံးပြုနည်း</h4>
<div class="manual-step">
    <ol class="mb-0">
        <li>"ပူးတွဲဖိုင် အရွယ်အစား" ကို ဖွင့်၍ စာရင်းကို စစ်ဆေးပါ</li>
        <li><i class="bi bi-eye"></i> ကို နှိပ်၍ ဖိုင်ကို ဖွင့်ကြည့်ပါ</li>
        <li>မလိုအပ်လျှင် <i class="bi bi-pencil"></i> ကို နှိပ်၍ ပြင်ဆင်စာမျက်နှာတွင် ပိုသေးသော ဖိုင်ကို တူညီသော အကွက်တွင် ပြန်တင်ပါ</li>
        <li>"ပြန်စကင်ဖတ်ရန်" ကို နှိပ်၍ ထပ်မံစစ်ဆေးပါ (ရလဒ်ကို ၁၀ မိနစ် သိမ်းထားသည်)</li>
    </ol>
</div>

