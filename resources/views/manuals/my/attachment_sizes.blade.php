<h4><i class="bi bi-hdd-stack-fill me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"ပူးတွဲဖိုင် အရွယ်အစား"</strong> (အသိပေးချက်များ အောက်၊ "ထပ်နေသော ဒေတာ" ၏ နောက်တွင်) သည် <strong>10 MB နှင့်အထက်</strong> တင်ထားသော ဖိုင်များကို
    မည်သူ့ဖိုင်၊ မည်သည့်အကွက်ဖြစ်သည်ကို ပြသည် — ဥပမာ စာမျက်နှာတစ်ခုတည်း ပတ်စ်ပို့စကင်ဖိုင် 12 MB ဖြစ်နေခြင်း —
    ပိုသေးသော ဖိုင်ကို ပြန်တင်၍ သိုလှောင်နေရာ သက်သာစေရန်။
</p>

