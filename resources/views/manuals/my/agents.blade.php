<h4><i class="bi bi-briefcase-fill me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"အေးဂျင့်များ (Agents)"</strong> မီနူးသည် စီးပွားရေး ဆက်သွယ်ပေးသော <strong>အလုပ်ရှင်အေးဂျင့်များ</strong>၏ အချက်အလက်ကို သိမ်းဆည်းသည်။
    တစ်ခါတစ်ရံ အလုပ်ရှင်သည် ကျွန်ုပ်တို့ ရုံးကို တိုက်ရိုက် ဆက်သွယ်မည့်အစား ညှိနှိုင်းသူ/အကြံပေးအဖြစ် ဆောင်ရွက်သော အေးဂျင့်တစ်ဦးမှတစ်ဆင့် ဆက်သွယ်ခဲသည်။
    မည်သည့် အေးဂျင့်ထံမှ အလုပ်တစ်ခု ရောက်လာသည်၊ ၎င်းတို့ကို ပေးရမည့် ကော်မရှင် ခြေရာခံရန် အသုံးပြုသည်
</p>

<h4><i class="bi bi-person-check me-2"></i>ဤမီနူးကို မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — ဝင်ရောက်နိုင်သည်</li>
    <li><span class="manual-role">Caretaker</span> — ကြည့်ရှုရုံသာ</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာ ဘယ်လိုပုံစံရှိသနည်း</h4>
<ol>
    <li><strong>အေးဂျင့် ဇယား</strong> — အမည်၊ ဖုန်းနံပါတ်၊ အီးမေးလ်၊ စီမံနေသော အလုပ်ရှင် အရေအတွက်</li>
    <li><strong>"+ အေးဂျင့်အသစ် ထည့်ရန်"</strong> ခလုတ်</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>အသုံးပြုနည်း</h4>

<h5>၁။ အေးဂျင့်အသစ် ထည့်ရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>"+ အေးဂျင့်အသစ် ထည့်ရန်" ကို နှိပ်ပါ</li>
        <li>အမည်၊ ဖုန်းနံပါတ်၊ အီးမေးလ်၊ လိပ်စာ ဖြည့်ပါ</li>
        <li>သဘောတူထားပါက ကော်မရှင် အသေးစိတ် ဖြည့်ပါ</li>
        <li>ရရှိနိုင်ပါက စာရွက်စာတမ်းများ (အေးဂျင့် စာချုပ်) တင်ပါ</li>
        <li>"သိမ်းမည်" ကို နှိပ်ပါ</li>
    </ol>
</div>

<h5>၂။ အေးဂျင့်ကို အလုပ်ရှင်နှင့် ချိတ်ဆက်ရန်</h5>
<div class="manual-step">
    "အလုပ်ရှင်" မီနူးသို့ သွားပါ → အလုပ်ရှင်ကို ပြင်ဆင်ပါ → အေးဂျင့် ရွေးပါ → သိမ်းမည်
</div>

<h4><i class="bi bi-lightbulb me-2"></i>အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>Agent vs Importer:</strong> Agent = ထိုင်းအလုပ်ရှင်အတွက် ကိုယ်စားလှယ်၊ Importer = နိုင်ငံခြားမှ အလုပ်သမား တင်သွင်းသော ကုမ္ပဏီ
</div>

<h4><i class="bi bi-question-circle me-2"></i>မေးလေ့ရှိသော မေးခွန်းများ</h4>
<dl>
    <dt>မေး: အေးဂျင့်တစ်ဦးကို အလုပ်ရှင် များစွာနှင့် ချိတ်ဆက်နိုင်ပါသလား?</dt>
    <dd>ဖြေ: ရနိုင်ပါသည် — အေးဂျင့်တစ်ဦးသည် ပုံမှန်အားဖြင့် ကုမ္ပဏီများစွာကို စီမံလေ့ရှိသည်</dd>
</dl>
