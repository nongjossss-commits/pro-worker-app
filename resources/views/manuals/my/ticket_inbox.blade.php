<h4><i class="bi bi-inbox-fill me-2"></i>ဤမီနူးသည် အဘယ်နည်း?</h4>
<p>
    <strong>"တောင်းဆိုချက် စာပုံး (Ticket Inbox)"</strong> မီနူးတွင် အလုပ်ရှင်များ တင်ပြသော <strong>တောင်းဆိုချက်/ပြဿနာများ</strong> ပါဝင်သည် —
    ဥပမာ- လက်မှတ်တောင်းဆိုခြင်း၊ ဝန်ထမ်း ပျက်ကွက်ခြင်း အသိပေးခြင်း၊ ဒေတာပြောင်းလဲရန် တောင်းဆိုခြင်း။
    မည်သည့်တောင်းဆိုချက်များ မဖြေကြားရသေးသည်ကို ခြေရာခံရန် ရုံးက ၎င်းကို အသုံးပြုသည်
</p>

<h4><i class="bi bi-person-check me-2"></i>မည်သူ ဝင်ရောက်နိုင်သနည်း?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — ဝင်ရောက်နိုင်သည် (<code>manage-tickets</code> ခွင့်ပြုချက် လိုအပ်သည်)</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>စာမျက်နှာ ဘယ်လိုပုံစံရှိသနည်း</h4>
<ol>
    <li><strong>တောင်းဆိုချက် စာရင်း</strong> — တောင်းဆိုချက်အားလုံးကို အသစ်ဆုံးအရင် ပြသသည်</li>
    <li><strong>အခြေအနေ စစ်ထုတ်ခြင်း</strong> — အဖြေစောင့်ဆိုင်းနေဆဲ / ဆောင်ရွက်နေဆဲ / ပိတ်ပြီး</li>
    <li><strong>စကားပြောဆိုမှု (မက်ဆေ့ချ်များ)</strong> — တောင်းဆိုချက်ကို ဖွင့်ပါက အပြန်အလှန် မက်ဆေ့ချ်များ မြင်ရသည်</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>အသုံးပြုနည်း</h4>

<h5>တောင်းဆိုချက်ကို ပြန်ကြားရန်</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>စာရင်းရှိ တောင်းဆိုချက်ကို နှိပ်ပါ</li>
        <li>ဖောက်သည်၏ တောင်းဆိုချက်ကို ဖတ်ပါ</li>
        <li>မက်ဆေ့ချ်ဘောက်စ်တွင် သင့်အဖြေကို ရိုက်ထည့်ပါ</li>
        <li>လိုအပ်ပါက ဖိုင်တစ်ခု ပူးတွဲနိုင်သည်</li>
        <li>"ပို့မည်" ကို နှိပ်ပါ — ဖောက်သည် အကြောင်းကြားခံရပါမည်</li>
    </ol>
</div>

<h5>တောင်းဆိုချက် ပိတ်ရန်</h5>
<div class="manual-step">
    ဖြေရှင်းပြီးသောအခါ → "တောင်းဆိုချက် ပိတ်ရန်" ကို နှိပ်ပါ → အခြေအနေသည် "ပိတ်ပြီး" သို့ ပြောင်းသွားပါမည်
</div>

<h4><i class="bi bi-lightbulb me-2"></i>အကြံပြုချက်များ</h4>

<div class="manual-tip">
    <strong>အမြန် ပြန်ကြားပါ:</strong> ဖောက်သည်များသည် လျင်မြန်သော ပြန်ကြားမှုကို နှစ်သက်ကြသည် — ပုံမှန်ပန်းတိုင်မှာ ၂၄ နာရီအတွင်း ဖြစ်သည်
</div>
