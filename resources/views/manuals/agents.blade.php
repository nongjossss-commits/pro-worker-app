<h4><i class="bi bi-briefcase-fill me-2"></i>เมนูนี้คืออะไร?</h4>
<p>
    เมนู <strong>"ตัวแทน (Agents)"</strong> เก็บข้อมูล<strong>ตัวแทนนายจ้าง</strong>ที่ติดต่องานให้
    บางครั้งนายจ้างไม่ติดต่อสำนักงานเองโดยตรง แต่ส่งผ่าน Agent ที่เป็นผู้ดูแล/ที่ปรึกษา
    ใช้สำหรับติดตามว่างานนี้มาจาก Agent คนไหน + ค่าคอมมิชชั่นที่ต้องจ่ายให้
</p>

<h4><i class="bi bi-person-check me-2"></i>ใครเข้าเมนูนี้ได้?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — เข้าได้</li>
    <li><span class="manual-role">Caretaker</span> — ดูได้</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>หน้าตาของหน้านี้</h4>
<ol>
    <li><strong>ตาราง Agent</strong> — ชื่อ, เบอร์, อีเมล, จำนวนนายจ้างที่อยู่ในการดูแล</li>
    <li><strong>ปุ่ม "+ เพิ่ม Agent ใหม่"</strong></li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>ขั้นตอนใช้งาน</h4>

<h5>1. เพิ่ม Agent ใหม่</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>กด "+ เพิ่ม Agent ใหม่"</li>
        <li>กรอกชื่อ, เบอร์, อีเมล, ที่อยู่</li>
        <li>กรอกข้อมูลค่าคอมมิชชั่น (ถ้ามีตกลงไว้)</li>
        <li>อัพโหลดเอกสาร (สัญญา Agent ถ้ามี)</li>
        <li>กด "บันทึก"</li>
    </ol>
</div>

<h5>2. ผูก Agent กับนายจ้าง</h5>
<div class="manual-step">
    ไปที่เมนู "ข้อมูลนายจ้าง" → แก้นายจ้าง → เลือก Agent → บันทึก
</div>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>

<div class="manual-tip">
    <strong>Agent vs Importer:</strong> Agent = ตัวแทนของนายจ้างคนไทย, Importer = บริษัทนำเข้าแรงงานจากต่างประเทศ
</div>

<h4><i class="bi bi-question-circle me-2"></i>คำถามที่พบบ่อย</h4>
<dl>
    <dt>Q: Agent 1 คน มีนายจ้างหลายคนได้ไหม?</dt>
    <dd>A: ได้ — Agent ทั่วไปดูแลหลายบริษัท</dd>
</dl>
