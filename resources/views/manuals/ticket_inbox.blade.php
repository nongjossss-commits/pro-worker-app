{{-- User Manual: Ticket Inbox --}}

<h4><i class="bi bi-inbox-fill me-2"></i>เมนูนี้คืออะไร?</h4>
<p>
    เมนู <strong>"กล่องรับเรื่อง (Ticket Inbox)"</strong> เก็บ<strong>คำขอ/แจ้งปัญหา</strong>จากนายจ้าง
    เช่น ขอใบรับรอง, แจ้งลูกจ้างขาดงาน, ขอเปลี่ยนข้อมูล
    สำนักงานใช้เพื่อ track ว่าคำขอใดยังไม่ตอบ
</p>

<h4><i class="bi bi-person-check me-2"></i>ใครเข้าได้?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — เข้าได้ (ต้องมีสิทธิ์ <code>manage-tickets</code>)</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>หน้าตาของหน้านี้</h4>
<ol>
    <li><strong>รายการ Ticket</strong> — แสดง ticket ทั้งหมด เรียงตามล่าสุด</li>
    <li><strong>ตัวกรองสถานะ</strong> — รอตอบ / กำลังดำเนินการ / ปิดแล้ว</li>
    <li><strong>การสนทนา (Messages)</strong> — เมื่อเปิด ticket จะเห็นข้อความโต้ตอบ</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>ขั้นตอนใช้งาน</h4>

<h5>ตอบ Ticket</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>คลิกที่ ticket ในรายการ</li>
        <li>อ่านคำขอของลูกค้า</li>
        <li>พิมพ์ข้อความตอบในกล่อง message</li>
        <li>แนบไฟล์ได้ (ถ้ามี)</li>
        <li>กด "ส่ง" — ลูกค้าจะได้รับแจ้งเตือน</li>
    </ol>
</div>

<h5>ปิด Ticket</h5>
<div class="manual-step">
    เมื่อจัดการเสร็จแล้ว → กดปุ่ม "ปิด Ticket" → สถานะเปลี่ยนเป็น "ปิดแล้ว"
</div>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>

<div class="manual-tip">
    <strong>ตอบเร็ว:</strong> ลูกค้าจะพอใจ — ปกติตั้งเป้าตอบภายใน 24 ชม.
</div>
