{{-- User Manual: Importers --}}

<h4><i class="bi bi-globe2 me-2"></i>เมนูนี้คืออะไร?</h4>
<p>
    เมนู <strong>"บริษัทนำเข้าแรงงาน (Importers)"</strong> เก็บข้อมูลของบริษัท
    <strong>ที่ประเทศต้นทาง</strong> (พม่า, ลาว, กัมพูชา) ที่เป็นผู้ส่งแรงงานมาให้ไทย
    ใช้สำหรับติดตามว่าลูกจ้างคนนี้มาจาก Importer คนไหน + ทำเอกสารทางการค้าระหว่างประเทศ
</p>

<h4><i class="bi bi-person-check me-2"></i>ใครเข้าเมนูนี้ได้?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — เข้าได้</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>หน้าตาของหน้านี้</h4>
<ol>
    <li><strong>ตาราง Importer</strong> — ชื่อบริษัท, ประเทศ, ที่อยู่, ผู้ติดต่อ</li>
    <li><strong>ปุ่ม "+ เพิ่ม Importer ใหม่"</strong></li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>ขั้นตอนใช้งาน</h4>

<h5>1. เพิ่ม Importer</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>กด "+ เพิ่ม Importer ใหม่"</li>
        <li>กรอกชื่อบริษัท (ไทย/อังกฤษ), ประเทศ, ที่อยู่</li>
        <li>กรอกผู้ติดต่อหลัก, เบอร์, อีเมล</li>
        <li>แนบเอกสาร license / ใบรับรองของ Importer</li>
        <li>กด "บันทึก"</li>
    </ol>
</div>

<h5>2. ผูกลูกจ้างกับ Importer</h5>
<div class="manual-step">
    เปิดข้อมูลลูกจ้าง → ฟิลด์ "Importer" → เลือกจาก dropdown
</div>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>

<div class="manual-tip">
    <strong>Importer มาจากประเทศต้นทาง:</strong> มีบทบาทสำคัญตอนต่อ MOU เพราะต้องประสานเอกสารกับสถานทูต
</div>

<h4><i class="bi bi-question-circle me-2"></i>คำถามที่พบบ่อย</h4>
<dl>
    <dt>Q: ลูกจ้างไม่มี Importer ได้ไหม?</dt>
    <dd>A: ได้ — ลูกจ้างเก่าที่อยู่ในระบบมานานอาจไม่มีข้อมูล Importer ติดไว้</dd>
</dl>
