<h4><i class="bi bi-hdd-stack-fill me-2"></i>เมนูนี้คืออะไร?</h4>
<p>
    เมนู <strong>"ขนาดไฟล์แนบ"</strong> (อยู่ใต้เมนูแจ้งเตือน ต่อจาก "ข้อมูลซ้ำ") แสดงไฟล์ที่อัปโหลดเข้าระบบซึ่งมีขนาด<strong>ตั้งแต่ 10 MB ขึ้นไป</strong>
    พร้อมบอกว่าเป็นไฟล์ของใคร ช่องไหน — เช่น สแกนพาสปอร์ตหน้าเดียวแต่ไฟล์ใหญ่ 12 MB ซึ่งละเอียดเกินความจำเป็น
    ช่วยให้ตัดสินใจอัปโหลดไฟล์ที่เล็กลงแทน เพื่อประหยัดพื้นที่จัดเก็บ
</p>

<h4><i class="bi bi-person-check me-2"></i>ใครเข้าได้?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span></li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>หน้าตาของหน้านี้</h4>
<ol>
    <li><strong>ตัวเลือกขนาด</strong> — แสดงไฟล์ตั้งแต่ 5 / 10 / 20 / 50 MB (ค่าเริ่มต้น 10 MB) และปุ่ม "สแกนใหม่"</li>
    <li><strong>การ์ดสรุป</strong> — จำนวนไฟล์ที่เกิน, พื้นที่ที่ใช้รวม, จำนวนไฟล์ทั้งหมดในระบบ, เวลาที่สแกน</li>
    <li><strong>ไฟล์ที่แนบอยู่กับข้อมูล</strong> — ชื่อไฟล์, ขนาด, ความละเอียดภาพ (px), แนบอยู่กับ (ลูกจ้าง/นายจ้าง/… และชื่อ), ช่อง (เช่น ไฟล์ 1. พาสปอร์ต)</li>
    <li><strong>ไฟล์ที่ไม่มีข้อมูลใดอ้างถึง</strong> — ไฟล์ใหญ่ที่ไม่มีข้อมูลใดชี้ถึง เช่น ไฟล์ดาวน์โหลดที่ระบบสร้าง</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>ขั้นตอนใช้งาน</h4>
<div class="manual-step">
    <ol class="mb-0">
        <li>เปิดเมนู "ขนาดไฟล์แนบ" — ตรวจรายการที่ขึ้นมา</li>
        <li>กด <i class="bi bi-eye"></i> เพื่อเปิดดูไฟล์ว่าจำเป็นต้องละเอียดขนาดนั้นหรือไม่</li>
        <li>ถ้าไม่จำเป็น กด <i class="bi bi-pencil"></i> เพื่อเปิดหน้าแก้ไข แล้วอัปโหลดไฟล์ที่เล็กลงในช่องเดิม</li>
        <li>กด "สแกนใหม่" เพื่อตรวจอีกครั้ง (ผลการสแกนเก็บไว้ 10 นาที)</li>
    </ol>
</div>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>
<div class="manual-tip">
    <strong>ขนาดที่เหมาะสม:</strong> รูปถ่ายหรือภาพสแกนเอกสารหน้าเดียว ความละเอียดประมาณ 2000 px ด้านยาว (ไม่เกิน 1 MB) ก็อ่านได้ชัดแล้ว
</div>
<div class="manual-warn">
    หน้านี้<strong>ไม่ลบไฟล์ใด ๆ</strong> — เป็นรายงานสำหรับตรวจสอบเท่านั้น การเปลี่ยนไฟล์ทำที่หน้าแก้ไขของข้อมูลนั้น
</div>
