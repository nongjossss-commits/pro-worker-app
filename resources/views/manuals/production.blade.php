<h4><i class="bi bi-clipboard-data-fill me-2"></i>เมนูนี้คืออะไร?</h4>
<p>
    เมนู <strong>"P Production"</strong> คือศูนย์รวมงานทั้งหมดที่กำลังดำเนินการอยู่ในสำนักงาน
    ตั้งแต่ลูกค้าใหม่ที่ปิดการขายจากเมนู Sales แล้ว → เข้าสู่ขั้นตอนเตรียมเอกสาร (Pre-Production)
    → ส่งต่อให้ Workflow ดำเนินการต่อ
</p>

<h4><i class="bi bi-person-check me-2"></i>ใครเข้าเมนูนี้ได้?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — เข้าได้เต็มที่</li>
    <li><span class="manual-role">Caretaker</span> — ทำงานประจำวันได้ (ข้อมูลลูกจ้าง, นัดหมาย) แต่สร้างงาน/ตั้งค่าขั้นตอน/แก้ข้อมูลการเงินไม่ได้ และติ๊กขั้นตอนไม่ได้ถ้าไม่ได้รับสิทธิ์</li>
    <li><span class="manual-role">Employer</span> (บัญชีลูกค้า) — เข้าเมนูนี้ไม่ได้</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>หน้าตาของหน้านี้</h4>
<ol>
    <li><strong>การ์ดสรุปสถิติ</strong> ด้านบน — จำนวนงานที่ใกล้ครบกำหนด, กำลังทำ, รอตรวจ</li>
    <li><strong>ตัวเลข "ยังไม่เริ่ม" บนกระดานคะแนน</strong> — นับเฉพาะลูกจ้างที่<strong>ยังไม่เสร็จ</strong>และยังไม่ได้ติ๊กขั้นตอนแรก (เหมือน Workflow) · คนที่เสร็จแล้วไม่ถูกนับ · กดตัวเลขเพื่อกรอง ผลตรงกับตัวเลข</li>
    <li><strong>ช่องค้นหา</strong> — พิมพ์ชื่อนายจ้าง/ลูกจ้างบางส่วน ระบบจะโชว์รายชื่อที่ตรงให้เลือกทันที (ไม่ต้องพิมพ์ให้ครบ) คลิกเลือกชื่อเพื่อกรองรายการทันที · ค้นได้ทั้งชื่อ (ไทย/อังกฤษ), เลขพาสปอร์ต, เลข Work Permit, เลขประจำตัว, เลข RA, เลขบัตรชมพู และ<strong>เลขคำขอ</strong> — รวมเลขคำขอที่อยู่บนการ์ดงาน (Workflow / Pre-Production) และบนการ์ดมติลงทะเบียน/ต่ออายุ · รายการแนะนำที่เด้งขึ้นระหว่างพิมพ์ใช้เงื่อนไขเดียวกับตอนกดค้นหา</li>
    <li><strong>ค้นหา 2 ช่อง</strong> — ช่องแรกพิมพ์ได้ทั้งข้อมูลลูกจ้าง (ชื่อ/พาสปอร์ต/เลขต่าง ๆ) นายจ้าง หรือเจ้าของงาน แล้วเลือกจากรายการ: เลือกลูกจ้าง = แสดงเฉพาะคนนั้น, เลือกนายจ้าง = เฉพาะนายจ้างนั้น, เลือกเจ้าของงาน = ทุกนายจ้างภายใต้เจ้าของงานนั้น (พิมพ์แล้วกด Enter = ค้นตามข้อความที่พิมพ์) · ช่องที่สองเปิดเมื่อช่องแรกมีค่า ใช้ค้นต่อให้แคบลงภายในผลของช่องแรก พิมพ์ได้ทุกแบบเหมือนช่องแรก · ในการ์ดนายจ้าง ถ้าคำค้นตรงกับนายจ้าง/เจ้าของงาน จะเห็นลูกจ้างทั้งหมดของนายจ้างนั้น ถ้าตรงกับลูกจ้าง จะเห็นเฉพาะคนที่ตรงกัน</li>
    <li><strong>แถบตัวกรอง</strong> — กรองตามนายจ้าง, เจ้าของงาน, ประเภทงาน (MOU/Visa)</li>
    <li><strong>การ์ดงาน</strong> — แต่ละการ์ดมีรูปเซลล์ + ชื่อนายจ้าง + จำนวนลูกจ้าง + สถานะแต่ละขั้นตอน</li>
    <li><strong>ปุ่ม "Send to Workflow"</strong> — ส่งงานเข้าสู่ขั้นตอน Workflow (เฉพาะ role ที่มีสิทธิ์ approve-production)</li>
    <li><strong>การ์ดนายจ้างที่ไม่มีลูกจ้างดำเนินการอยู่</strong> (ทุกคนเสร็จ/ยกเลิก หรือ<strong>ลูกจ้างถูกลบไปถังขยะ</strong>) — เป็นสีเทา ตัวเลขเป็น 0 และอยู่ท้ายรายการเสมอ · การ์ดที่ยังมีคนดำเนินการอยู่ขึ้นก่อน (เรียงตามรหัสนายจ้าง) · คนที่ถูกลบไม่นับในตัวเลข และกู้คืนจากถังขยะแล้วกลับมาเอง</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>ขั้นตอนใช้งาน</h4>

<h5>1. เปิดงานเพื่อดูรายละเอียด</h5>
<div class="manual-step">
    กดที่การ์ดงาน → เข้าหน้า Edit Job ที่มีหลายแท็บ: ลูกจ้าง, เอกสาร, การเงิน, ระยะเวลา
</div>

<h5>2. แก้ไขข้อมูลทีละลูกจ้าง</h5>
<div class="manual-step">
    ในแท็บ "ลูกจ้าง" — แต่ละการ์ดลูกจ้างมีปุ่มแก้ไข, ดูเอกสาร, อัพโหลดภาพ
    ใช้ฟังก์ชัน <strong>Document Scanner</strong> ถ่ายรูปจากกล้องเข้าระบบได้เลย
</div>

<h5>3. เพิ่ม Custom Field</h5>
<div class="manual-step">
    บางงานมีข้อมูลเพิ่มเติมพิเศษ — กดปุ่ม "Fields" บนการ์ด → เพิ่มฟิลด์ใหม่ตามต้องการ
    (เช่น "เลขที่ใบรับรองแพทย์", "วันที่ปฐมนิเทศ")
</div>

<h5>4. ส่งงานเข้า Workflow</h5>
<div class="manual-step">
    เมื่อเอกสารพร้อมแล้ว → กดปุ่ม <strong>"Send to Workflow"</strong>
    <div class="manual-warn mt-2 mb-0">
        <i class="bi bi-exclamation-triangle-fill"></i>
        เฉพาะ role ที่มีสิทธิ์ <code>approve-production</code> (Admin/Super Admin) เท่านั้น
    </div>
</div>

<h5>5. ส่งทั้งใบ (Bulk Send)</h5>
<div class="manual-step">
    ถ้ามีหลายลูกจ้างในใบ MOU เดียวกัน — กดปุ่ม "ส่งทั้งใบ" ที่การ์ด MOU เพื่อส่งครั้งเดียว
</div>

<h5>6. แท็บการเงิน (Financial Tab) ในใบงาน</h5>
<div class="manual-step">
    เมื่อเปิด Edit Job → คลิก tab <strong>"Financial"</strong> หรือกดปุ่ม "การเงิน" ที่การ์ดนายจ้าง
    <ul class="mb-0">
        <li><strong>สร้างแท็บการเงินหลายอัน</strong>ในใบงานเดียวได้ (เช่น "ค่าบริการ MOU พม่า", "งวดเปลี่ยนนายจ้าง")
            กด <strong>"+ เพิ่มแท็บ"</strong> → ตั้งชื่อแท็บ (บังคับ — ห้ามว่าง / ห้ามซ้ำ)</li>
        <li>กดไอคอน <i class="bi bi-pencil-square"></i> หรือ <strong>double-click ที่ชื่อแท็บ</strong> เพื่อเปลี่ยนชื่อ</li>
        <li>กดไอคอน <i class="bi bi-trash"></i> เพื่อลบแท็บ (มี confirm + แสดงผลกระทบ)</li>
    </ul>
</div>

<h5>7. ตั้งราคา per-head + หมายเหตุงวด</h5>
<div class="manual-step">
    ในแท็บการเงิน เลือกโหมด <strong>"ต่อหัว (Per-head)"</strong>:
    <ul class="mb-0">
        <li>เพิ่มงวดราคา (Tier) — แต่ละงวดมี ราคา + จำนวนคน + <strong>หมายเหตุ</strong></li>
        <li>คลิกที่ <strong>กล่องหมายเหตุ</strong>หรือไอคอน <i class="bi bi-pencil-square"></i> เพื่อเปิด popup ใหญ่แก้ไข (มี counter 500 ตัวอักษร + Ctrl+Enter บันทึก)</li>
        <li>หมายเหตุนี้จะแสดงในใบแจ้งหนี้/ใบเสร็จที่ออกตามงวดนี้ด้วย</li>
        <li>กด <i class="bi bi-trash"></i> ลบงวด — มี confirm + เตือนถ้ามีลูกจ้าง assigned อยู่</li>
    </ul>
    <br><strong>งวดที่ชำระครบแล้ว:</strong> ในกล่อง "งวดงานและการชำระเงิน" งวดที่ชำระครบจะอยู่ใน <strong>รายการปัจจุบัน</strong> 24 ชม. (มีป้าย "ย้ายในอีก N ชม.") แล้วย้ายไปแท็บ <strong>ชำระครบแล้ว</strong> — กดแท็บนั้นเพื่อดูย้อนหลัง/ออกเอกสารได้เหมือนเดิม · ยอดรวมและสรุปการเงินยังนับทุกงวดเหมือนเดิม · ถ้างวดกลับมาค้างชำระ (เช่น ลบการชำระ) จะกลับมาที่รายการปัจจุบันเอง · ในแท็บชำระครบแล้ว เลือก<strong>เดือนที่ชำระครบ</strong>ได้ (เปิดมาเป็นเดือนล่าสุด) พร้อมสรุปจำนวนงวด / ยอดสุทธิ / ได้รับแล้ว · เลือก "ทุกเดือน" = ตารางสรุปรายเดือน คลิกเดือนเพื่อดูงวดของเดือนนั้น
    <br><strong>คอลัมน์ซ้ายแบ่งเป็นแท็บ:</strong> <strong>ราคา</strong> (โหมดราคา + ระดับราคา) · <strong>สำรองจ่าย &amp; ภาษี</strong> (เงินสำรองจ่าย + VAT / WHT) · <strong>สรุป</strong> (สรุปการเงิน) · <strong>เอกสาร</strong> (ออกใบเสนอราคา/ใบแจ้งหนี้/ใบกำกับภาษี/ใบเสร็จ + เก็บเงินที่) — คลิกสลับด้านบน ไม่ต้องเลื่อนยาว · แถบใต้แท็บแสดงยอดรวมที่ต้องรับ / ชำระแล้วรวม / ยอดคงค้าง ตลอด · ปุ่มบันทึกราคาอยู่ในแท็บราคาและแท็บสำรองจ่าย &amp; ภาษี (บันทึกทั้งสองแท็บพร้อมกัน) · กล่องหมายเหตุของแต่ละระดับราคาสูงตามข้อความ (สั้นก็บรรทัดเดียว)
    <br><strong>โหมด "ราคารวมคงที่" (Fixed Total) — เพิ่มได้หลายรายการ:</strong> ไม่ได้มีช่องยอดรวมเดียวอีกต่อไป — กด <strong>"Add Item"</strong> เพื่อเพิ่มได้หลายแถว แต่ละแถวมี <strong>จำนวนเงิน + หมายเหตุ</strong> (เช่น "ค่ารถ 5,000", "ค่าอาหารกลางวัน 3,000") ระบบรวมยอดทุกแถวเป็น Total Project Value ให้อัตโนมัติ
    <br><strong>ใช้รายการราคารวมคงที่ตอนเพิ่มงวดงาน:</strong> เมื่อกด <strong>"+ เพิ่มงวดงาน"</strong> และโหมดราคาเป็น Fixed Total จะมีรายการให้ติ๊กเลือกว่าจะใช้รายการไหนในงวดนี้ — ติ๊กได้หลายรายการ ยอดเงินจะรวมให้อัตโนมัติ และแต่ละรายการจะแยกแสดงเป็นคนละบรรทัดในใบแจ้งหนี้/ใบเสร็จ (ไม่ใช่รวมเป็นบรรทัดเดียวคั่นด้วยจุลภาคแบบเดิม) · <strong>รายการที่ถูกใช้ไปในงวดงานหนึ่งแล้วจะหายไปทั้งจากตัวเลือกและจากแท็บ "ราคา" ฝั่งซ้ายด้วย</strong> (แท็บราคาจะแสดงเฉพาะรายการที่ยังไม่ถูกใช้เท่านั้น) เพื่อไม่ให้ใช้ซ้ำโดยไม่ตั้งใจ เหมือนกับลูกจ้างรายหัวที่ถูกวางบิลไปแล้ว — ถ้าลบงวดงานนั้นทิ้ง รายการจะกลับมาแสดงในแท็บราคาให้เลือก/แก้ไขราคาและเหตุผลได้ใหม่ทันทีโดยอัตโนมัติ · ยอด "ยอดรวมที่ต้องรับ" แถบบนสุดยังคงนับรวมรายการที่ถูกใช้ไปแล้วด้วยเสมอ (ไม่ลดยอดลงเวลาวางบิลบางส่วน) ส่วน "รวม (ยังไม่ได้วางบิล)" ใต้รายการในแท็บราคาจะนับเฉพาะรายการที่ยังเห็นอยู่เท่านั้น
    <br><strong>ค่าใช้จ่ายเพิ่มเติม (Payment History & Details):</strong> ในหน้า "Payment History & Details" ของแต่ละงวดงาน มีการ์ด <strong>"ค่าใช้จ่ายเพิ่มเติม"</strong> คู่กับการ์ดส่วนลด — กรอกเหตุผล (เช่น "ค่ารถ", "ค่าอาหาร") + จำนวนเงิน แล้วกด "เพิ่มเข้าบิลนี้" → <strong>แต่ละรายการเป็นบรรทัดแยก</strong> แสดงใต้ปุ่ม (ลบได้ด้วยปุ่ม ✕) และบวกเข้ายอด Total (ยอดแสดงแยก "ค่างาน + ค่าใช้จ่ายเพิ่มเติม") · กด "Update" เพื่อบันทึก · ใบวางบิล/ใบแจ้งหนี้มี<strong>แถวของแต่ละรายการ</strong> แถวรวมกันได้เท่ายอดรวม · เก็บเงินรายบุคคล: มีแถวของแต่ละรายการต่อท้ายรายชื่อ กรอกเงินที่รับของค่านั้นได้เหมือนลูกจ้าง · รายการที่รับเงินแล้วลบไม่ได้ (ลบรายการรับเงินก่อน) · ติ๊ก/เอาติ๊กลูกจ้างออก ค่าใช้จ่ายเพิ่มเติมไม่หายจากยอด · บิลเก่าที่เคยเพิ่มไว้ในหมายเหตุ ("+ ค่ารถ: ฿500.00") ถูกย้ายเป็นรายการแยกให้อัตโนมัติ (ยอดเท่าเดิม)
    <br><strong>แก้ไขรายชื่อลูกจ้างในงวด (Edit Employees):</strong> รายการแสดงเฉพาะลูกจ้างของงวดนี้ · <strong>เอาติ๊กออก</strong> = แถวเป็นสีแดง "จะถูกนำออกจากงวดนี้เมื่อกด Update" → กด Update แล้วลูกจ้างหลุดจากงวด กลับไปเป็น "ยังไม่ได้วางบิล" แก้ระดับราคาได้ และเพิ่มกลับเข้างวดได้ (ได้ราคาตามระดับราคาปัจจุบัน) · หรือกด <strong>"เปลี่ยนระดับราคา"</strong> ที่แถวนั้น เลือกระดับราคาใหม่ = คงอยู่ในงวดนี้ด้วยราคาใหม่ (ระดับราคาต้องบันทึกแล้ว) · ปุ่ม <strong>"เพิ่มลูกจ้าง"</strong> ด้านบน = รายชื่อลูกจ้างที่ตั้งราคาแล้วและยังไม่อยู่ในงวดใด กด + เพื่อเพิ่ม (แถวสีเขียว "ใหม่") · ยอด Total คำนวณใหม่ทันที · ลูกจ้างที่<strong>รับเงินรายบุคคลไปแล้ว</strong>ในงวดนี้ เอาออกไม่ได้ (ลบรายการรับเงินก่อน) · บิลคิดรายหัวต้องเหลือลูกจ้างอย่างน้อย 1 คน · ปุ่ม <strong>"เปลี่ยนราคา"</strong> มีทุกแถวของงวด — เปลี่ยนได้แม้<strong>รับเงินแล้ว</strong> (ราคาขึ้น = งวดกลับมามียอดค้าง) · ถ้าราคาลดลงจนยอดที่รับมา<strong>เกินยอดบิลใหม่</strong> กล่องจะเตือน และกด Update แล้วต้องเลือกว่าจะทำอย่างไรกับยอดที่เกิน: <strong>เก็บเป็นรายได้</strong> (เพิ่มบรรทัด "ยอดชำระเกิน (เก็บเป็นรายได้)" ในบิล) · <strong>คืนเงินลูกค้า</strong> (เลือกวันที่และบัญชีที่คืน — ลงเป็นรายจ่ายในสมุดบัญชี) · <strong>นำไปหักบิลอื่นของนายจ้างนี้</strong> (บิลที่ยังค้างพอ — ไม่มีเงินเข้าออกธนาคาร) · หรือ (เก็บเงินรายบุคคล) <strong>นำไปหักยอดคนอื่นในบิลนี้</strong> ที่ยังค้าง · ยอดในบิลไม่มีทางเกินยอดบิล และยอดรายคนไม่เกินราคาของคนนั้น · รายการที่เกิดขึ้น (คืนเงิน/โอน/โยกยอด) แสดงในรายการชำระพร้อมป้าย แก้ไขหรือออกใบเสร็จไม่ได้ — กดลบ = ยกเลิกกลับเหมือนเดิม (การโอนระหว่างบิลยกเลิกทั้งสองบิล) · บิลที่มีการโอนยอดลบไม่ได้จนกว่าจะยกเลิกการโอน · ลูกจ้างที่<strong>ถูกยกเลิกหลังวางบิลแล้ว</strong> (ยกเลิกใน Workflow, ยกเลิกทั้งการ์ด หรือยกเลิกในมติลงทะเบียน/ต่ออายุ) ยังอยู่ในงวดเดิม ยอดไม่หาย มีป้าย "ยกเลิกแล้ว" (ในเก็บเงินรายบุคคลด้วย) — แท็บ Cancelled แสดงเฉพาะคนเหล่านี้ · ถ้าต้องเรียกเก็บคนที่ถูกยกเลิกอีกราคาหนึ่ง เพิ่มเข้างวดใหม่ได้จาก "เพิ่มลูกจ้าง" (มีป้ายบอก) · ลูกจ้างที่<strong>ถูกลบ</strong> (อยู่ในถังขยะ — ลบในการ์ด Workflow หรือลบจากเมนูพนักงาน) หลังวางบิลแล้ว ยังอยู่ในงวดเดิม ยอดไม่หาย มีป้ายสีแดง "ถูกลบ" และในตารางรายชื่อแนบบิลต่อท้ายชื่อว่า "(ถูกลบ / Deleted)" · คนที่ถูกลบไม่ถูกเสนอให้เพิ่มเข้างวดใหม่
</div>

<h5>8. จัดทีมใน Pre-Production</h5>
<div class="manual-step">
    กดปุ่ม <strong>จัดทีม</strong> บนการ์ดลูกจ้าง → เลือกหรือสร้างทีม · รายชื่อลูกจ้างจะจัดกลุ่มตามทีมเหมือนใน Workflow ·
    แก้ชื่อ/ลบทีมได้จากป้ายทีม · ปุ่ม "ไม่มีทีม" เอาลูกจ้างออกจากทีม
</div>

<h5>9. จัดการขั้นตอนเตรียมงาน (ปุ่ม Steps)</h5>
<div class="manual-step">
    เพิ่ม / เปลี่ยนชื่อ / ลบ / ลากเรียงลำดับขั้นตอนเตรียมงานได้ในหน้าต่างเดียว ไม่ต้องรีโหลดหน้า
    (ขั้นตอนของ Pre-Production แยกจากขั้นตอนของ Workflow)
</div>

<h5>10. แท็บแบบหลายการ์ด กับการส่งเข้า Workflow</h5>
<div class="manual-step">
    แท็บที่ตั้งเป็น <strong>หลายการ์ด</strong> (เช่น MOU นำเข้า) — การ์ดแต่ละใบถูกส่งเข้า Workflow เป็นงานแยกกัน ไม่ถูกรวมเข้ากับการ์ดอื่นของนายจ้างเดียวกัน
</div>

<h5>11. ตรวจข้อมูลซ้ำ + โหมดเช็คงาน</h5>
<div class="manual-step">
    ตอนเพิ่มลูกจ้างใหม่ ระบบเตือนถ้าเลขพาสปอร์ต / ใบอนุญาตทำงาน / บัตรชมพู / เลขประจำตัว / เลข RA ซ้ำกับลูกจ้างที่มีอยู่ ·
    เมนูนี้เป็น 1 ใน 4 เมนูของ <strong>โหมดเช็คงาน</strong> (ดูรายละเอียดในคู่มือ Workflow) · แก้ <strong>เลข RA</strong> หรือ <strong>อีเมลเข้าระบบ Outsource</strong> บนการ์ดงานโดยตรง ระบบก็เตือนแบบเดียวกันก่อนบันทึก — อีเมลที่ลูกจ้างคนอื่นใช้อยู่แล้วบันทึกไม่ได้
</div>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>

<div class="manual-tip">
    <strong>ดูสถานะรวม:</strong> สีของการ์ดบอกความเร่งด่วน — เหลือง = ใกล้ครบกำหนด, แดง = เลยกำหนด
</div>

<div class="manual-tip">
    <strong>Pre-Production vs Workflow:</strong> งานที่อยู่ในเมนูนี้เป็น Pre-Production (เตรียมเอกสาร)
    หลังกด Send to Workflow แล้วงานจะย้ายไปอยู่ในเมนู "Workflow"
</div>
<div class="manual-tip">
    <strong>ส่งข้อมูลไปแชท LINE:</strong> ลากปุ่ม <i class="bi bi-grid-3x2-gap-fill"></i> บนการ์ดไปวางในแชท หรือคลิกเพื่อคัดลอกข้อความ / รูปการ์ด / แชร์ — ดูรายละเอียดที่คู่มือเมนูลูกจ้าง ข้อ 11
</div>
<div class="manual-tip">
    <strong>ผู้ดำเนินการ (ปุ่ม <i class="bi bi-person-badge-fill"></i> มุมขวาล่างของการ์ด):</strong> กดแล้วเลือกผู้ใช้ในระบบ หรือเลือก "ผู้ยื่นภายนอก (พิมพ์ชื่อเอง)" แล้วพิมพ์ชื่อ หรือเลือก "ไม่ระบุ" เพื่อล้าง — ทำงานเหมือนกันในมติลงทะเบียน มติต่ออายุ (ทุกแถบ) Pre-Production และ Workflow · ชื่อที่พิมพ์เองแสดงต่อท้ายว่า (ภายนอก) · การเลือกผู้ดำเนินการไม่เปลี่ยนสถานะของการ์ด
</div>

<div class="manual-warn">
    <strong>ระวัง:</strong> งานที่ส่งไป Workflow แล้ว แก้ไขใน Production ไม่ได้ — ต้องไปแก้ใน Workflow
</div>

<h4><i class="bi bi-question-circle me-2"></i>คำถามที่พบบ่อย</h4>
<dl>
    <dt>Q: ทำไมไม่เห็นปุ่ม "Send to Workflow"?</dt>
    <dd>A: role ของคุณไม่มีสิทธิ์ approve-production — ติดต่อ Admin ให้เพิ่มสิทธิ์</dd>

    <dt>Q: งานหายไปไหน หลังกด Send to Workflow?</dt>
    <dd>A: ย้ายไปอยู่ในเมนู "Workflow" — กรองด้วยชื่อนายจ้างก็เจอ</dd>

    <dt>Q: ติ๊กขั้นตอนเตรียมงานไม่ได้?</dt>
    <dd>A: บัญชีนั้นยังไม่มีสิทธิ์ "อัปเดตขั้นตอนความคืบหน้า" — ให้ Admin เปิดสิทธิ์ที่เมนูจัดการผู้ใช้</dd>

    <dt>Q: ลูกจ้างที่ลาออกระหว่างทำงาน Production?</dt>
    <dd>A: เปิดการ์ดลูกจ้าง → กด "ลาออก" — งานจะถูกถอดออกจาก Production อัตโนมัติ</dd>
</dl>

<div class="manual-tip">
    <strong>ข้อมูลบนการ์ดลูกจ้าง:</strong> ใต้ชื่อลูกจ้างแสดงรายละเอียดสูงสุด 6 รายการ ชุดเดียวกับการ์ดในเมนูข้อมูลลูกจ้าง (Super Admin เลือกและจัดลำดับได้ที่ ตั้งค่า Super Admin → แท็บ "ข้อมูลบนการ์ดลูกจ้าง") · สัญชาติแสดงเสมอ · แต่ละรายการมี <strong>ปุ่มคัดลอก</strong> <i class="bi bi-copy"></i> กดครั้งเดียวคัดลอกได้เลย ไม่ต้องลากคลุมข้อความ · แก้ข้อมูลลูกจ้างแล้วการ์ดอัปเดตทันที
</div>

<div class="manual-tip">
    <strong>สีการ์ดงาน:</strong> แถบสีด้านซ้ายและแสงเรืองบอกสถานะ — สีหลักของแบรนด์ = กำลังเตรียม, เขียว = เสร็จแล้ว, เทา = ยกเลิก · ชี้เมาส์แล้วการ์ดยกขึ้นพร้อมเงาสี
</div>
