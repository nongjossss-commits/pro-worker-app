{{-- User Manual: Ticket Inbox (Chinese) --}}

<h4><i class="bi bi-inbox-fill me-2"></i>这个菜单是做什么的?</h4>
<p>
    <strong>"工单收件箱(Ticket Inbox)"</strong> 菜单保存雇主提出的<strong>请求/问题反馈</strong> ——
    例如申请证明文件、报告雇员缺勤、申请修改数据。
    办公室用它来追踪哪些请求尚未回复
</p>

<h4><i class="bi bi-person-check me-2"></i>谁可以进入?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> —— 可以进入(需拥有 <code>manage-tickets</code> 权限)</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>页面外观</h4>
<ol>
    <li><strong>工单列表</strong> —— 显示所有工单，按最新排序</li>
    <li><strong>状态筛选</strong> —— 待回复 / 处理中 / 已关闭</li>
    <li><strong>对话(Messages)</strong> —— 打开工单后可查看往来消息</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>使用步骤</h4>

<h5>回复工单</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>点击列表中的某个工单</li>
        <li>阅读客户的请求内容</li>
        <li>在消息框中输入回复内容</li>
        <li>如需要，可附上文件</li>
        <li>点击"发送" —— 客户将收到通知</li>
    </ol>
</div>

<h5>关闭工单</h5>
<div class="manual-step">
    处理完成后 → 点击"关闭工单" → 状态将变更为"已关闭"
</div>

<h4><i class="bi bi-lightbulb me-2"></i>使用小贴士</h4>

<div class="manual-tip">
    <strong>快速回复:</strong> 客户会更满意 —— 通常目标是在 24 小时内回复
</div>
