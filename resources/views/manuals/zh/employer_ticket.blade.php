{{-- User Manual: Employer Ticket (Employer side) (Chinese) --}}

<h4><i class="bi bi-envelope-paper-fill me-2"></i>这个菜单是做什么的?</h4>
<p>
    <strong>"问题反馈 / 提交请求(Employer Ticket)"</strong> 菜单供<strong>雇主</strong>
    (<span class="manual-role">Employer</span> 角色)使用，用于向办公室反馈问题/提交请求 ——
    例如申请雇用证明、报告雇员缺勤、申请修改数据
</p>

<h4><i class="bi bi-person-check me-2"></i>谁可以进入?</h4>
<ul>
    <li><span class="manual-role">Employer</span> —— 可以创建 + 查看自己的工单</li>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> —— 可以查看 + 回复(通过 Ticket Inbox)</li>
</ul>

<h4><i class="bi bi-list-check me-2"></i>使用步骤(雇主端)</h4>

<h5>创建新工单</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>点击"+ 提交新请求"</li>
        <li>选择类型(申请证明文件、反馈问题等)</li>
        <li>输入详细内容</li>
        <li>可附上文件/照片</li>
        <li>点击"发送" —— 办公室会收到并在 Ticket Inbox 中回复</li>
    </ol>
</div>

<h5>追踪状态</h5>
<div class="manual-step">
    工单列表会显示"待回复"、"处理中"、"已关闭"等状态 ——
    点击工单即可查看办公室的回复内容
</div>

<h4><i class="bi bi-lightbulb me-2"></i>使用小贴士</h4>

<div class="manual-tip">
    <strong>附上照片/文件:</strong> 有助于更清楚地说明问题 —— 工作人员可以更准确地回复
</div>
