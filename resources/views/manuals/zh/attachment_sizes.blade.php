{{-- User Manual: Attachment File Sizes (ZH) --}}

<h4><i class="bi bi-hdd-stack-fill me-2"></i>这个菜单是做什么的?</h4>
<p>
    <strong>"附件文件大小"</strong>（位于"通知"下、"重复数据"之后）列出<strong>10 MB 及以上</strong>的已上传文件，
    并显示文件属于谁、在哪个栏位 —— 例如单页护照扫描件却有 12 MB，清晰度远超所需 ——
    以便重新上传较小的文件，节省存储空间。
</p>

<h4><i class="bi bi-person-check me-2"></i>谁可以进入?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span></li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>页面外观</h4>
<ol>
    <li><strong>大小选择</strong> —— 显示 5 / 10 / 20 / 50 MB 以上的文件（默认 10 MB）及"重新扫描"按钮</li>
    <li><strong>汇总卡片</strong> —— 大文件数量、占用空间、系统中所有文件、扫描时间</li>
    <li><strong>已附加到记录的文件</strong> —— 文件名、大小、图片分辨率（px）、所属（雇员/雇主/… 及名称）、栏位（如 文件 1. 护照）</li>
    <li><strong>未关联任何记录的文件</strong> —— 例如系统生成的下载文件</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>使用步骤</h4>
<div class="manual-step">
    <ol class="mb-0">
        <li>打开"附件文件大小"，检查列表</li>
        <li>点击 <i class="bi bi-eye"></i> 打开文件，判断是否需要如此清晰</li>
        <li>若不需要，点击 <i class="bi bi-pencil"></i> 打开编辑页面，在同一栏位上传较小的文件</li>
        <li>点击"重新扫描"再次检查（扫描结果保留 10 分钟）</li>
    </ol>
</div>

<h4><i class="bi bi-lightbulb me-2"></i>使用小贴士</h4>
<div class="manual-tip">
    照片或单页扫描件长边约 2000 px（小于 1 MB）即可清晰阅读。
</div>
<div class="manual-warn">
    此页面<strong>不会删除任何文件</strong> —— 仅供检查的报告。请在该记录的编辑页面更换文件。
</div>
