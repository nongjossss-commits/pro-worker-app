{{-- User Manual: Delegates (Chinese) --}}

<h4><i class="bi bi-people me-2"></i>这个菜单是做什么的?</h4>
<p>
    <strong>"授权代表(Delegates)"</strong> 菜单用于保存
    <strong>雇主指派</strong>负责与我们公司联系的人员信息 ——
    例如客户公司的 HR、秘书，或在现场负责管理劳工的负责人
</p>
<p>
    <strong>重要说明:</strong> 部分角色的左侧菜单中可能显示为"员工信息"，
    但实际上就是这个 Delegates 菜单 —— <strong>并非外籍劳工</strong>
</p>

<h4><i class="bi bi-person-check me-2"></i>谁可以进入这个菜单?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> —— 可以进入</li>
    <li><span class="manual-role">Caretaker</span> —— 仅可查看</li>
    <li><span class="manual-role">Employer</span> —— 只能查看自己的</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>页面外观</h4>
<ol>
    <li><strong>授权代表表格</strong> —— 姓名、所属雇主、职位、电话、邮箱</li>
    <li><strong>"+ 新增授权代表"</strong> 按钮 —— 创建 delegate</li>
    <li><strong>筛选器</strong> —— 按雇主筛选，按姓名/电话搜索</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>使用步骤</h4>

<h5>1. 新增授权代表</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>点击"+ 新增授权代表"</li>
        <li>选择雇主</li>
        <li>填写姓名、职位、电话、邮箱、地址</li>
        <li>如有，上传身份证复印件</li>
        <li>点击"保存"</li>
    </ol>
</div>

<h5>2. 编辑信息</h5>
<div class="manual-step">
    点击表格中该代表的姓名 → 编辑 → 保存
</div>

<h5>3. 删除授权代表</h5>
<div class="manual-step">
    点击该行的垃圾桶图标 —— 系统会要求确认
</div>

<h4><i class="bi bi-lightbulb me-2"></i>使用小贴士</h4>

<div class="manual-tip">
    <strong>Delegate ≠ Employee:</strong> Delegate = 代表雇主进行联系的人员(HR、秘书)，
    Employee = 实际在现场工作的外籍雇员
</div>

<div class="manual-tip">
    <strong>1 个雇主 = 多个 delegate:</strong> 一个雇主可能有多名 HR 人员、采购团队等
</div>

<h4><i class="bi bi-question-circle me-2"></i>常见问题</h4>
<dl>
    <dt>Q: 为什么菜单中把 Delegate 显示为"员工信息"?</dt>
    <dd>A: 因为在"Employer"角色下，客户会看到这个名称的菜单 —— 是为了让客户更容易理解</dd>

    <dt>Q: 一位授权代表可以关联多个雇主吗?</dt>
    <dd>A: 不可以 —— 一条 delegate 记录对应一个雇主，如果同一人为多家公司工作，需要分别创建多条记录</dd>
</dl>
