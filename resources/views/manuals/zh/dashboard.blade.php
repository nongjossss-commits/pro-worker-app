<h4><i class="bi bi-speedometer2 me-2"></i>这个菜单是做什么的?</h4>
<p>
    <strong>"仪表板 (Dashboard)"</strong> 是登录后看到的第一个页面。
    显示系统总览 —— 雇主数量、雇员数量、正在进行的工作、即将到期的项目、重要通知。
</p>

<h4><i class="bi bi-person-check me-2"></i>谁可以进入这个菜单?</h4>
<p>拥有 <code>view-dashboard</code> 权限的任何角色 —— 通常除特殊角色外所有人都可以</p>

<h4><i class="bi bi-layout-text-window me-2"></i>页面各部分</h4>
<ol>
    <li><strong>品牌色页头</strong> —— 日期、更新时间与重点数字:近 12 个月完成 · 国籍数 · 有进行中工作的标签 · 近 14 天操作</li>
    <li><strong>关键数字卡片</strong> —— 在职员工 · 雇主 · 进行中 · 本月完成(较上月)· 未来 7 天的预约 · 15 天内到期的 90 天报到 · 30 天内到期的证件 —— <strong>将鼠标悬停在卡片上</strong>可查看明细与统计方式</li>
    <li><strong>每月完成工作</strong>(12 个月，按 Workflow / 登记决议 / 续期决议)与每月<strong>新增员工与离职对比</strong>(含净变化)</li>
    <li><strong>各标签进行中的工作</strong> —— 点击柱条即可打开该标签 · <strong>按国籍划分的员工</strong></li>
    <li><strong>证件到期概况</strong>(签证 / 工作证 / 护照:已过期 · 30 · 60 · 90 天)· <strong>员工最多的前 8 个雇主</strong></li>
    <li><strong>系统活动(14 天)</strong>与<strong>最近操作</strong></li>
</ol>
<p class="small">在职员工 = 未报离职、未删除且不在取消状态 · 预约 = 登记 / 续期决议及 Workflow 中尚未标记完成的预约 · <strong>仪表板不显示财务数字</strong>(收入 / 未收款),因为所有能进入仪表板的账户都能看到 —— 请在财务菜单查看 · 所有数字仅涵盖该账户可查看的雇主 · 支持浅色/深色模式与 4 种语言</p>

<h4><i class="bi bi-shield-lock me-2"></i>登录与安全</h4>
<ol>
    <li>用邮箱和密码<strong>登录</strong>(点击眼睛图标可显示输入的密码)</li>
    <li><strong>记住我</strong>在该设备上记住<strong>邮箱</strong>;若也想自动填写密码,请在浏览器询问时点"保存密码"</li>
    <li><strong>关闭浏览器 / 应用 = 需重新登录</strong>;程序页面全部关闭超过 5 分钟(如手机应用长时间在后台)会自动登出 —— 防止在他人设备上忘记登出</li>
    <li>刷新页面或在新标签页打开程序可照常使用</li>
    <li><strong>忘记密码:</strong>点"忘记密码?" → 填写邮箱 → 60 分钟内打开邮件中的链接(多次申请时只有最新邮件的链接有效)</li>
    <li><strong>设置了密码的菜单</strong>(如财务)需输入菜单密码;解锁后在使用期间 30 分钟内保持可用</li>
</ol>

<h4><i class="bi bi-circle-half me-2"></i>显示模式(浅色 / 深色)</h4>
<ol>
    <li>模式按钮位于顶部栏、语言按钮之后 —— 共 3 种:<strong>浅色</strong>、<strong>深色</strong>、<strong>跟随设备</strong>(默认)</li>
    <li>切换立即生效,无需刷新;正在填写的内容不会丢失,其他已打开的标签页也会同步切换</li>
    <li><strong>跟随设备:</strong>使用设备上设置的模式(例如夜间自动变暗的手机 —— 程序会立即跟随)</li>
    <li>所选模式<strong>按设备分别记住</strong> —— 电脑和手机可以使用不同的模式</li>
    <li>打印时始终为白色背景,即使正在使用深色模式</li>
</ol>

<h4><i class="bi bi-lightbulb me-2"></i>使用小贴士</h4>

<div class="manual-tip">
    <strong>每天早上检查:</strong> 仪表板会告诉你今天有什么需要处理的事项，再开始工作。
</div>

<div class="manual-tip">
    <strong>悬停查看详情:</strong> 将鼠标指向数字卡片或图表即可立即看到明细，无需进入菜单 · 在"各标签进行中的工作"中点击柱条即可打开该标签
</div>

<div class="manual-tip">
    <strong>在手机上:</strong> 所有菜单的列表表格（雇主、进口商、中介、用户、设置、Labor 等）每行显示为一张卡片 —— 第一行为名称，每个值旁标注列名，查看/编辑/删除按钮在卡片底部，无需左右滑动 · 「全选」位于卡片上方 · 会计报表/账簿/报表仍为可左右滑动的表格 · 电脑上显示为普通表格
</div>
