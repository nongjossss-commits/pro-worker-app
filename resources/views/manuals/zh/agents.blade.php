{{-- User Manual: Agents (Chinese) --}}

<h4><i class="bi bi-briefcase-fill me-2"></i>这个菜单是做什么的?</h4>
<p>
    <strong>"劳务中介(Agents)"</strong> 菜单用于保存<strong>为雇主介绍业务的中介</strong>信息。
    有些雇主不会直接联系我们公司，而是通过担任协调人/顾问角色的 Agent。
    用于追踪某项业务来自哪位 Agent，以及需支付给他们的佣金
</p>

<h4><i class="bi bi-person-check me-2"></i>谁可以进入这个菜单?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> —— 可以进入</li>
    <li><span class="manual-role">Caretaker</span> —— 仅可查看</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>页面外观</h4>
<ol>
    <li><strong>Agent 表格</strong> —— 姓名、电话、邮箱、所管理的雇主数量</li>
    <li><strong>"+ 新增 Agent"</strong> 按钮</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>使用步骤</h4>

<h5>1. 新增 Agent</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>点击"+ 新增 Agent"</li>
        <li>填写姓名、电话、邮箱、地址</li>
        <li>如有约定，填写佣金信息</li>
        <li>如有，上传相关文件(Agent 合同)</li>
        <li>点击"保存"</li>
    </ol>
</div>

<h5>2. 将 Agent 关联至雇主</h5>
<div class="manual-step">
    前往"雇主"菜单 → 编辑该雇主 → 选择 Agent → 保存
</div>

<h4><i class="bi bi-lightbulb me-2"></i>使用小贴士</h4>

<div class="manual-tip">
    <strong>Agent 与 Importer 的区别:</strong> Agent = 泰国雇主的代表，Importer = 从国外引入劳工的公司
</div>

<h4><i class="bi bi-question-circle me-2"></i>常见问题</h4>
<dl>
    <dt>Q: 一位 Agent 可以关联多个雇主吗?</dt>
    <dd>A: 可以 —— 通常一位 Agent 会管理多家公司</dd>
</dl>
