{{-- User Manual: Activity Logs (Chinese) --}}

<h4><i class="bi bi-journal-text me-2"></i>这个菜单是做什么的?</h4>
<p>
    <strong>"操作日志(Activity Logs)"</strong> 菜单记录系统中发生的<strong>每一项变更</strong> ——
    谁做了什么、何时做的，用于<strong>审计与核查</strong>，
    例如谁删除了这位雇主、谁修改了价格、谁更改了雇员状态
</p>

<h4><i class="bi bi-person-check me-2"></i>谁可以进入?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> —— 可以进入</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>页面外观</h4>
<ol>
    <li><strong>筛选器</strong> —— 按日期、用户、操作类型(新增 / 修改 / 删除)筛选</li>
    <li><strong>历史记录表格</strong> —— 日期时间、用户、操作、被修改的项目</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>使用步骤</h4>

<h5>查询谁修改了什么</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>选择日期范围(起-止)</li>
        <li>如需要，选择用户</li>
        <li>选择操作类型</li>
        <li>点击"搜索" —— 表格将只显示符合条件的记录</li>
    </ol>
</div>

<h5>按姓名或任意编号搜索</h5>
<div class="manual-step">
    首页和每日页面的搜索框可搜索雇员/雇主的<strong>姓名</strong>及<strong>各类编号</strong>：
    RA 编号（outsource）、护照、工作证、粉卡、申请编号、身份编号、参考编号、社保号、税号
    —— 也包括<strong>录入或修改该编号当天</strong>的记录。
</div>

<h5>阅读变更内容</h5>
<div class="manual-step">
    <ul class="mb-0">
        <li>"详细说明"以句子呈现，例如 <em>修改雇员 Somchai（编号 128）的资料 —— 2 项</em></li>
        <li>"变更内容"直接显示前 3 项，例如 <em>护照号：由 A123 改为 B456</em>、<em>在"文件 1. 护照"栏附加文件</em>、<em>文件由"2. 签证"栏移至"其他文件 1"栏</em> —— 点击"查看全部"查看完整列表</li>
        <li>文件名可点击打开（若文件仍存在）· 密码不显示具体值，只显示"修改了密码"</li>
        <li>记录范围：雇员、雇主、中介、进口公司、授权代表及用户账号</li>
    </ul>
</div>

<h5>登录 / 退出跟踪</h5>
<div class="manual-step">
    <ul class="mb-0">
        <li><strong>登录成功</strong>与<strong>登录失败</strong>（密码错误 —— 显示所用邮箱，不保存密码）</li>
        <li><strong>退出登录</strong>（自己点击）或<strong>系统自动退出</strong>（关闭浏览器/应用，或超过 5 分钟未打开程序）</li>
        <li>"IP / 设备"显示浏览器和设备，例如 <em>Chrome · Windows</em>、<em>Safari · iPhone</em></li>
    </ul>
</div>

<h4><i class="bi bi-lightbulb me-2"></i>使用小贴士</h4>

<div class="manual-tip">
    <strong>审计即证据:</strong> 操作日志可作为法律证据使用 —— 系统不会自动删除
</div>
