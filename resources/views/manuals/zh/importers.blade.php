{{-- User Manual: Importers (Chinese) --}}

<h4><i class="bi bi-globe2 me-2"></i>这个菜单是做什么的?</h4>
<p>
    <strong>"劳务进口代理公司(Importers)"</strong> 菜单用于保存
    <strong>输出国</strong>(缅甸、老挝、柬埔寨)那些负责将劳工送来泰国的公司信息。
    用于追踪某位雇员来自哪家 Importer，并处理相关的国际贸易文件
</p>

<h4><i class="bi bi-person-check me-2"></i>谁可以进入这个菜单?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> —— 可以进入</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>页面外观</h4>
<ol>
    <li><strong>Importer 表格</strong> —— 公司名称、国家、地址、联系人</li>
    <li><strong>"+ 新增 Importer"</strong> 按钮</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>使用步骤</h4>

<h5>1. 新增 Importer</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>点击"+ 新增 Importer"</li>
        <li>填写公司名称(泰文/英文)、国家、地址</li>
        <li>填写主要联系人、电话、邮箱</li>
        <li>附上该 Importer 的执照/资质证明文件</li>
        <li>点击"保存"</li>
    </ol>
</div>

<h5>2. 将雇员关联至 Importer</h5>
<div class="manual-step">
    打开雇员资料 → "Importer" 栏位 → 从下拉菜单中选择
</div>

<h4><i class="bi bi-lightbulb me-2"></i>使用小贴士</h4>

<div class="manual-tip">
    <strong>Importer 位于输出国:</strong> 在 MOU 续签时扮演重要角色，因为需要与大使馆协调相关文件
</div>

<h4><i class="bi bi-question-circle me-2"></i>常见问题</h4>
<dl>
    <dt>Q: 雇员可以没有 Importer 吗?</dt>
    <dd>A: 可以 —— 已在系统中存在很久的旧雇员，可能没有关联 Importer 信息</dd>
</dl>
