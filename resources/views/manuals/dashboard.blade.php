<h4><i class="bi bi-speedometer2 me-2"></i>เมนูนี้คืออะไร?</h4>
<p>
    <strong>"แดชบอร์ด (Dashboard)"</strong> คือหน้าแรกที่ login เข้ามาเจอ
    แสดงภาพรวมของระบบ — จำนวนนายจ้าง, ลูกจ้าง, งานที่กำลังทำ, รายการที่ใกล้หมดอายุ, แจ้งเตือนสำคัญ
</p>

<h4><i class="bi bi-person-check me-2"></i>ใครเข้าได้?</h4>
<p>ทุก role ที่มีสิทธิ์ <code>view-dashboard</code> — ปกติทุกคนยกเว้น role พิเศษ</p>

<h4><i class="bi bi-layout-text-window me-2"></i>ส่วนต่างๆ ของหน้า</h4>
<ol>
    <li><strong>การ์ดสรุปสถิติ</strong> — ตัวเลขสำคัญ (นายจ้างทั้งหมด, ลูกจ้างที่ active, งานที่ทำอยู่)</li>
    <li><strong>กราฟแสดงแนวโน้ม</strong> — รายเดือน/รายไตรมาส (ถ้ามี)</li>
    <li><strong>รายการเร่งด่วน</strong> — งานที่ใกล้ครบกำหนด, แจ้งเตือนที่ต้องดำเนินการ</li>
    <li><strong>ลิงก์ลัด</strong> — ไปยังเมนูที่ใช้บ่อย</li>
</ol>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>

<div class="manual-tip">
    <strong>เช็คทุกเช้า:</strong> Dashboard บอกว่ามีอะไรที่ต้องดำเนินการวันนี้ ก่อนเริ่มงาน
</div>

<div class="manual-tip">
    <strong>คลิกการ์ด:</strong> การ์ดสถิติทุกใบคลิกได้ — พาไปดูรายละเอียดของเมนูนั้น
</div>
