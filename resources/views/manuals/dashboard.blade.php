<h4><i class="bi bi-speedometer2 me-2"></i>เมนูนี้คืออะไร?</h4>
<p>
    <strong>"แดชบอร์ด (Dashboard)"</strong> คือหน้าแรกที่ login เข้ามาเจอ
    แสดงภาพรวมของระบบ — จำนวนนายจ้าง, ลูกจ้าง, งานที่กำลังทำ, รายการที่ใกล้หมดอายุ, แจ้งเตือนสำคัญ
</p>

<h4><i class="bi bi-person-check me-2"></i>ใครเข้าได้?</h4>
<p>ทุก role ที่มีสิทธิ์ <code>view-dashboard</code> — ปกติทุกคนยกเว้น role พิเศษ</p>

<h4><i class="bi bi-layout-text-window me-2"></i>ส่วนต่างๆ ของหน้า</h4>
<ol>
    <li><strong>แถบหัวสีแบรนด์</strong> — วันที่ เวลาอัปเดต และตัวเลขเด่น: เสร็จสิ้นใน 12 เดือน · จำนวนสัญชาติ · แท็บที่มีงานค้าง · การทำงานใน 14 วัน</li>
    <li><strong>การ์ดตัวเลขสำคัญ</strong> — ลูกจ้างปัจจุบัน · นายจ้าง · กำลังดำเนินการ · เสร็จสิ้นเดือนนี้ (เทียบเดือนที่แล้ว) · นัดหมายใน 7 วันข้างหน้า · รายงานตัว 90 วัน ภายใน 15 วัน · เอกสารหมดอายุใน 30 วัน — <strong>ชี้เมาส์ที่การ์ด</strong> เพื่อดูรายละเอียดแยกย่อยและวิธีนับ</li>
    <li><strong>กราฟงานที่เสร็จสิ้นรายเดือน</strong> (12 เดือน แยก Workflow / มติจดทะเบียน / มติต่ออายุ) และ <strong>ลูกจ้างเข้าใหม่ เทียบ แจ้งออก</strong> รายเดือน พร้อมยอดเพิ่ม/ลดสุทธิ</li>
    <li><strong>งานที่กำลังดำเนินการแยกตามแท็บ</strong> — คลิกแท่งกราฟเพื่อเปิดแท็บนั้นได้ทันที · <strong>ลูกจ้างแยกตามสัญชาติ</strong></li>
    <li><strong>เอกสารที่จะหมดอายุ</strong> (วีซ่า / ใบอนุญาตทำงาน / พาสปอร์ต: หมดอายุแล้ว · 30 · 60 · 90 วัน) · <strong>นายจ้างที่มีลูกจ้างมากที่สุด</strong> 8 อันดับ</li>
    <li><strong>การใช้งานระบบ 14 วัน</strong> และ <strong>การทำงานล่าสุด</strong></li>
</ol>
<p class="small">ลูกจ้างปัจจุบัน = ยังไม่แจ้งออก ไม่ถูกลบ และไม่ได้อยู่ในสถานะยกเลิก · นัดหมาย = นัดในมติจดทะเบียน / มติต่ออายุ และ Workflow ที่ยังไม่ติ๊กว่าเสร็จ · <strong>แดชบอร์ดไม่แสดงตัวเลขการเงิน</strong> (รายรับ/ยอดค้าง) เพราะทุกบัญชีที่เข้าแดชบอร์ดได้จะเห็น — ดูตัวเลขการเงินที่เมนูการเงิน · ตัวเลขทั้งหมดเห็นเฉพาะนายจ้างที่บัญชีนั้นมีสิทธิ์ดู · ใช้ได้ทั้งโหมดสว่าง/มืด และ 4 ภาษา</p>

<h4><i class="bi bi-shield-lock me-2"></i>การเข้าสู่ระบบและความปลอดภัย</h4>
<ol>
    <li><strong>เข้าสู่ระบบ:</strong> กรอกอีเมลและรหัสผ่าน (กดรูปตาเพื่อดูรหัสที่พิมพ์)</li>
    <li><strong>จดจำฉัน:</strong> จำ<strong>อีเมล</strong>ไว้ในเครื่องนั้น ครั้งหน้ากรอกให้อัตโนมัติ — ถ้าต้องการให้กรอกรหัสผ่านด้วย ให้กด "บันทึกรหัสผ่าน" ที่เบราว์เซอร์ถาม</li>
    <li><strong>ปิดเบราว์เซอร์ / ปิดแอป = ต้องเข้าสู่ระบบใหม่</strong> — และถ้าไม่มีหน้าโปรแกรมเปิดอยู่เลยเกิน 5 นาที (เช่น พับแอปบนมือถือทิ้งไว้) ระบบจะออกจากระบบให้อัตโนมัติ ป้องกันกรณีลืมออกจากระบบบนเครื่องของคนอื่น</li>
    <li>รีเฟรชหน้า หรือเปิดโปรแกรมในแท็บใหม่ ใช้งานต่อได้ตามปกติ</li>
    <li><strong>ลืมรหัสผ่าน:</strong> กด "ลืมรหัสผ่าน?" → กรอกอีเมล → เปิดลิงก์ในอีเมลเพื่อตั้งรหัสใหม่ (ลิงก์ใช้ได้ 60 นาที ถ้ากดขอหลายครั้ง ใช้ได้เฉพาะอีเมลฉบับล่าสุด)</li>
    <li><strong>เมนูที่ตั้งรหัสผ่าน:</strong> บางเมนู (เช่น การเงิน) อาจต้องกรอกรหัสผ่านเมนูก่อน — ปลดล็อกแล้วใช้ได้ต่อเนื่อง 30 นาทีขณะใช้งาน</li>
</ol>

<h4><i class="bi bi-circle-half me-2"></i>โหมดการแสดงผล (สว่าง / มืด)</h4>
<ol>
    <li>ปุ่มโหมดอยู่ที่แถบด้านบน ถัดจากปุ่มเปลี่ยนภาษา — เลือกได้ 3 แบบ: <strong>สว่าง</strong>, <strong>มืด</strong>, <strong>ตามอุปกรณ์</strong> (ค่าเริ่มต้น)</li>
    <li>เปลี่ยนแล้วมีผลทันที ไม่ต้องรีเฟรช งานที่กรอกค้างไว้ไม่หาย และแท็บอื่นที่เปิดอยู่เปลี่ยนตามด้วย</li>
    <li><strong>ตามอุปกรณ์:</strong> ใช้โหมดเดียวกับที่ตั้งไว้ในเครื่อง (เช่น มือถือที่ตั้งให้มืดตอนกลางคืน โปรแกรมจะเปลี่ยนตามทันที)</li>
    <li>ระบบจำค่าที่เลือกไว้<strong>แยกตามเครื่อง</strong> — คอมพิวเตอร์กับมือถือเลือกคนละโหมดได้</li>
    <li>เวลาสั่งพิมพ์ เอกสารออกเป็นพื้นขาวเสมอ แม้กำลังใช้โหมดมืด</li>
</ol>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>

<div class="manual-tip">
    <strong>เช็คทุกเช้า:</strong> Dashboard บอกว่ามีอะไรที่ต้องดำเนินการวันนี้ ก่อนเริ่มงาน
</div>

<div class="manual-tip">
    <strong>ชี้เมาส์ดูรายละเอียด:</strong> ชี้ที่การ์ดตัวเลขหรือกราฟ จะขึ้นรายละเอียดแยกย่อยทันที โดยไม่ต้องเข้าเมนู · กราฟ "งานที่กำลังดำเนินการแยกตามแท็บ" คลิกแท่งเพื่อเปิดแท็บนั้นได้
</div>

<div class="manual-tip">
    <strong>ใช้บนมือถือ:</strong> ตารางรายการทุกเมนู (นายจ้าง บริษัทนำเข้า เอเจนซี่ ผู้ใช้ ตั้งค่า Labor ฯลฯ) จะแสดงเป็นการ์ดทีละรายการ — ชื่ออยู่บรรทัดแรก ข้อมูลแต่ละช่องมีชื่อหัวข้อกำกับ ปุ่มดู/แก้ไข/ลบอยู่ท้ายการ์ด ไม่ต้องเลื่อนซ้าย-ขวา · ช่อง "เลือกทั้งหมด" อยู่เหนือการ์ด · รายงานบัญชี/สมุดบัญชี/งบ ยังเป็นตารางเลื่อนซ้าย-ขวาเหมือนเดิม · คอมพิวเตอร์แสดงเป็นตารางตามปกติ
</div>
