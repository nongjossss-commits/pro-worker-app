<h4><i class="bi bi-speedometer2 me-2"></i>เมนูนี้คืออะไร?</h4>
<p>
    <strong>"แดชบอร์ด (Dashboard)"</strong> คือหน้าแรกที่ login เข้ามาเจอ
    แสดงภาพรวมของระบบ — จำนวนนายจ้าง, ลูกจ้าง, งานที่กำลังทำ, รายการที่ใกล้หมดอายุ, แจ้งเตือนสำคัญ
</p>

<h4><i class="bi bi-person-check me-2"></i>ใครเข้าได้?</h4>
<p>ทุก role ที่มีสิทธิ์ <code>view-dashboard</code> — ปกติทุกคนยกเว้น role พิเศษ</p>

<h4><i class="bi bi-layout-text-window me-2"></i>ส่วนต่างๆ ของหน้า</h4>
<ol>
    <li><strong>การ์ดสรุปสถิติ</strong> — ตัวเลขสำคัญ (นายจ้างทั้งหมด, ลูกจ้างที่ active, งานที่ทำอยู่)</li>
    <li><strong>กราฟแสดงแนวโน้ม</strong> — รายเดือน/รายไตรมาส (ถ้ามี)</li>
    <li><strong>รายการเร่งด่วน</strong> — งานที่ใกล้ครบกำหนด, แจ้งเตือนที่ต้องดำเนินการ</li>
    <li><strong>ลิงก์ลัด</strong> — ไปยังเมนูที่ใช้บ่อย</li>
</ol>

<h4><i class="bi bi-shield-lock me-2"></i>การเข้าสู่ระบบและความปลอดภัย</h4>
<ol>
    <li><strong>เข้าสู่ระบบ:</strong> กรอกอีเมลและรหัสผ่าน (กดรูปตาเพื่อดูรหัสที่พิมพ์)</li>
    <li><strong>จดจำฉัน:</strong> จำ<strong>อีเมล</strong>ไว้ในเครื่องนั้น ครั้งหน้ากรอกให้อัตโนมัติ — ถ้าต้องการให้กรอกรหัสผ่านด้วย ให้กด "บันทึกรหัสผ่าน" ที่เบราว์เซอร์ถาม</li>
    <li><strong>ปิดเบราว์เซอร์ / ปิดแอป = ต้องเข้าสู่ระบบใหม่</strong> — และถ้าไม่มีหน้าโปรแกรมเปิดอยู่เลยเกิน 5 นาที (เช่น พับแอปบนมือถือทิ้งไว้) ระบบจะออกจากระบบให้อัตโนมัติ ป้องกันกรณีลืมออกจากระบบบนเครื่องของคนอื่น</li>
    <li>รีเฟรชหน้า หรือเปิดโปรแกรมในแท็บใหม่ ใช้งานต่อได้ตามปกติ</li>
    <li><strong>ลืมรหัสผ่าน:</strong> กด "ลืมรหัสผ่าน?" → กรอกอีเมล → เปิดลิงก์ในอีเมลเพื่อตั้งรหัสใหม่ (ลิงก์ใช้ได้ 60 นาที ถ้ากดขอหลายครั้ง ใช้ได้เฉพาะอีเมลฉบับล่าสุด)</li>
    <li><strong>เมนูที่ตั้งรหัสผ่าน:</strong> บางเมนู (เช่น การเงิน) อาจต้องกรอกรหัสผ่านเมนูก่อน — ปลดล็อกแล้วใช้ได้ต่อเนื่อง 30 นาทีขณะใช้งาน</li>
</ol>

<h4><i class="bi bi-circle-half me-2"></i>โหมดการแสดงผล (สว่าง / มืด)</h4>
<ol>
    <li>ปุ่มโหมดอยู่ที่แถบด้านบน ถัดจากปุ่มเปลี่ยนภาษา — เลือกได้ 3 แบบ: <strong>สว่าง</strong>, <strong>มืด</strong>, <strong>ตามอุปกรณ์</strong> (ค่าเริ่มต้น)</li>
    <li>เปลี่ยนแล้วมีผลทันที ไม่ต้องรีเฟรช งานที่กรอกค้างไว้ไม่หาย และแท็บอื่นที่เปิดอยู่เปลี่ยนตามด้วย</li>
    <li><strong>ตามอุปกรณ์:</strong> ใช้โหมดเดียวกับที่ตั้งไว้ในเครื่อง (เช่น มือถือที่ตั้งให้มืดตอนกลางคืน โปรแกรมจะเปลี่ยนตามทันที)</li>
    <li>ระบบจำค่าที่เลือกไว้<strong>แยกตามเครื่อง</strong> — คอมพิวเตอร์กับมือถือเลือกคนละโหมดได้</li>
    <li>เวลาสั่งพิมพ์ เอกสารออกเป็นพื้นขาวเสมอ แม้กำลังใช้โหมดมืด</li>
</ol>

