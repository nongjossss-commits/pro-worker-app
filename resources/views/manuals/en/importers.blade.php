{{-- User Manual: Importers (English) --}}

<h4><i class="bi bi-globe2 me-2"></i>What is this menu?</h4>
<p>
    The <strong>"Importers"</strong> menu stores information about companies
    <strong>in the country of origin</strong> (Myanmar, Laos, Cambodia) that send workers into Thailand.
    Used to track which Importer a given employee came from + handle international trade documentation
</p>

<h4><i class="bi bi-person-check me-2"></i>Who can access this menu?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — can access</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>What the page looks like</h4>
<ol>
    <li><strong>Importer table</strong> — company name, country, address, contact person</li>
    <li><strong>"+ Add New Importer"</strong> button</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>How to use it</h4>

<h5>1. Add an Importer</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>Click "+ Add New Importer"</li>
        <li>Fill in the company name (Thai/English), country, address</li>
        <li>Fill in the main contact person, phone number, email</li>
        <li>Attach the Importer's license/certification documents</li>
        <li>Click "Save"</li>
    </ol>
</div>

<h5>2. Link an employee to an Importer</h5>
<div class="manual-step">
    Open the employee's record → the "Importer" field → select from the dropdown
</div>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>

<div class="manual-tip">
    <strong>Importers are based in the country of origin:</strong> they play a key role during MOU renewal, since they must coordinate documents with the embassy
</div>

<h4><i class="bi bi-question-circle me-2"></i>Frequently Asked Questions</h4>
<dl>
    <dt>Q: Can an employee have no Importer set?</dt>
    <dd>A: Yes — older employees who have been in the system for a long time may not have Importer data attached</dd>
</dl>
