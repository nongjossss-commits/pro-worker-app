{{-- User Manual: Incomplete Data (English) --}}

<h4><i class="bi bi-exclamation-diamond-fill me-2"></i>What is this menu?</h4>
<p>
    The <strong>"Incomplete Data"</strong> menu collects <strong>employers/employees</strong>
    whose data in the system is <strong>still missing something</strong> — e.g. no tax ID, no photo, no passport —
    so the office can see them and fill in what's missing
</p>

<h4><i class="bi bi-person-check me-2"></i>Who can access it?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — can access (requires the <code>manage-tickets</code> permission)</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>What the page looks like</h4>
<ol>
    <li><strong>Type tabs</strong> — Employers / Employees</li>
    <li><strong>Table</strong> — shows records missing data + what exactly is missing</li>
    <li><strong>Edit button</strong> — click through to fill in the missing data</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>How to use it</h4>

<h5>Fix missing data</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>Select a type (Employers/Employees)</li>
        <li>Click a record in the table — the system tells you what's missing (e.g. "Missing: tax ID, photo")</li>
        <li>Click "Edit" → the system takes you to that record's edit page</li>
        <li>Fill in the missing data → Save</li>
        <li>Once you go back, the record <strong>disappears from the "Incomplete Data" list</strong></li>
    </ol>
</div>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>

<div class="manual-tip">
    <strong>Check every week:</strong> this menu keeps the system's data complete — so day-to-day work isn't interrupted by missing information
</div>

<div class="manual-tip">
    <strong>Before creating a tax invoice:</strong> check this menu first — if an employer has no tax ID, you can't issue an invoice
</div>
