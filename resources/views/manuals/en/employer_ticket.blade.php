{{-- User Manual: Employer Ticket (Employer side) (English) --}}

<h4><i class="bi bi-envelope-paper-fill me-2"></i>What is this menu?</h4>
<p>
    The <strong>"Report Issue / Send Request (Employer Ticket)"</strong> menu is for <strong>employers</strong>
    (the <span class="manual-role">Employer</span> role) to report issues/send requests to the office —
    e.g. requesting an employment certificate, reporting an absent employee, requesting a data change
</p>

<h4><i class="bi bi-person-check me-2"></i>Who can access it?</h4>
<ul>
    <li><span class="manual-role">Employer</span> — can create + view their own tickets</li>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — can view + reply (via Ticket Inbox)</li>
</ul>

<h4><i class="bi bi-list-check me-2"></i>How to use it (Employer side)</h4>

<h5>Create a new ticket</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>Click "+ Send New Request"</li>
        <li>Select a type (request a certificate, report an issue, etc.)</li>
        <li>Type in the details</li>
        <li>You can attach a file/photo</li>
        <li>Click "Send" — the office will receive it and reply via Ticket Inbox</li>
    </ol>
</div>

<h5>Track the status</h5>
<div class="manual-step">
    The ticket list shows the status "Awaiting Reply", "In Progress", "Closed" —
    click a ticket to see the office's replies
</div>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>

<div class="manual-tip">
    <strong>Attach photos/documents:</strong> makes the issue easier to understand — staff can reply more accurately
</div>
