{{-- User Manual: Ticket Inbox (English) --}}

<h4><i class="bi bi-inbox-fill me-2"></i>What is this menu?</h4>
<p>
    The <strong>"Ticket Inbox"</strong> menu holds <strong>requests/issues</strong> reported by employers —
    e.g. requesting a certificate, reporting an absent employee, requesting a data change.
    The office uses it to track which requests haven't been answered yet
</p>

<h4><i class="bi bi-person-check me-2"></i>Who can access it?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — can access (requires the <code>manage-tickets</code> permission)</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>What the page looks like</h4>
<ol>
    <li><strong>Ticket list</strong> — shows all tickets, newest first</li>
    <li><strong>Status filter</strong> — Awaiting Reply / In Progress / Closed</li>
    <li><strong>Conversation (Messages)</strong> — opening a ticket shows the back-and-forth messages</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>How to use it</h4>

<h5>Reply to a ticket</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>Click a ticket in the list</li>
        <li>Read the customer's request</li>
        <li>Type your reply in the message box</li>
        <li>You can attach a file (if needed)</li>
        <li>Click "Send" — the customer will be notified</li>
    </ol>
</div>

<h5>Close a ticket</h5>
<div class="manual-step">
    Once resolved → click "Close Ticket" → status changes to "Closed"
</div>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>

<div class="manual-tip">
    <strong>Reply quickly:</strong> customers appreciate fast responses — the usual target is within 24 hours
</div>
