{{-- User Manual: Attachment File Sizes (EN) --}}

<h4><i class="bi bi-hdd-stack-fill me-2"></i>What is this menu?</h4>
<p>
    <strong>"Attachment File Sizes"</strong> (under Notifications, after "Duplicate Records") lists uploaded files of <strong>10 MB or more</strong>
    and shows whose file it is and which slot it is in — e.g. a one-page passport scan of 12 MB that is far more detailed than needed —
    so you can re-upload a smaller copy and save storage space.
</p>

<h4><i class="bi bi-person-check me-2"></i>Who can access it?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span></li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>What the page looks like</h4>
<ol>
    <li><strong>Size selector</strong> — show files from 5 / 10 / 20 / 50 MB (default 10 MB) and a "Scan again" button</li>
    <li><strong>Summary cards</strong> — number of large files, space they use, all uploaded files, scan time</li>
    <li><strong>Attached to records</strong> — file name, size, image resolution (px), attached to (employee/employer/… and name), slot (e.g. File 1. Passport)</li>
    <li><strong>Not linked to any record</strong> — large files no record points to, e.g. generated downloads</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>How to use it</h4>
<div class="manual-step">
    <ol class="mb-0">
        <li>Open "Attachment File Sizes" and review the list</li>
        <li>Press <i class="bi bi-eye"></i> to open the file and judge whether it needs to be that detailed</li>
        <li>If not, press <i class="bi bi-pencil"></i> to open the edit page and upload a smaller file into the same slot</li>
        <li>Press "Scan again" to check again (results are kept for 10 minutes)</li>
    </ol>
</div>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>
<div class="manual-tip">
    <strong>A sensible size:</strong> a photo or one-page scan at about 2000 px on the long side (under 1 MB) is clear enough to read.
</div>
<div class="manual-warn">
    This page <strong>never deletes files</strong> — it is a report only. Replace a file from that record's edit page.
</div>
