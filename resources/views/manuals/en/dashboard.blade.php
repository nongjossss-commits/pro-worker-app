{{-- User Manual: Dashboard --}}

<h4><i class="bi bi-speedometer2 me-2"></i>What is this menu?</h4>
<p>
    <strong>"Dashboard"</strong> is the first page you see after logging in.
    It shows an overview of the system — number of employers, employees, jobs in progress, items nearing expiry, and important notifications.
</p>

<h4><i class="bi bi-person-check me-2"></i>Who can access it?</h4>
<p>Any role with the <code>view-dashboard</code> permission — normally everyone except special roles</p>

<h4><i class="bi bi-layout-text-window me-2"></i>Page sections</h4>
<ol>
    <li><strong>Brand-colour header</strong> — date, update time and highlight figures: finished in 12 months · nationalities · tabs with work in progress · actions in 14 days</li>
    <li><strong>Key figure cards</strong> — workforce · employers · in progress · finished this month (vs last month) · appointments in the next 7 days · 90-day reports due in 15 days · documents expiring in 30 days — <strong>hover a card</strong> for its breakdown and how it is counted</li>
    <li><strong>Work finished per month</strong> (12 months, Workflow / Registration / Renewal resolution) and <strong>new employees vs notified out</strong> per month with the net change</li>
    <li><strong>Work in progress by tab</strong> — click a bar to open that tab · <strong>workforce by nationality</strong></li>
    <li><strong>Document expiry outlook</strong> (visa / work permit / passport: expired · 30 · 60 · 90 days) · <strong>top 8 employers by workforce</strong></li>
    <li><strong>System activity (14 days)</strong> and <strong>recent activities</strong></li>
</ol>
<p class="small">Workforce = not notified out, not deleted and not in a cancelled status · appointments = Registration / Renewal resolution and Workflow appointments not marked done · <strong>the dashboard shows no finance figures</strong> (income / outstanding) because every account with the dashboard sees it — see them in the Finance menu · all figures cover only the employers that account may see · works in light/dark mode and all 4 languages</p>

<h4><i class="bi bi-shield-lock me-2"></i>Login and security</h4>
<ol>
    <li><strong>Log in</strong> with email and password (click the eye to show what you typed)</li>
    <li><strong>Remember me</strong> remembers the <strong>email</strong> on that device; to have the password filled in too, click "Save password" when the browser asks</li>
    <li><strong>Closing the browser / app = log in again</strong>; if no page of the program is open for more than 5 minutes (e.g. the phone app left in the background) you are signed out automatically — protects against forgetting to log out on someone else's device</li>
    <li>Refreshing or opening the program in a new tab keeps working normally</li>
    <li><strong>Forgot password:</strong> "Forgot your password?" → email → open the link within 60 minutes (only the newest email's link works)</li>
    <li><strong>Password-protected menus</strong> (e.g. Finance) ask for the menu password; once unlocked it stays open for 30 minutes of activity</li>
</ol>

<h4><i class="bi bi-circle-half me-2"></i>Display mode (light / dark)</h4>
<ol>
    <li>The mode button is in the top bar, right after the language button — 3 choices: <strong>Light</strong>, <strong>Dark</strong>, <strong>Device default</strong> (the default)</li>
    <li>It switches instantly with no refresh; anything you were typing stays, and other open tabs follow</li>
    <li><strong>Device default:</strong> uses the mode set on the device (e.g. a phone that turns dark at night — the program follows straight away)</li>
    <li>The choice is remembered <strong>per device</strong> — a computer and a phone can use different modes</li>
    <li>Printing always comes out on a white background, even in dark mode</li>
</ol>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>

<div class="manual-tip">
    <strong>Check every morning:</strong> the Dashboard tells you what needs attention today, before you start work.
</div>

<div class="manual-tip">
    <strong>Hover for details:</strong> point at a figure card or chart to see its breakdown right away, without opening the menu · in "Work in progress by tab", click a bar to open that tab
</div>

<div class="manual-tip">
    <strong>On a phone:</strong> list tables in every menu (employers, importers, agencies, users, settings, Labor …) show one card per row — the name on the first line, each value with its column name, the view / edit / delete buttons at the bottom of the card, no sideways scrolling · "Select all" sits above the cards · accounting reports / ledgers / statements stay as side-scrolling tables · computers show the normal table
</div>
