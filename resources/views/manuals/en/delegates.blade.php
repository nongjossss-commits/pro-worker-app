{{-- User Manual: Delegates (English) --}}

<h4><i class="bi bi-people me-2"></i>What is this menu?</h4>
<p>
    The <strong>"Delegates"</strong> menu stores information about
    <strong>the people an employer assigns</strong> to be the point of contact with our office —
    e.g. HR staff at the client company, a secretary, or a supervisor who manages workers on-site
</p>
<p>
    <strong>Important note:</strong> in the left menu for some roles, this may be labeled "Employee Info",
    but it is actually this same Delegates menu — <strong>not migrant workers</strong>
</p>

<h4><i class="bi bi-person-check me-2"></i>Who can access this menu?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — can access</li>
    <li><span class="manual-role">Caretaker</span> — view only</li>
    <li><span class="manual-role">Employer</span> — can only view their own</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>What the page looks like</h4>
<ol>
    <li><strong>Delegate table</strong> — name, linked employer, position, phone number, email</li>
    <li><strong>"+ Add New Delegate"</strong> button — creates a delegate</li>
    <li><strong>Filter</strong> — filter by employer, search by name/phone number</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>How to use it</h4>

<h5>1. Add a new delegate</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>Click "+ Add New Delegate"</li>
        <li>Select an employer</li>
        <li>Fill in the full name, position, phone number, email, address</li>
        <li>Upload a copy of their ID card (if available)</li>
        <li>Click "Save"</li>
    </ol>
</div>

<h5>2. Edit information</h5>
<div class="manual-step">
    Click the delegate's name in the table → edit → save
</div>

<h5>3. Delete a delegate</h5>
<div class="manual-step">
    Click the trash icon on the delegate's row — the system will ask for confirmation
</div>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>

<div class="manual-tip">
    <strong>Delegate ≠ Employee:</strong> Delegate = a person representing an employer for contact purposes (HR, secretary),
    Employee = a migrant worker actually working on-site
</div>

<div class="manual-tip">
    <strong>1 employer = many delegates:</strong> one employer may have several HR staff, a purchasing team, etc.
</div>

<h4><i class="bi bi-question-circle me-2"></i>Frequently Asked Questions</h4>
<dl>
    <dt>Q: Why is Delegate labeled "Employee Info" in the menu?</dt>
    <dd>A: Because under the "Employer" role, customers see this menu under that name instead — to make it easier for them to understand from their point of view</dd>

    <dt>Q: Can one delegate be linked to multiple employers?</dt>
    <dd>A: No — one delegate record = one employer. If the same person works for several companies, you need to create a separate record for each</dd>
</dl>
