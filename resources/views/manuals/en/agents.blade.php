{{-- User Manual: Agents (English) --}}

<h4><i class="bi bi-briefcase-fill me-2"></i>What is this menu?</h4>
<p>
    The <strong>"Agents"</strong> menu stores information about <strong>employer agents</strong> who bring in business.
    Sometimes an employer doesn't contact our office directly, but goes through an Agent who acts as their coordinator/consultant.
    Used to track which Agent a job came from + the commission owed to them
</p>

<h4><i class="bi bi-person-check me-2"></i>Who can access this menu?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> <span class="manual-role">Staff</span> — can access</li>
    <li><span class="manual-role">Caretaker</span> — view only</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>What the page looks like</h4>
<ol>
    <li><strong>Agent table</strong> — name, phone number, email, number of employers managed</li>
    <li><strong>"+ Add New Agent"</strong> button</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>How to use it</h4>

<h5>1. Add a new Agent</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>Click "+ Add New Agent"</li>
        <li>Fill in the name, phone number, email, address</li>
        <li>Fill in commission details (if agreed upon)</li>
        <li>Upload documents (Agent contract if available)</li>
        <li>Click "Save"</li>
    </ol>
</div>

<h5>2. Link an Agent to an employer</h5>
<div class="manual-step">
    Go to the "Employers" menu → edit the employer → select the Agent → Save
</div>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>

<div class="manual-tip">
    <strong>Agent vs Importer:</strong> Agent = a representative for a Thai employer, Importer = a company that imports labor from abroad
</div>

<h4><i class="bi bi-question-circle me-2"></i>Frequently Asked Questions</h4>
<dl>
    <dt>Q: Can one Agent be linked to multiple employers?</dt>
    <dd>A: Yes — an Agent typically manages several companies</dd>
</dl>
