<h4><i class="bi bi-people-fill me-2"></i>เมนูนี้คืออะไร?</h4>
<p>
    เมนู <strong>"ข้อมูลลูกจ้าง"</strong> คือฐานข้อมูลแรงงานต่างด้าว (พม่า/ลาว/กัมพูชา) ที่อยู่ในการดูแลของสำนักงาน
    ใช้เก็บข้อมูลพื้นฐาน (ชื่อ-นามสกุล, สัญชาติ, เลขพาสปอร์ต, วีซ่า, ใบอนุญาตทำงาน, สัญญา MOU)
    และเชื่อมโยงกับ<strong>นายจ้าง</strong>ที่ลูกจ้างทำงานอยู่
</p>

<h4><i class="bi bi-person-check me-2"></i>ใครเข้าเมนูนี้ได้?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> — เข้าได้ทุกอย่าง รวมถึงลาออก/กู้คืน/ลบถาวร</li>
    <li><span class="manual-role">Staff</span> — ดู / เพิ่ม / แก้ไข ได้ ไม่สามารถลบถาวรได้</li>
    <li><span class="manual-role">Caretaker</span> — ดู / เพิ่ม / แก้ไข + ลาออกลูกจ้างได้</li>
    <li><span class="manual-role">Employer</span> — เห็นเฉพาะลูกจ้างของตัวเอง</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>หน้าตาของหน้านี้</h4>
<ol>
    <li><strong>แถบกรอง</strong> ด้านบน — กรองตามสัญชาติ, สถานะวีซ่า, นายจ้าง, ค้นหาด้วยชื่อ/เลขพาสปอร์ต · <strong>ช่องสัญชาติ</strong> มีครบทุกสัญชาติทั่วโลก (4 ภาษา) — พิมพ์บางส่วนเพื่อตัดตัวเลือก (พิมพ์ได้ทั้งไทย/อังกฤษ/พม่า/จีน เช่น "กัม", "japan") หรือกดลูกศร ▾ เพื่อเลื่อนเลือกจากรายการทั้งหมด · คลิกช่องว่าง ๆ จะเห็น "เลือกล่าสุด" 4 รายการที่เบราว์เซอร์นี้เคยเลือก ตามด้วยสัญชาติหลัก (เมียนมา ลาว กัมพูชา เวียดนาม) · <strong>ช่องวันหมดอายุ</strong> (ท้ายแถบกรอง) กรองลูกจ้างที่ใบอนุญาตทำงาน <em>หรือ</em> วีซ่า หมดอายุในวันที่เลือก</li>
    <li><strong>ช่องค้นหา</strong> — พิมพ์ชื่อลูกจ้าง/นายจ้างบางส่วน ระบบจะโชว์รายชื่อที่ตรงให้เลือกทันที (ไม่ต้องพิมพ์ให้ครบ) คลิกเลือกชื่อเพื่อกรองรายการทันที · <strong>คลิกเลือกลูกจ้างจากรายการที่เด้งขึ้นมา = แสดงเฉพาะคนนั้นคนเดียว</strong> แม้มีคนอื่นชื่อซ้ำ (คนละนายจ้าง) · ถ้าพิมพ์แล้วกด Enter โดยไม่เลือก = แสดงทุกคนที่ตรงกับคำที่พิมพ์ · ผลค้นหารวมลูกจ้างที่ถูกแจ้งออก/ยกเลิกทะเบียนด้วย (ตรงกับรายชื่อที่เด้งขึ้นมา)</li>
    <li><strong>ค้นหา 2 ช่อง</strong> — ช่องแรกพิมพ์ได้ทั้งข้อมูลลูกจ้าง (ชื่อ/พาสปอร์ต/เลขต่าง ๆ) นายจ้าง หรือเจ้าของงาน แล้วเลือกจากรายการ: เลือกลูกจ้าง = แสดงเฉพาะคนนั้น, เลือกนายจ้าง = เฉพาะนายจ้างนั้น, เลือกเจ้าของงาน = ทุกนายจ้างภายใต้เจ้าของงานนั้น (พิมพ์แล้วกด Enter = ค้นตามข้อความที่พิมพ์) · ช่องที่สองเปิดเมื่อช่องแรกมีค่า ใช้ค้นต่อให้แคบลงภายในผลของช่องแรก พิมพ์ได้ทุกแบบเหมือนช่องแรก</li>
    <li><strong>แถบสถานะ</strong> — ทำงานอยู่ / ลาออก / หมดสัญญา / ถังขยะ</li>
    <li><strong>คัดกรองตามที่อยู่</strong> — เลือกจังหวัด → อำเภอ/เขต → ตำบล/แขวง ตามที่อยู่ของนายจ้าง (มีให้เลือกเฉพาะที่อยู่ที่มีในรายการตอนนั้น) · เปลี่ยนจังหวัดแล้วอำเภอ/ตำบลเดิมถูกล้างให้ · ค้นหาหรือกรองอย่างอื่นต่อได้โดยตัวกรองที่อยู่ยังอยู่ · เปลี่ยนภาษาเป็นอังกฤษ/อื่น ๆ ชื่อจังหวัด/อำเภอ/ตำบลแสดงเป็นภาษาอังกฤษ (ถ้าบันทึกชื่ออังกฤษไว้) · ใช้แบบเดียวกันในเมนูนายจ้าง, ข้อมูลไม่ครบ, การแจ้งเตือน, Workflow, Pre-Production, มติลงทะเบียน/ต่ออายุ, กลุ่ม/ทีม</li>
    <li><strong>การ์ดลูกจ้าง</strong> — แสดงเป็นตาราง การ์ดขนาดคงที่ทุกใบ เรียงต่อกันเต็มแถวตามความกว้างจอ (จอใหญ่หรือซูมออก = ได้หลายใบต่อแถวขึ้น, ซูมเข้า = น้อยลง, มือถือ 1 ใบ) ข้อความยาวในการ์ด: ชื่อนายจ้างตัดด้วย … แต่ปุ่มแว่นขยายยังอยู่, บรรทัดรายละเอียดขึ้นได้ 2 บรรทัด ชี้เพื่อดูข้อความเต็ม · แต่ละใบมีรูปถ่าย (ธงชาติชิดขอบซ้ายของการ์ด ชื่อสัญชาติอยู่ขวารูป แสดงตามภาษาที่เลือก), ชื่อพร้อมปุ่มแว่นขยาย 🔍 ต่อท้ายชื่อ, นายจ้าง, ข้อมูลรายละเอียดสูงสุด 6 บรรทัด (ค่าเริ่มต้น: เลขพาสปอร์ต, วันหมดอายุพาสปอร์ต, ประเภทใบอนุญาตทำงาน, รายงานตัว 90 วัน — Super Admin เปลี่ยนได้ที่ ตั้งค่า Super Admin → แท็บ "ข้อมูลบนการ์ดลูกจ้าง" เลือกได้สูงสุด 6 รายการและจัดลำดับได้), กล่องสถานะงานที่กำลังดำเนินการ (แสดงได้ 3 ป้าย ข้อความยาวตัดด้วย … ชี้เพื่อดูเต็ม การ์ดไม่ขยาย) และปุ่มต่าง ๆ ด้านล่าง · ช่องติ๊กเลือกอยู่มุมขวาบน · เลือกแสดงหน้าละ 25 / 50 / 100 คนได้ที่ปุ่มมุมขวา — ระบบจำค่าที่เลือกล่าสุดไว้ในเบราว์เซอร์นั้น (รีเฟรชหรือเปิดใหม่ก็ยังเป็นค่าเดิม แต่ละเมนูจำแยกกัน ครั้งแรกเริ่มที่ 100) · แบบเดียวกันในลูกจ้างที่ถูกแจ้งออก, แท็บพนักงานในหน้านายจ้าง และกลุ่มและทีม (เมนู Workflow / มติ ยังเป็นการ์ดแบบเดิม)</li>
    <li><strong>ปุ่ม "+ เพิ่มลูกจ้างใหม่"</strong> และ <strong>"นำเข้าจาก Excel"</strong> ที่มุมบนขวา</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>ขั้นตอนใช้งานที่พบบ่อย</h4>

<h5>1. เพิ่มลูกจ้างทีละคน</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>กด <strong>"+ เพิ่มลูกจ้างใหม่"</strong> ที่มุมบนขวา</li>
        <li>กรอกข้อมูลพื้นฐาน — ชื่อ-นามสกุล (ไทย/อังกฤษ), เพศ, สัญชาติ (พิมพ์ค้นหาหรือเลือกจากรายการได้ทุกสัญชาติ — แบบเดียวกับตัวกรอง), วันเกิด</li>
        <li>กรอกเลข <strong>พาสปอร์ต</strong> + วันหมดอายุ</li>
        <li>เลือก <strong>นายจ้าง</strong> ที่ลูกจ้างทำงานอยู่</li>
        <li>อัพโหลดรูปถ่าย + เอกสาร (สำเนาพาสปอร์ต, วีซ่า, ใบอนุญาตทำงาน) เท่าที่มี</li>
        <li>กด <strong>"บันทึก"</strong></li>
    </ol>
</div>

<div class="manual-tip">
    💡 <strong>หน้าเพิ่ม / แก้ไข / พรีวิวลูกจ้าง แบ่งเป็นแท็บ</strong> — ไม่ต้องเลื่อนหาข้อมูล คลิกแท็บที่ต้องการได้เลย:
    <strong>ข้อมูลส่วนตัว</strong> (รูปถ่าย ชื่อ วันเกิด สัญชาติ เบอร์โทร + ข้อมูลการเข้าสู่ระบบ) · <strong>พาสปอร์ต วีซ่า และใบอนุญาตทำงาน</strong> (พาสปอร์ต + ประเภทหนังสือเดินทางเมื่อเป็นเมียนมา/กัมพูชา วีซ่า วันหมดอายุวีซ่า · ใบอนุญาตทำงานเรียง ประเภทใบอนุญาต → เลข Work Permit → เลขประจำตัว → เลขบัตรชมพู → วันออก/วันหมดอายุ รายงานตัว 90 วัน เลข RA ตำแหน่งงาน ลักษณะงาน) ·
    <strong>การจ้างงานและประกันสุขภาพ</strong> (วันเริ่มงาน/อายุงาน เลขที่คำขอ เลขผู้เสียภาษี รหัสคนงาน แผนก ธนาคาร · ประกัน) · <strong>ไฟล์แนบ</strong> (ตัวเลข = จำนวนไฟล์ที่แนบแล้ว)
    · <strong>ขนาดช่องกรอกตามชนิดข้อมูล</strong> (อายุ/ส่วนสูงช่องเล็ก วันที่ช่องสั้น ชื่อ/ลักษณะงานช่องยาว) และเรียงต่อกันตามลำดับเต็มความกว้างจอ (ช่องถัดไปขึ้นมาต่อแถวเดิมเมื่อยังมีที่ ไม่เว้นที่ว่าง) — จอใหญ่หรือซูมออกได้หลายช่องต่อแถว ซูมเข้าก็ลดลง ช่องไม่ถูกยืด · รูปถ่ายอยู่มุมขวาบนของแท็บข้อมูลส่วนตัว ทุกหมวดเรียงขึ้นไปข้างรูปไม่เว้นที่ว่าง
    <ul class="mb-0 mt-2">
        <li>ด้านบนเป็น<strong>หัวโปรไฟล์</strong> — รูป ชื่อ นายจ้าง วันเกิด (อายุ) สัญชาติ เลขพาสปอร์ต และป้ายวันหมดอายุ พาสปอร์ต / วีซ่า / Work Permit / รายงานตัว 90 วัน:
            <span class="text-danger">แดง = หมดอายุแล้ว</span> · <span class="text-warning">เหลือง = ใกล้หมด (30 วัน, รายงานตัว 15 วัน)</span> · <span class="text-success">เขียว = ยังไม่หมด</span> · เทา = ยังไม่ได้กรอก</li>
        <li>ปุ่ม <strong>บันทึก</strong> อยู่ล่างจอเสมอ กดได้จากทุกแท็บ — บันทึกข้อมูลทุกแท็บพร้อมกัน</li>
        <li>ถ้ามีช่องที่กรอกไม่ครบหรือผิด ระบบจะเปิดแท็บนั้นให้อัตโนมัติ และแท็บนั้นมี<strong>จุดแดง</strong> · ช่องที่ยังขาด (ไอคอนเหลือง) จะนับเป็นตัวเลขที่แท็บ</li>
        <li>บนมือถือ เลื่อนแถบแท็บซ้าย-ขวาได้</li>
        <li><strong>แท็บไฟล์แนบ</strong> แบ่งเป็น <strong>เอกสารหลัก</strong> (1–8) และ <strong>เอกสารอื่นๆ</strong> (9–18) พร้อมตัวนับ "แนบแล้ว x/y" — แต่ละช่องเป็นการ์ดเล็ก: ขอบเขียว + ป้าย "แนบแล้ว" = มีไฟล์ (ปุ่ม 👁 ดู · PDF · ✏️ แก้ไข) · ปุ่ม <strong>เลือกไฟล์ / เปลี่ยนไฟล์</strong> และ 📷 สแกน/ถ่ายรูป · เลือกไฟล์ใหม่แล้วการ์ดเป็นสีฟ้าพร้อมชื่อไฟล์ (อัปโหลดเมื่อกดบันทึก) · <strong>เอกสารอื่นๆ 9–18</strong>: ชื่อช่องคือชื่อเอกสาร (ค่าเริ่มต้นตามที่ Super Admin ตั้งในตั้งค่า → Attachment Files Settings) กดปุ่ม ✏️ ข้างชื่อเพื่อเปลี่ยนชื่อเฉพาะลูกจ้างคนนี้ (Enter = ตกลง, Esc = ยกเลิก) — ดาวน์โหลด/ส่งออก/แก้ไขขั้นสูงใช้ชื่อกลางที่ Super Admin ตั้ง</li>
        <li><strong>พรีวิว</strong> (ปุ่มแว่นขยาย 🔍): หัวโปรไฟล์และแถบแท็บอยู่กับที่ หน้าต่างไม่ยืด-หดตามข้อมูล — เปลี่ยนแท็บแล้วเฉพาะข้อมูลด้านล่างเลื่อนขึ้นมา (ข้อมูลยาวเลื่อนดูได้ในกรอบ) · พรีวิวนายจ้างใช้แบบเดียวกัน · หน้าต่างพรีวิวลูกจ้างกว้างและสูงเกือบเต็มจอ ข้อมูลเรียงต่อกันเต็มแถวตามความกว้างหน้าต่าง (ช่องสั้นอย่างอายุ/ส่วนสูงกินที่น้อย ช่องยาวอย่างชื่อ/โรงพยาบาลกินที่มากกว่า มือถือ 2 คอลัมน์) · แท็บไฟล์แนบแสดงเป็นกล่องเล็กเรียงกัน — ช่องที่มีไฟล์เป็นสีเขียวพร้อมปุ่ม "ดู" และ "PDF" ช่องที่ยังไม่มีไฟล์เป็นสีจางพร้อมคำว่า "ไม่มีเอกสาร" ชื่อยาวขึ้นได้ 2 บรรทัด ชี้เพื่อดูเต็ม</li>
        <li>ในพรีวิวมีปุ่ม <strong>"แก้ไข"</strong> มุมขวาบน (เฉพาะผู้มีสิทธิ์แก้ไข) — กดแล้วไปหน้าแก้ไข เมื่อบันทึกหรือยกเลิก ระบบพากลับมาหน้าเดิมและเปิดพรีวิวใหม่พร้อมข้อมูลล่าสุด</li>
    </ul>
</div>

<h5>2. นำเข้าลูกจ้างเป็นกลุ่ม (Excel Bulk Import)</h5>
<div class="manual-step">
    เหมาะกับนายจ้างที่มีลูกจ้างเข้ามาทีเดียวหลายคน
    <ol class="mb-0 mt-2">
        <li>กดปุ่ม <strong>"นำเข้าจาก Excel"</strong></li>
        <li>ดาวน์โหลด <strong>"แบบฟอร์ม Template"</strong> ก่อน — ไฟล์ตัวอย่างมีหัวคอลัมน์ที่ระบบต้องการ</li>
