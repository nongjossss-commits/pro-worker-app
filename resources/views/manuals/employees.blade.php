        <li>อัพโหลดไฟล์กลับเข้าระบบ</li>
        <li>ตรวจ <strong>preview</strong> ก่อนยืนยัน — ระบบจะแสดงรายการที่จะเพิ่มและเตือนถ้ามีข้อมูลผิด</li>
        <li>กด <strong>"ยืนยัน"</strong> — ระบบจะเพิ่มทีเดียวทั้งหมด</li>
    </ol>
</div>

<h5>3. ลาออก / หมดสัญญา (Terminate)</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>เปิดการ์ดลูกจ้างที่จะลาออก</li>
        <li>กดปุ่ม <strong>"ลาออก / หมดสัญญา"</strong></li>
        <li>เลือกสาเหตุ + วันที่ลาออก</li>
        <li>กด <strong>"ยืนยัน"</strong> — สถานะจะเปลี่ยนเป็น "ลาออก" และจะไม่นับในโควต้าใช้งาน</li>
    </ol>
    <div class="manual-tip mt-2 mb-0">
        <i class="bi bi-info-circle-fill"></i> <strong>เคล็ดลับ:</strong>
        ลูกจ้างที่ลาออกไม่ได้หายไป — ยังอยู่ในแถบ "ลาออก" สามารถกู้คืนกลับมาทำงานได้ถ้าจ้างใหม่
    </div>
</div>

<h5>4. กู้คืนลูกจ้างที่ลาออก (Reinstate)</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>คลิกแถบสถานะ <strong>"ลาออก"</strong> ด้านบน</li>
        <li>หาลูกจ้างที่ต้องการกู้คืน</li>
        <li>กด <strong>"กลับมาทำงาน"</strong></li>
    </ol>
</div>

<h5>5. ลบลูกจ้างถาวร (Force Delete)</h5>
<div class="manual-warn">
    <strong>เฉพาะ Admin/Super Admin เท่านั้น</strong> — ใช้สำหรับลูกจ้างที่ป้อนผิดหรือซ้ำ ลบแล้ว<strong>ย้อนคืนไม่ได้</strong>
    <br>
    ขั้นตอน: ไปที่แถบ "ถังขยะ" → กดไอคอนลบถาวร → ยืนยัน 2 ครั้ง
</div>

<h5>6. ตรวจข้อมูลลูกจ้างซ้ำ</h5>
<div class="manual-step">
    ทุกช่องทางที่สร้างลูกจ้าง (เมนูนี้, Workflow / Pre-Production, มติลงทะเบียน / ต่ออายุ, นำเข้า Excel, ส่งต่อจากเมนูการขาย)
    จะเทียบเลขพาสปอร์ต / ใบอนุญาตทำงาน / บัตรชมพู / เลขประจำตัว / เลข RA กับลูกจ้างที่มีอยู่ ถ้าตรงกันจะเตือนก่อนบันทึก (เตือน ไม่บล็อก)
    — การนำเข้า Excel และการส่งต่อจากการขายจะให้ติ๊กยืนยัน "นำเข้าต่อ" ก่อน
</div>

<h5>7. ค้นหาเจอลูกจ้างทุกสถานะ</h5>
<div class="manual-step">
    รายการปกติแสดงเฉพาะคนที่ยังทำงานอยู่ แต่เมื่อพิมพ์ค้นหา จะเจอคนที่ถูกแจ้งออก / ยกเลิกการลงทะเบียนด้วย
    พร้อมป้าย <strong>Terminated</strong> / <strong>Registration Cancelled</strong> — ใช้เทียบเมื่อมีคำเตือนข้อมูลซ้ำ
</div>

<h5>8. ย้ายไฟล์แนบของลูกจ้างหลายคน (Super Admin)</h5>
<div class="manual-step">
    เลือกลูกจ้างด้วย checkbox → <strong>ย้ายไฟล์แนบ</strong> → เลือกช่องต้นทาง/ปลายทาง และวิธี: สลับ / ย้ายแล้วลบต้นทาง / รวมเข้าช่อง B (รวมหน้า PDF)
    มีผลเฉพาะคนที่เลือก · Super Admin มอบสิทธิ์นี้ให้ Admin/Staff บางคนได้ที่เมนูจัดการผู้ใช้
</div>

<h5>9. ประเภทใบอนุญาตทำงาน</h5>
<div class="manual-step">
    รายการ "ประเภทใบอนุญาตทำงาน" จัดการโดย Super Admin ที่หน้าตั้งค่า (เพิ่ม / เปลี่ยนชื่อ / เรียงลำดับ) —
    เปลี่ยนชื่อแล้วข้อมูลลูกจ้างเดิมเปลี่ยนตามให้อัตโนมัติ · ประเภทที่ยังมีลูกจ้างใช้อยู่ลบไม่ได้ · ตัวเลือก "อื่นๆ" ยังพิมพ์เองได้
</div>

<h5>10. แต่งรูปถ่ายลูกจ้าง (หน้าต่างครอบรูป)</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li><strong>หมุน / ปรับองศา</strong> — มุมที่ว่างหลังหมุนจะเติมเป็นสีพื้นหลังที่เลือก (ค่าเริ่มต้นสีขาว) ไม่เป็นสีเทา/ดำ</li>
        <li><strong>Auto Face Center Crop</strong> — ตัดกรอบให้ใบหน้าอยู่กึ่งกลางแบบรูปติดบัตร ใช้ได้ทุกเบราว์เซอร์ (ครั้งแรกอาจใช้เวลาสักครู่)</li>
        <li><strong>White BG / Light Blue BG</strong> — ระบบตัดพื้นหลังและเติมสีให้อัตโนมัติ</li>
        <li>ถ้าตัดผิด (เช่น แขนหรือไหล่หายไป) กด <strong>Refine / Edit Mask</strong>:
            <ul>
                <li><strong>เงาภาพเดิม</strong> — แสดงรูปเดิมจาง ๆ ด้านหลัง ให้เห็นส่วนที่ถูกตัดออก</li>
                <li><strong>กู้คืน</strong> — ระบายบนเงาเพื่อเอาส่วนที่ตัดผิดกลับมา · <strong>Erase</strong> — ลบส่วนที่เกิน</li>
                <li><strong>ขอบอัจฉริยะ</strong> (เปิดไว้เป็นค่าเริ่มต้น) — วางจุดกลางแปรงบนส่วนที่ต้องการลบ/กู้ ขอบแปรงล้ำเข้าไปได้ ระบบหยุดที่เส้นขอบให้เอง</li>
                <li><strong>ไม้กายสิทธิ์</strong> — คลิกครั้งเดียวลบพื้นที่สีใกล้เคียงกันทั้งแถบ</li>
                <li>ลูกกลิ้งเมาส์ = ซูม · กด Space ค้าง หรือคลิกขวาค้างแล้วลาก = เลื่อนภาพ · <kbd>[</kbd> <kbd>]</kbd> = ขนาดแปรง · <kbd>Ctrl</kbd>+<kbd>Z</kbd> = ย้อนกลับ</li>
            </ul>
        </li>
        <li>กด <strong>Apply Changes</strong> — รูปจะได้พื้นหลังสีที่เลือกไว้ทันที (ไม่ต้องกดปุ่มพื้นหลังซ้ำ)</li>
    </ol>
</div>

<h5>11. ส่งข้อมูลลูกจ้าง / นายจ้างไปแชท (LINE ฯลฯ)</h5>
<div class="manual-step">
    การ์ดลูกจ้างและนายจ้างมีปุ่ม <i class="bi bi-grid-3x2-gap-fill"></i> (มุมขวาล่างของการ์ด) — มีในเมนูลูกจ้าง, นายจ้าง, การแจ้งเตือน, Pre-Production, มติขึ้นทะเบียน/ต่ออายุ, Workflow, ปฏิทินนัดหมาย, ข้อมูลไม่ครบ และใบงาน
    <ol class="mb-0 mt-2">
        <li><strong>ลาก</strong>ปุ่มไปวางในช่องแชท LINE (บนคอมพิวเตอร์) หรือโปรแกรมอื่น — ได้ข้อความอ่านง่าย เช่น ชื่อ สัญชาติ พาสปอร์ต วันหมดอายุ (ลากไปวางในแชทภายในโปรแกรมยังได้การ์ดแบบเดิม)</li>
        <li><strong>คลิก</strong>ปุ่มเพื่อเปิดเมนู:
            <ul>
                <li><strong>คัดลอกเป็นข้อความ</strong> — แล้วกด <kbd>Ctrl</kbd>+<kbd>V</kbd> ในแชท</li>
                <li><strong>คัดลอกเป็นรูปการ์ด</strong> — ได้รูปการ์ดสีแบรนด์ มีรูปถ่ายและข้อมูล แล้วกด <kbd>Ctrl</kbd>+<kbd>V</kbd> ในแชท</li>
                <li><strong>บันทึกรูปการ์ด</strong> — ได้ไฟล์ PNG ไว้ส่งต่อ</li>
                <li><strong>แชร์…</strong> (มือถือ/แท็บเล็ต) — เปิดเมนูแชร์ของเครื่อง แล้วเลือก LINE ได้เลย</li>
            </ul>
        </li>
        <li>จากเมนูการแจ้งเตือน ข้อความจะมีบรรทัดเหตุผล เช่น "⚠️ วีซ่าหมดอายุ: 28/01/2026 (เกินมา 242 วัน)"</li>
        <li><strong>Admin</strong> เลือกได้ว่าข้อมูลช่องไหนส่งออกได้ — กดปุ่ม <i class="bi bi-grid-3x2-gap-fill"></i> → <strong>ตั้งค่าข้อมูลที่ส่งออก (ลาก/แชร์)</strong> (ชื่อถูกส่งเสมอ)</li>
        <li><strong>ข้อมูลตามเมนู:</strong> เลขคำขอ, วันนัดหมาย, ทีม และหมายเหตุ ดึงจากการ์ดของเมนูที่ส่ง — Workflow / Pre-Production ใช้ของงานนั้น, มติลงทะเบียน / ต่ออายุ ใช้ของแถบนั้น, ส่งจากเมนูลูกจ้างใช้ข้อมูลในฐานข้อมูลลูกจ้าง · ช่องที่ติ๊กไว้แต่ยังไม่มีข้อมูลจะแสดง "-"</li>
        <li>ทุกครั้งที่ส่งข้อมูลออก ระบบบันทึกไว้ใน <strong>ประวัติการกระทำ</strong> (ประเภท "ส่งข้อมูลออก") ว่าใครส่งข้อมูลของใคร ด้วยวิธีไหน</li>
    </ol>
</div>
<div class="manual-warn">
    ข้อมูลที่ส่งเข้า LINE หรือโปรแกรมอื่นแล้ว ระบบควบคุมต่อไม่ได้ (ข้อมูลส่วนบุคคล — PDPA) ส่งเฉพาะให้คนที่เกี่ยวข้อง
</div>

<h4><i class="bi bi-lightbulb me-2"></i>ข้อควรรู้ / Tips</h4>

<div class="manual-tip">
    <strong>โควต้าลูกจ้างสูงสุด:</strong> Super Admin สามารถจำกัดจำนวนลูกจ้างที่ active ได้
    (ตั้งค่าใน Super Admin Settings → ตั้งค่าโควต้า) — ถ้าเต็ม จะเพิ่มลูกจ้างใหม่ไม่ได้
</div>

<div class="manual-tip">
    <strong>ลูกจ้าง vs ผู้แทน (Delegate):</strong> "ข้อมูลพนักงาน" ในเมนูซ้ายของบางบทบาท
    หมายถึง <strong>ผู้แทนนายจ้าง (Delegate)</strong> ไม่ใช่ลูกจ้างแรงงาน — สองอันคนละเมนูกัน
</div>

<div class="manual-tip">
    <strong>วีซ่า/พาสปอร์ตใกล้หมด:</strong> ระบบจะแจ้งเตือนใน <strong>Notifications</strong>
    อัตโนมัติเมื่อใกล้หมดอายุ — เช็คทุกวันเช้า
</div>
<div class="manual-tip">
    <strong>ดาวน์โหลดขั้นสูงแบบรวมเป็น PDF / แยก PDF รายคน:</strong> ไฟล์ PDF ที่สแกนจากเครื่องสแกนหรือแอปมือถือ (รูปแบบ PDF รุ่นใหม่) ระบบแปลงให้ก่อนรวมอัตโนมัติ · ถ้าไฟล์ไหนรวมไม่ได้จริง ๆ ระบบจะแจ้งใน Download Center และในแบบแยกรายคนจะใส่ไฟล์ต้นฉบับไว้ใน ZIP ให้ — แบบ ZIP ได้ไฟล์ต้นฉบับครบเสมอ
</div>
<div class="manual-tip">
    <strong>ดาวน์โหลดลูกจ้างจำนวนมาก:</strong> กดเริ่มแล้วระบบสร้างไฟล์อยู่เบื้องหลัง — Download Center แสดงความคืบหน้า (เช่น "Processing... 120/500") และเริ่มดาวน์โหลดให้เองเมื่อเสร็จ (เปิด Download Center ค้างไว้) · ถ้าปิดไปก่อน กลับมากด Download ในรายการได้ภายใน 24 ชม. · แบบ "รวมเป็น PDF เดียว" ที่ใหญ่มากจนเกินหน่วยความจำของเซิร์ฟเวอร์ ระบบจะแบ่งเป็นหลายไฟล์ PDF ใน ZIP ให้ (เรียงตามลำดับเดิม) แทนการล้ม
</div>

<div class="manual-warn">
    <strong>ก่อนลบลูกจ้างถาวร:</strong> ตรวจให้แน่ใจว่าไม่มีงาน Production / Workflow / ใบกำกับภาษี
    ที่อ้างถึงลูกจ้างคนนี้อยู่
</div>

<h4><i class="bi bi-question-circle me-2"></i>คำถามที่พบบ่อย</h4>

<dl>
    <dt>Q: เพิ่มลูกจ้างไม่ได้ ขึ้นเตือน "เกินโควต้า"?</dt>
    <dd>A: โควต้าระบบเต็มแล้ว — ติดต่อ Super Admin ให้เพิ่มโควต้า หรือลาออกลูกจ้างเก่าที่ไม่ใช้แล้ว</dd>

    <dt>Q: ทำไม Import Excel ขึ้น error?</dt>
    <dd>A: ตรวจหัวคอลัมน์ในไฟล์ Excel ต้องตรงกับ template ที่ดาวน์โหลด — อย่าเปลี่ยนชื่อคอลัมน์</dd>

    <dt>Q: ลูกจ้างย้ายไปอยู่นายจ้างใหม่?</dt>
    <dd>A: แก้ข้อมูลลูกจ้าง → เปลี่ยน "นายจ้าง" เป็นคนใหม่ → บันทึก</dd>

    <dt>Q: เห็นแต่ลูกจ้างของบริษัทเดียว?</dt>
    <dd>A: ถ้าคุณ login ด้วย role "Employer" จะเห็นเฉพาะลูกจ้างของตัวเอง — ต้องใช้ role Admin/Staff ขึ้นไปเพื่อดูทุกคน</dd>
</dl>
