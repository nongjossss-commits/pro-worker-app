<h4><i class="bi bi-cash-coin me-2"></i>เมนูนี้คืออะไร?</h4>
<p>
    เมนู <strong>"การเงิน (Finance)"</strong> เป็นศูนย์รวมระบบบัญชี/การเงินของสำนักงาน
    รวมทั้ง การวางบิลและรับชำระ (ศูนย์รวมการเงิน), ใบลดหนี้ (Credit Note), สมุดบัญชี (Ledger), ใบกำกับภาษี (Tax Invoice), การออกใบหัก ณ ที่จ่าย (WHT),
    รายงานภาษี (ภ.พ.30, ภ.ง.ด.3/53), การปรับยอดธนาคาร (Bank Reconciliation) และ Audit Log
</p>

<h4><i class="bi bi-person-check me-2"></i>ใครเข้าเมนูนี้ได้?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> — เข้าได้เต็มที่</li>
    <li><span class="manual-role">Staff</span> — เข้าได้บางส่วน (ขึ้นกับสิทธิ์ <code>manage-finance</code>)</li>
    <li><span class="manual-role">Caretaker</span> <span class="manual-role">Employer</span> — ไม่มีสิทธิ์</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>ส่วนต่างๆ ของเมนูการเงิน</h4>
<ol>
    <li><strong>Ledger (สมุดบัญชี)</strong> — บันทึกรายรับ-รายจ่ายทั้งหมด แยกตามวันที่</li>
    <li><strong>Tax Invoices (ใบกำกับภาษี)</strong> — สร้าง/ดู/พิมพ์ใบกำกับภาษี + ช่องทางชำระเงิน</li>
    <li><strong>WHT (หัก ณ ที่จ่าย)</strong> — บันทึก WHT 3%/5% รับมา + ออกเอกสาร</li>
    <li><strong>Tax Reports</strong> — ภ.พ.30 + ภ.ง.ด.3/53 — สรุปประจำเดือนสำหรับยื่นภาษี</li>
    <li><strong>Bank Reconciliation</strong> — ปรับยอดบัญชีธนาคารกับรายการในระบบ</li>
    <li><strong>Audit Log</strong> — ดูประวัติการแก้ไขข้อมูลการเงินทั้งหมด</li>
    <li><strong>Monthly Bundle</strong> — ดาวน์โหลด ZIP รวมเอกสารปิดสิ้นเดือน</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>ขั้นตอนใช้งานที่พบบ่อย (บัญชีและภาษี)</h4>

<h5>1. บันทึกรายรับใหม่</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>เข้า Ledger → กด "+ บันทึกรายการ"</li>
        <li>เลือก "รายรับ"</li>
        <li>กรอกวันที่, ลูกค้า, จำนวนเงิน, ประเภท VAT</li>
        <li>แนบ slip ภาพ (ถ้ามี)</li>
        <li>กด "บันทึก"</li>
    </ol>
</div>

<h5>2. สร้างใบกำกับภาษี</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>เข้า Tax Invoices → กด "+ สร้างใหม่"</li>
        <li>เลือก <strong>โปรไฟล์ผู้ออก</strong> (ออฟฟิศของเรา)</li>
        <li>กรอกชื่อลูกค้า + เลขผู้เสียภาษี + ที่อยู่</li>
        <li>กรอกยอดเงิน + อัตรา VAT (ปกติ 7%)</li>
        <li>ติ๊กช่องทางการชำระเงิน (เงินสด, โอน, PromptPay)</li>
        <li>ถ้าเลือก "โอน" — เลือกบัญชีธนาคารจากโปรไฟล์</li>
        <li>กด "Save & Issue" — ระบบจะ lock เลขที่ใบ + generate PDF</li>
    </ol>
</div>

<h5>3. ออกรายงานภาษีรายเดือน</h5>
<div class="manual-step">
    เข้า Tax Reports → เลือกเดือน → ดาวน์โหลด ภ.พ.30 หรือ ภ.ง.ด.3/53
</div>

<h5>4. ปรับยอดธนาคาร</h5>
<div class="manual-step">
    เข้า Bank Reconciliation → upload statement ธนาคาร → ระบบจะ match กับรายการในระบบให้
</div>

<h5>5. ปิดสิ้นเดือน (Monthly Bundle)</h5>
<div class="manual-step">
    เข้า Monthly Bundle → เลือกเดือน → กด "Generate" → ดาวน์โหลด ZIP รวมเอกสารทั้งหมดของเดือน
</div>

<h4><i class="bi bi-wallet2 me-2"></i>ศูนย์รวมการเงิน — วางบิลและรับชำระ</h4>

<h5>6. หน้าภาพรวม และการ์ดสถิติ (กดเพื่อกรองได้)</h5>
<div class="manual-step">
    การ์ด 4 ใบด้านบน:
    <ul>
        <li><strong>รายรับวันนี้ / รายรับเดือนนี้</strong> — เงินที่<strong>รับจริง</strong>ในวัน/เดือนนั้น นับตามวันที่รับเงินของแต่ละครั้ง
            (บิลที่จ่ายเดือนก่อนบางส่วนและจ่ายที่เหลือเดือนนี้ จะนับแยกเดือนถูกต้อง ไม่ซ้ำ ไม่ปน)</li>
        <li><strong>ยอดที่รอดำเนินการ</strong> — ยอดคงค้างของบิลที่ยังไม่จ่ายหรือจ่ายไม่ครบ</li>
        <li><strong>ยอดค้างชำระเกินกำหนด</strong> — ยอดคงค้างของบิลที่ถูกตั้งสถานะเกินกำหนด</li>
    </ul>
    <strong>กดที่การ์ด</strong> = แสดงเฉพาะบิลที่รวมเป็นตัวเลขนั้น (กดซ้ำเพื่อยกเลิก) · การ์ดรายรับจะแสดงรายการรับเงินใต้ช่อง "ชำระแล้ว"
    — ตัวหนา = รับในช่วงนั้น, สีจาง = รับในช่วงอื่น · กล่องสรุปผลการกรองแสดงยอด "รับชำระในช่วงนี้" เท่ากับตัวเลขบนการ์ด
    ใบเสนอราคาไม่ถูกนับในยอดเหล่านี้
</div>

<h5>7. บิลมาจากเมนูไหน — ป้ายที่มา และตัวกรองที่มา</h5>
<div class="manual-step">
    ใต้ชื่อนายจ้าง/โครงการมีป้ายบอกที่มา เช่น <code>Workflow › ต่ออายุ MOU</code>, <code>มติต่ออายุ › แถบ X</code>, <code>บิล Manual</code> ·
    ถ้าแถบงานต้นทางถูกลบไปแล้ว ป้ายเป็น<strong>สีแดง</strong> "แถบถูกลบแล้ว" พร้อมวันที่ — บิลยังเป็นยอดจริง ยังเก็บเงินต่อหรือออกใบลดหนี้ได้ ·
    ตัวกรอง <strong>"ที่มา"</strong>: ทุกที่มา / จากแถบที่ใช้งานอยู่ / จากแถบที่ถูกลบแล้ว · ถ้ามีบิลค้างจากแถบที่ถูกลบ จะมีแถบแจ้งเตือนสีแดงพร้อมปุ่มดูบิลเหล่านั้น
</div>

<h5>8. แท็บตามเมนูงาน</h5>
<div class="manual-step">
    แท็บ <strong>Workflow และ Pre Production</strong>, <strong>มติลงทะเบียน</strong>, <strong>มติต่ออายุ</strong> แสดงยอดรวม/วางบิลแล้ว/คงค้าง ของแต่ละนายจ้าง
    กด <strong>จัดการการเงิน</strong> เพื่อเปิดหน้าต่างตั้งราคา วางบิล และรับชำระ ·
    แท็บ <strong>บิลที่สร้างเอง</strong> และ <strong>ใบเสนอราคา</strong> แยกกัน — ประวัติใบเสนอราคาไม่ปนกับบิลจริง
</div>

<h5>9. รับชำระเงิน (Payment History)</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>เปิดบิล → ปุ่มรับชำระ → กรอก <strong>ยอด</strong>, <strong>วันที่รับเงิน</strong>, <strong>บัญชีที่รับเงิน</strong>, แนบสลิป (ถ้ามี)</li>
        <li>รับหลายงวดได้ — สถานะบิลเปลี่ยนเป็น "ชำระบางส่วน" / "ชำระแล้ว" อัตโนมัติ (หักใบลดหนี้ด้วย)</li>
        <li>ไม่ได้เลือกบัญชี → ระบบถามยืนยันก่อนบันทึก เพราะยอดนี้จะ<strong>ไม่ลงยอดคงเหลือของบัญชีธนาคาร</strong></li>
        <li>รายการรับเงินที่เลือกบัญชี จะถูกบันทึกลงสมุดบัญชี (Ledger) ตามวันที่รับเงิน</li>
    </ol>
</div>

<h5>10. ใบลดหนี้ (Credit Note)</h5>
<div class="manual-step">
    ใช้ลดยอดของบิลที่ออกไปแล้ว เช่น ลดราคา หรือยกเลิกยอดที่เหลือที่ไม่เก็บ:
    <ol class="mb-0">
        <li>เมนู <strong>ใบลดหนี้</strong> → <strong>สร้างใบลดหนี้</strong> → เลือกบิล กรอกยอดและเหตุผล (บันทึกเป็นฉบับร่าง)</li>
        <li><strong>ออกใบลดหนี้</strong> — ล็อกเลขที่เอกสาร และลดยอดคงค้างของบิลทันที</li>
        <li>ออกผิด → <strong>Void</strong> ยอดของบิลกลับเป็นเหมือนเดิม · ฉบับร่างลบได้</li>
        <li>ใบลดหนี้รวมอยู่ในไฟล์สรุปประจำเดือนด้วย</li>
    </ol>
</div>

<h5>11. สร้างบิลด้วยตนเอง</h5>
<div class="manual-step">
    เลือก <strong>ประเภทเอกสาร</strong> ก่อน: <strong>ใบเสนอราคา</strong> (ไม่บังคับเลือกนายจ้าง) หรือ <strong>ใบแจ้งหนี้</strong> (ต้องเลือกนายจ้าง) ·
    เพิ่ม <strong>ลูกจ้างฉบับร่าง</strong> ได้ (กรอกชื่อ/สัญชาติ/พาสปอร์ต/รูป โดยไม่สร้างข้อมูลลูกจ้างจริง — ใช้กับบิล manual เท่านั้น) ·
    ใบเสนอราคาเลือกได้ว่าจะ <strong>แสดงยอดรวม</strong> หรือแสดงเฉพาะราคาต่อหน่วย · เอกสารทุกใบมีหมายเหตุอัตรา VAT/WHT ตามที่ตั้งค่าไว้
</div>

<h5>12. รายงานประจำเดือน</h5>
<div class="manual-step">
    ปุ่ม <strong>รายงานประจำเดือน</strong> → เลือกเดือน/ผู้ออกบิล → ดาวน์โหลด ZIP (CSV + สลิป + เอกสาร WHT) ·
    รายรับแสดง <strong>1 แถวต่อการรับเงิน 1 ครั้ง</strong> ตามวันที่รับจริง — บิลที่จ่ายหลายเดือนจะแยกอยู่ในรายงานของแต่ละเดือน ·
    ยอดหัก ณ ที่จ่ายของบิลแสดงครั้งเดียวในแถวของการชำระงวดสุดท้าย · ไม่รวมใบเสนอราคา
</div>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>

<div class="manual-tip">
    <strong>VAT 7%:</strong> เป็น default ของไทย ปัดเศษ 2 ตำแหน่ง
</div>

<div class="manual-tip">
    <strong>WHT 3% vs 5%:</strong> 3% = ค่าบริการทั่วไป, 5% = ค่าเช่าทรัพย์/บุคคล
</div>

<div class="manual-warn">
    <strong>ใบกำกับภาษีที่ Issued แล้ว แก้ไม่ได้:</strong> ตามกฎหมายห้ามแก้ — ต้อง void แล้วออกใบใหม่
</div>

<h4><i class="bi bi-question-circle me-2"></i>คำถามที่พบบ่อย</h4>
<dl>
    <dt>Q: ไม่เห็นช่องเลือกบัญชีธนาคาร?</dt>
    <dd>A: ต้องสร้างบัญชีในโปรไฟล์การเงินก่อน — ไปที่ Financial Profiles → เลือกโปรไฟล์ → เพิ่มบัญชี</dd>

    <dt>Q: เลขใบกำกับภาษีต่อเนื่องไหม?</dt>
    <dd>A: ต่อเนื่อง — ระบบรัน number ต่อจากใบล่าสุดในปีภาษีเดียวกันเสมอ ห้ามขาด</dd>

    <dt>Q: ลบใบกำกับภาษีที่ออกผิดได้ไหม?</dt>
    <dd>A: <strong>Void</strong> ได้ ลบจริงๆ ไม่ได้ — เลขใบยังเก็บไว้ในระบบเพื่อรักษาลำดับ</dd>

    <dt>Q: "รายรับวันนี้" ไม่เท่ากับยอด "ชำระแล้ว" ของบิล?</dt>
    <dd>A: ถูกต้อง — การ์ดนับเฉพาะเงินที่รับในวันนั้นจริง ส่วนช่อง "ชำระแล้ว" ของบิลเป็นยอดสะสมทุกงวด กดการ์ดเพื่อดูรายการรับเงินของแต่ละบิล</dd>

    <dt>Q: ลูกค้าไม่จ่ายส่วนที่เหลือแล้ว จะปิดบิลอย่างไร?</dt>
    <dd>A: ออก <strong>ใบลดหนี้</strong> เท่ากับยอดที่เหลือ — บิลจะเป็น "ชำระแล้ว" และยอดคงค้างเป็น 0 โดยประวัติการรับเงินเดิมยังอยู่ครบ</dd>

    <dt>Q: บิลมีป้ายสีแดง "แถบถูกลบแล้ว"?</dt>
    <dd>A: แถบงานที่สร้างบิลถูกลบไปแล้ว แต่บิลเป็นยอดจริงที่ยังอยู่ — ตัดสินใจว่าจะเก็บเงินต่อ หรือออกใบลดหนี้ปิดยอดที่เหลือ</dd>
</dl>
