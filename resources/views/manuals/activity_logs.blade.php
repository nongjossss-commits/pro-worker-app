<h4><i class="bi bi-journal-text me-2"></i>เมนูนี้คืออะไร?</h4>
<p>
    เมนู <strong>"ประวัติการกระทำ (Activity Logs)"</strong> บันทึก<strong>ทุกการเปลี่ยนแปลง</strong>
    ที่เกิดขึ้นในระบบ ใครทำอะไร เมื่อไหร่ ใช้สำหรับ <strong>audit + ตรวจสอบ</strong>
    เช่น ใครลบนายจ้างคนนี้ ใครแก้ราคา ใครเปลี่ยนสถานะลูกจ้าง
</p>

<h4><i class="bi bi-person-check me-2"></i>ใครเข้าได้?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> — เข้าได้</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>หน้าตาของหน้านี้</h4>
<ol>
    <li><strong>ตัวกรอง</strong> — ตามวันที่, ผู้ใช้, ประเภทกิจกรรม (create / update / delete)</li>
    <li><strong>ตารางประวัติ</strong> — วันเวลา, ผู้ใช้, การกระทำ, รายการที่ถูกแก้</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>ขั้นตอนใช้งาน</h4>

<h5>ค้นหาว่าใครแก้อะไร</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>เลือกช่วงวันที่ (จาก-ถึง)</li>
        <li>เลือกผู้ใช้ (ถ้าต้องการ)</li>
        <li>เลือกประเภทกิจกรรม</li>
        <li>กด "ค้นหา" — ตารางจะแสดงเฉพาะที่ตรง</li>
    </ol>
</div>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>

<div class="manual-tip">
    <strong>Audit คือหลักฐาน:</strong> Activity Log ใช้เป็นหลักฐานทาง legal ได้ — ระบบไม่ลบให้อัตโนมัติ
</div>
