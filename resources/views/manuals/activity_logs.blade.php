{{-- User Manual: Activity Logs --}}

<h4><i class="bi bi-journal-text me-2"></i>เมนูนี้คืออะไร?</h4>
<p>
    เมนู <strong>"ประวัติการกระทำ (Activity Logs)"</strong> บันทึก<strong>ทุกการเปลี่ยนแปลง</strong>
    ที่เกิดขึ้นในระบบ ใครทำอะไร เมื่อไหร่ ใช้สำหรับ <strong>audit + ตรวจสอบ</strong>
    เช่น ใครลบนายจ้างคนนี้ ใครแก้ราคา ใครเปลี่ยนสถานะลูกจ้าง
</p>

<h4><i class="bi bi-person-check me-2"></i>ใครเข้าได้?</h4>
<ul>
    <li><span class="manual-role">Super Admin</span> <span class="manual-role">Admin</span> — เข้าได้</li>
</ul>

<h4><i class="bi bi-layout-text-window me-2"></i>หน้าตาของหน้านี้</h4>
<ol>
    <li><strong>ตัวกรอง</strong> — ตามวันที่, ผู้ใช้, ประเภทกิจกรรม (create / update / delete)</li>
    <li><strong>ตารางประวัติ</strong> — วันเวลา, ผู้ใช้, การกระทำ, รายการที่ถูกแก้</li>
</ol>

<h4><i class="bi bi-list-check me-2"></i>ขั้นตอนใช้งาน</h4>

<h5>ค้นหาว่าใครแก้อะไร</h5>
<div class="manual-step">
    <ol class="mb-0">
        <li>เลือกช่วงวันที่ (จาก-ถึง)</li>
        <li>เลือกผู้ใช้ (ถ้าต้องการ)</li>
        <li>เลือกประเภทกิจกรรม</li>
        <li>กด "ค้นหา" — ตารางจะแสดงเฉพาะที่ตรง</li>
    </ol>
</div>

<h5>ค้นหาด้วยชื่อหรือเลขต่าง ๆ</h5>
<div class="manual-step">
    ช่องค้นหาด้านบนของหน้าแรก และช่องค้นหาในหน้ารายวัน ค้นได้ทั้ง<strong>ชื่อ</strong> และ<strong>เลขทุกชนิด</strong>ของลูกจ้าง/นายจ้าง:
    เลข RA (outsource), พาสปอร์ต, ใบอนุญาตทำงาน, บัตรชมพู, เลขที่คำขอ, เลขประจำตัว, เลขอ้างอิง, เลขประกันสังคม, เลขผู้เสียภาษี
    — รวมถึงรายการในวันที่มีการ<strong>กรอกหรือแก้เลขนั้น</strong>
</div>

<h5>อ่านรายการเปลี่ยนแปลง</h5>
<div class="manual-step">
    <ul class="mb-0">
        <li>ช่อง "รายละเอียด" เขียนเป็นประโยค เช่น <em>แก้ไขข้อมูลลูกจ้าง Somchai (รหัส 128) — 2 รายการ</em></li>
        <li>ช่อง "ข้อมูลการเปลี่ยนแปลง" แสดง 3 รายการแรกทันที เช่น <em>เลขพาสปอร์ต: จาก A123 เป็น B456</em>, <em>แนบไฟล์ในช่อง ไฟล์ 1. พาสปอร์ต</em>, <em>ย้ายไฟล์จากช่อง 2. วีซ่า ไปช่อง เอกสารอื่นๆ 1</em> — กด "ดูทั้งหมด" เพื่อดูครบ</li>
        <li>ชื่อไฟล์กดเปิดดูได้ (ถ้าไฟล์ยังอยู่) · รหัสผ่านไม่แสดงค่า แสดงแค่ว่า "เปลี่ยนรหัสผ่าน"</li>
        <li>บันทึกครอบคลุม ลูกจ้าง, นายจ้าง, ตัวแทน, บริษัทนำเข้า, ผู้แทน และบัญชีผู้ใช้</li>
    </ul>
</div>

<h5>ติดตามการเข้า / ออกระบบ</h5>
<div class="manual-step">
    <ul class="mb-0">
        <li><strong>เข้าสู่ระบบสำเร็จ</strong> และ <strong>เข้าสู่ระบบไม่สำเร็จ</strong> (รหัสผ่านผิด — แสดงอีเมลที่ใช้ ไม่เก็บรหัสผ่าน)</li>
        <li><strong>ออกจากระบบ</strong> (กดออกเอง) หรือ <strong>ระบบออกจากระบบให้อัตโนมัติ</strong> (ปิดเบราว์เซอร์/แอป หรือไม่ได้เปิดโปรแกรมเกิน 5 นาที)</li>
        <li>ช่อง "IP / Device" บอกเบราว์เซอร์และอุปกรณ์ เช่น <em>Chrome · Windows</em>, <em>Safari · iPhone</em></li>
    </ul>
</div>

<h4><i class="bi bi-lightbulb me-2"></i>Tips</h4>

<div class="manual-tip">
    <strong>Audit คือหลักฐาน:</strong> Activity Log ใช้เป็นหลักฐานทาง legal ได้ — ระบบไม่ลบให้อัตโนมัติ
</div>
<div class="manual-tip">
    <strong>ส่งข้อมูลออก:</strong> ทุกครั้งที่มีคนลากการ์ดลูกจ้าง/นายจ้างไปวางในโปรแกรมอื่น (เช่น LINE) คัดลอกข้อความ คัดลอก/บันทึกรูปการ์ด หรือแชร์ จะมีรายการประเภท "ส่งข้อมูลออก (ลาก/คัดลอก/แชร์)" บอกว่าใครส่งข้อมูลของใคร ด้วยวิธีไหน
</div>
